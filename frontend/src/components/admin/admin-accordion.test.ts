import { readFileSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";

/**
 * Свёрнутые секции монетизации: память между заходами и целый первый кадр.
 *
 * Страницы выросли до трёхсот строк разметки подряд. Складывание их в секции
 * само по себе безобидно — опасно то, **как** запоминается раскрытое.
 *
 * Состояние лежит в localStorage, которого на сервере нет. Прочитать его в
 * первом рендере значит нарисовать в браузере не то, что пришло с сервера:
 * React бросает #418 и пересобирает страницу целиком. Это в проекте уже
 * случалось на семнадцати страницах из двадцати одной (разбор — в
 * `docs/hydration.md` и в CLAUDE.md), и правило записано прямо: localStorage
 * читается в `useEffect`, и **запись не начинается раньше чтения**.
 *
 * Тесты ниже сторожат оба правила по исходнику: проверить их прогоном
 * нечем — jsdom в проекте нет, — но нарушение видно в коде однозначно.
 */
const АККОРДЕОН = join(import.meta.dirname, "AdminAccordion.tsx");
const МОНЕТИЗАЦИЯ = join(import.meta.dirname, "AdminMonetizationSection.tsx");

const аккордеон = () => readFileSync(АККОРДЕОН, "utf8");

/** Исходник без комментариев: проверять надо код, а не объяснения к нему. */
function безКомментариев(текст: string): string {
  return текст.replace(/\/\*[\s\S]*?\*\//g, "").replace(/\/\/.*$/gm, "");
}

describe("раскрывающиеся секции админки", () => {
  /**
   * Первый кадр одинаков на сервере и в браузере.
   *
   * Проверяется не «есть useEffect», а то, что в инициализаторе `useState`
   * нет обращения к хранилищу: ровно так расхождение и заводится.
   */
  it("начальное состояние не читает localStorage", () => {
    const текст = аккордеон();

    const инициализатор = текст.slice(
      текст.indexOf("useState<ReadonlySet<string>>"),
      текст.indexOf("const [прочитано"),
    );
    expect(инициализатор, "начальное состояние обязано быть пустым набором").toContain("new Set()");
    expect(
      инициализатор,
      "localStorage в первом рендере разводит разметку с серверной",
    ).not.toMatch(/localStorage/);

    /*
     * И вообще всякое обращение к хранилищу — только внутри эффекта.
     *
     * Сверяется код без комментариев: первая редакция этой проверки поймала
     * собственный docblock компонента, где слово localStorage стоит в
     * объяснении, и объявила нарушение там, где его нет.
     */
    const доЭффекта = безКомментариев(текст).slice(0, безКомментариев(текст).indexOf("useEffect("));
    expect(доЭффекта, "обращение к localStorage до первого useEffect").not.toMatch(/localStorage/);
  });

  /**
   * Запись не начинается раньше чтения.
   *
   * Без этого первый же рендер положил бы пустой набор поверх сохранённого —
   * и выбор человека стёрся бы ровно в тот момент, когда он открыл страницу.
   */
  it("не пишет в хранилище, пока не прочитал", () => {
    const текст = аккордеон();

    const запись = текст.slice(
      текст.indexOf("useEffect(() => {", текст.indexOf("setПрочитано(true)")),
      текст.indexOf("const переключить"),
    );

    expect(запись).toContain("setItem");
    expect(запись, "нет сторожа: запись пойдёт раньше чтения").toMatch(
      /if \(!прочитано\) return;[\s\S]{0,200}setItem/,
    );
  });

  /** Отказ хранилища не роняет страницу: приватное окно, запрет, мусор в JSON. */
  it("чтение и запись обёрнуты в try/catch", () => {
    const текст = аккордеон();

    expect((текст.match(/try \{/g) ?? []).length).toBeGreaterThanOrEqual(2);
    expect((текст.match(/\} catch \{/g) ?? []).length).toBeGreaterThanOrEqual(2);
  });

  /**
   * Открытая однажды секция не снимается при сворачивании.
   *
   * Задание требует «внутри весь текущий функционал без изменений». Снимать
   * содержимое значило бы терять состояние карточки и перезагружать данные
   * на каждое открытие.
   */
  it("содержимое монтируется один раз и дальше прячется стилем", () => {
    const текст = аккордеон();

    expect(текст).toContain("смонтированные");
    expect(текст).toMatch(/hidden=\{!открыта\}/);
    expect(текст, "свёрнутая и ни разу не открытая секция ничего не рисует").toMatch(
      /смонтирована \?/,
    );
  });

  /** Нажатие переключает в обе стороны, и это видно вспомогательным службам. */
  it("кнопка секции объявляет своё состояние", () => {
    const текст = аккордеон();

    expect(текст).toMatch(/aria-expanded=\{открыта\}/);
    expect(текст).toMatch(/aria-controls=/);
    expect(текст, "нет ветки сворачивания").toMatch(/следующий\.delete\(id\)/);
  });

  /** Секции названы так, как просил заказчик, и разложены по вкладкам. */
  it("состав секций на месте", () => {
    const текст = readFileSync(МОНЕТИЗАЦИЯ, "utf8");

    for (const название of [
      "Безопасные сделки",
      "Цены размещения",
      "Тарифы подписки",
      "Надбавка на доставку",
      "Промокоды",
      "Реферальная программа",
      "Платежи и бухгалтерия",
      "Кошельки",
    ]) {
      expect(текст, `нет секции «${название}»`).toContain(`title: "${название}"`);
    }

    // У каждой вкладки свой ключ хранения: иначе раскрытое на одной странице
    // считалось бы раскрытым на другой.
    const ключи = [...текст.matchAll(/storageKey="([^"]+)"/g)].map((m) => m[1]);
    expect(ключи.length).toBeGreaterThanOrEqual(3);
    expect(new Set(ключи).size, "ключи хранения должны быть разными").toBe(ключи.length);
  });

  /**
   * Содержимое секций не переписано.
   *
   * Заказчик просил «внутри весь текущий функционал без изменений», и карточки
   * должны остаться теми же самыми, а не новыми.
   */
  it("карточки внутри — прежние", () => {
    const текст = readFileSync(МОНЕТИЗАЦИЯ, "utf8");

    for (const карточка of [
      "<EscrowProviderAdminCard",
      "<DeliveryMarkupAdminCard",
      "<PromoPoolsAdminCard",
      "<FirstHundredAdminCard",
      "<PromoCodesBlock",
      "<ReferralProgramAdminCard",
      "<LedgerTotalsCard",
      "<AdminBillingOpsCard",
    ]) {
      expect(текст, `карточка пропала: ${карточка}`).toContain(карточка);
    }
  });
});
