import { readFileSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";

/**
 * «Что открывает роль» правится, а не только показывается.
 *
 * До 28.09 матрица рисовала галочки из константы в коде: поменять состав
 * разделов у роли можно было только правкой `AdminAccess::SECTIONS` и
 * выкаткой.
 *
 * Тесты здесь про интерфейс. Главное — что снятый доступ **закрыт на
 * сервере**, а не спрятан в меню — проверяется запросом в
 * `AdminRoleAccessTest`: спрятать пункт и закрыть маршрут в этом коде уже
 * расходились (17.09 заявки сообществ сервер модератору отдавал, а меню
 * прятало), и повторять это на вере нельзя.
 */
const СЕКЦИЯ = join(import.meta.dirname, "AdminRolesSection.tsx");
const КЛИЕНТ = join(import.meta.dirname, "..", "..", "lib", "api", "admin-roles.ts");

const секция = () => readFileSync(СЕКЦИЯ, "utf8");

describe("правка «что открывает роль»", () => {
  it("есть кнопка правки, сохранение и отмена", () => {
    const текст = секция();

    expect(текст, "нет кнопки правки").toMatch(/Редактировать/);
    expect(текст, "нет сохранения").toMatch(/Сохранить/);
    expect(текст, "нет отмены").toMatch(/Отмена/);
    expect(текст, "матрица не вызывает сохранение карты").toContain("saveRoleAccess");
  });

  it("галочки становятся кликабельными именно в режиме правки", () => {
    const текст = секция();

    expect(текст).toContain('type="checkbox"');
    // Показ и правка — разные ветки: вне правки остаются галочки-иконки.
    expect(текст).toMatch(/правим \?[\s\S]{0,400}type="checkbox"/);
  });

  /**
   * Критичные клетки спрашивают подтверждение.
   *
   * Список причин взят из того же места, где `AdminAccess` отказывается
   * выдавать эти ключи отдельному человеку. Здесь он не запрещает, а
   * спрашивает: карту правит Владелец, и решение его — но не молча.
   */
  it("перед критичным изменением спрашивает подтверждение", () => {
    const текст = секция();

    expect(текст).toContain("КРИТИЧНЫЕ");
    const список = текст.slice(
      текст.indexOf("const КРИТИЧНЫЕ"),
      текст.indexOf("function RoleMatrix"),
    );
    // Точечные ключи в объекте записаны в кавычках, простые — без них.
    for (const ключ of ["roles", "settings", "users.manage", "rulesPages", "monetization"]) {
      expect(список, `в списке критичных нет ${ключ}`).toMatch(
        new RegExp(`(^|[\\s"])${ключ.replace(".", "\\.")}"?\\s*:`, "m"),
      );
    }

    /*
     * Ищем вызов после начала обработчика, а не с начала файла: первое
     * вхождение `saveRoleAccess` — в списке импортов, и срез вышел бы пустым.
     * На этом тест и споткнулся с первой попытки.
     */
    const началоСохранения = текст.indexOf("const сохранить = async");
    const сохранение = текст.slice(
      началоСохранения,
      текст.indexOf("saveRoleAccess", началоСохранения),
    );
    expect(сохранение, "сохранение идёт без подтверждения").toContain("askConfirm");
    expect(сохранение, "снятие доступа у Владельца тоже должно спрашивать").toContain("уВладельца");
  });

  /** Запертую клетку нельзя выключить: поле выключено, а не просто серое. */
  it("запертая клетка не переключается", () => {
    const текст = секция();

    expect(текст).toContain("roleAccessLocked");
    expect(текст).toMatch(/disabled=\{locked/);
  });

  /**
   * Правка идёт по копии.
   *
   * Иначе галочки меняли бы то, что пришло с сервера, и «Отмена» было бы
   * нечему отменять — а сохранение уходило бы не тем, что человек видел.
   */
  it("до сохранения ничего не уходит: правка по копии", () => {
    const текст = секция();

    expect(текст).toContain("setКопия");
    const начало = текст.slice(текст.indexOf("const начать ="), текст.indexOf("const заперта ="));
    expect(начало, "копия должна быть глубокой, иначе правится пришедшее с сервера").toContain(
      "{ ...ключи }",
    );
  });

  /** После сохранения сводка перечитывается — «применяется сразу». */
  it("после сохранения сводка перечитывается", () => {
    const текст = секция();

    expect(текст).toContain("onSaved()");
    expect(текст).toMatch(/<RoleMatrix[\s\S]{0,120}onSaved=\{load\}/);
  });

  it("клиент отдаёт карту целиком и получает список изменённых клеток", () => {
    const клиент = readFileSync(КЛИЕНТ, "utf8");

    expect(клиент).toContain("/admin/roles/access");
    expect(клиент).toMatch(/method:\s*"PUT"/);
    expect(клиент).toMatch(/changed:\s*Array<\{/);
  });
});
