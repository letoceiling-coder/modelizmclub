import { readFileSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";

/**
 * Глаз в списке пользователей открывает карточку, а не показывает тост.
 *
 * До 27.09 кнопка вызывала `toast.info` с именем человека и больше ничего:
 * действие выглядело как «посмотреть», а смотреть было нечего. Подпись
 * `previewToast` при этом жила в словаре, то есть заглушка не выглядела
 * заглушкой.
 *
 * Тесты ниже сторожат не вёрстку, а три вещи, которые легко потерять при
 * следующей правке: что окно вообще открывается, что в нём есть то, ради
 * чего его заводили, и что опасные действия спрашивают подтверждение.
 */
const СЕКЦИЯ = join(import.meta.dirname, "AdminUsersSection.tsx");
const КАРТОЧКА = join(import.meta.dirname, "AdminUserCard.tsx");

const секция = () => readFileSync(СЕКЦИЯ, "utf8");
const карточка = () => readFileSync(КАРТОЧКА, "utf8");

describe("карточка пользователя в админке", () => {
  it("глаз открывает карточку, а не показывает тост", () => {
    const текст = секция();

    expect(текст).toContain("setCardUuid(u.uuid)");
    expect(текст, "заглушка previewToast должна была уйти вместе с тостом").not.toContain(
      "previewToast",
    );
    expect(текст, "карточка должна отрисовываться").toContain("<AdminUserCardDialog");
  });

  /**
   * Окно, а не переход.
   *
   * Заказчик просил именно окно: администратор остаётся на своём месте
   * списка и прокрутка не сбрасывается. Переход на отдельный адрес вернул
   * бы его наверх, и после каждого действия пришлось бы долистывать заново.
   */
  it("это окно, а не отдельная страница", () => {
    expect(карточка()).toContain("<Dialog ");
    expect(
      секция(),
      "карточка не должна открываться переходом: список потеряет прокрутку",
    ).not.toMatch(/navigate\(\s*\{\s*to:\s*"\/admin\/users\//);
  });

  /** Всё, что заказчик перечислил, в карточке есть. */
  it("показывает весь перечисленный состав", () => {
    const текст = карточка();

    const обязательное: Array<[string, string]> = [
      ["почта", "card.email"],
      ["телефон", "card.phone"],
      ["город", "card.city"],
      ["дата регистрации", "card.registeredAt"],
      ["последняя активность", "card.lastSeenAt"],
      ["статус", "card.status"],
      ["подтверждён ли телефон", "card.phoneVerified"],
      ["роль", "card.role"],
      ["подписка", "card.subscription"],
      ["запас размещений", "placements"],
      ["счётчики", "counts: c"],
      ["сообщества и каналы", "spaces: s"],
      ["журнал действий", "card.audit"],
    ];

    for (const [что, признак] of обязательное) {
      expect(текст, `в карточке нет: ${что}`).toContain(признак);
    }

    expect(текст, "нет ссылки на публичную страницу").toContain("Открыть профиль пользователя");
    expect(текст, "ссылка должна вести на страницу пользователя").toContain('to="/user/$id"');
  });

  /**
   * Деньги в типе необязательные.
   *
   * Модератору сервер их не присылает вовсе — не нулями, а отсутствием.
   * Если поле станет обязательным, фронт начнёт рисовать «0 ₽» там, где
   * верно «мы этого не показываем», и это будет ложью о человеке.
   */
  it("кошелёк описан как необязательный", () => {
    const клиент = readFileSync(
      join(import.meta.dirname, "..", "..", "lib", "api", "admin.ts"),
      "utf8",
    );

    expect(клиент).toMatch(/wallet\?:\s*\{/);
    expect(клиент).toMatch(/placementGrants\?:/);
  });

  /**
   * Смена роли и подписки спрашивает подтверждение.
   *
   * Оба действия уже стоили живым людям потерь: 24.09 три роли, выданные
   * «на минуту посмотреть», никто не снял; 23.09 подписку обычного человека
   * переключили четыре раза за сорок секунд и забрали у него год доступа.
   * Блокировка и удаление спрашивали и раньше.
   */
  it("роль и подписка меняются только после askConfirm", () => {
    const текст = секция();

    const тело = (имя: string): string => {
      const начало = текст.indexOf(`const ${имя} = async`);
      expect(начало, `не нашёл обработчик ${имя}`).toBeGreaterThan(-1);
      /*
       * Режем по первому вызову, который что-то меняет на сервере: всё, что
       * до него, — это и есть «спросили ли». Перечисление именное, а не
       * «первый await»: в обработчиках есть и чтения, и askText.
       */
      const мутации = [
        "updateAdminUser(",
        "setAdminUserSubscription(",
        "deleteAdminUser(",
        "changeAdminUserListingCredits(",
      ];
      const край =
        мутации
          .map((м) => текст.indexOf(м, начало))
          .filter((i) => i > начало)
          .sort((a, b) => a - b)[0] ?? начало;

      expect(край, `в ${имя} не нашёл вызова, меняющего данные`).toBeGreaterThan(начало);

      return текст.slice(начало, край);
    };

    expect(тело("changeRole"), "смена роли идёт без подтверждения").toContain("askConfirm");
    expect(тело("changeSubscription"), "подписка меняется без подтверждения").toContain(
      "askConfirm",
    );
    expect(тело("toggle"), "блокировка идёт без подтверждения").toContain("askConfirm");
    expect(тело("remove"), "удаление идёт без подтверждения").toContain("askConfirm");
  });

  /**
   * «Кредиты размещения» переименованы.
   *
   * Название не говорило ни что это, ни чем отличается от двух квот, у
   * которых числа похожие. Разбор — в `docs/known-issues.md`.
   */
  it("старое название «кредиты» не осталось в подписях", () => {
    const словарь = readFileSync(
      join(import.meta.dirname, "..", "..", "lib", "i18n", "locales", "ru-admin.ts"),
      "utf8",
    );

    expect(словарь).not.toMatch(/"[^"]*[Кк]редит[^"]*"/);
    expect(словарь).toContain("Размещения в запасе");
  });
});
