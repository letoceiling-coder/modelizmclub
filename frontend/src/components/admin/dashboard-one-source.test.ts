import { readFileSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";

/**
 * Сводку читают одной ручкой — и Владелец, и модератор.
 *
 * До 29.09 `/admin/dashboard` была закрыта владельческим ключом, хотя
 * раздел объявлен модераторским и стоял у модератора в меню. Фронтенд
 * обходил это двумя лишними запросами и собирал объект, где шесть из
 * восьми чисел были нулями.
 *
 * На экране обход не был виден: нулевые карточки и так отфильтрованы по
 * `adminOnly`. Поэтому проверка смотрит не на экран, а на источник —
 * именно он расходился с правами.
 */
const ЭКРАН = join(import.meta.dirname, "AdminDashboardSection.tsx");
const КЛИЕНТ = join(import.meta.dirname, "..", "..", "lib", "api", "admin.ts");

const читать = (путь: string) => readFileSync(путь, "utf8");

describe("источник сводки", () => {
  it("обхода для модератора больше нет", () => {
    expect(читать(КЛИЕНТ), "мёртвая функция-обход осталась").not.toContain(
      "fetchModeratorDashboardStats",
    );
    expect(читать(ЭКРАН), "экран всё ещё зовёт обход").not.toContain(
      "fetchModeratorDashboardStats",
    );
  });

  it("сводка читается одной ручкой, без развилки по роли", () => {
    const экран = читать(ЭКРАН);
    const кусок = экран.slice(экран.indexOf("useEffect"), экран.indexOf("const allStats"));

    expect(кусок, "сводку зовут не для всех").toContain("fetchDashboard()");
    // Журнал действий остаётся владельческим — это другой раздел.
    expect(кусок, "журнал перестал быть владельческим").toContain('role === "owner"');
    expect(кусок, "нулевые числа всё ещё подставляются").not.toContain("usersTotal: 0");
  });
});

/**
 * Сводку видит и модератор — целиком.
 *
 * Флаг `adminOnly` прятал от него четыре карточки из шести, а две
 * величины (активные тарифы и промокоды) сервер считал и не показывал
 * НИКОМУ: карточек для них не было вовсе.
 *
 * Прятать нечего: денег в сводке нет, а разделы, которые считают
 * счётчики, модератору открыты. Владельческим на экране остаётся журнал
 * действий — это отдельный раздел (`auditLog`).
 */
describe("состав сводки", () => {
  const экран = читать(ЭКРАН);

  it("карточки больше не делятся на свои и чужие", () => {
    /*
     * Ищем флаг как код, а не как слово: в разборе выше он назван по
     * имени, и проверка на голое вхождение падала бы на собственном
     * комментарии. Поле объекта — `adminOnly:`, чтение — `.adminOnly`.
     */
    expect(экран, "флаг остался полем карточки").not.toMatch(/adminOnly\s*:/);
    expect(экран, "флаг где-то читается").not.toMatch(/\.adminOnly\b/);
  });

  it("показываются все восемь счётчиков", () => {
    for (const поле of [
      "usersTotal",
      "communitiesTotal",
      "bannersActive",
      "postsTotal",
      "moderationPending",
      "reportsPending",
      "plansActive",
      "promocodesActive",
    ]) {
      expect(экран, `счётчик ${поле} не показывается`).toContain(`data?.${поле}`);
    }
  });

  it("график виден не только Владельцу", () => {
    const график = экран.indexOf("registrationsChart");
    const владелец = экран.indexOf('role === "owner"', экран.indexOf("return ("));

    expect(график).toBeGreaterThan(0);
    // Первая проверка роли в разметке стоит ПОСЛЕ графика — значит график
    // за ней не спрятан. Журнал действий идёт дальше и остаётся за ролью.
    expect(владелец, "график снова заперт за ролью").toBeGreaterThan(график);
  });

  it("журнал действий остаётся владельческим", () => {
    const журнал = экран.indexOf("recentActions");
    const владелец = экран.lastIndexOf('role === "owner"', журнал);

    expect(владелец, "журнал перестал быть владельческим").toBeGreaterThan(0);
  });
});
