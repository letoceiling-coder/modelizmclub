import { readFileSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import { разметка, круглыйШаг } from "@/lib/chart/scale";

/**
 * График регистраций: шкала, нули и подписи.
 *
 * До 28.09 график рисовал семь столбиков по зашитому в код массиву
 * `[40, 65, 55, 80, 70, 90, 60]` с подписями «пн…вс» — ни одного настоящего
 * числа. Выглядело это правдоподобно, и заметить подмену по виду было
 * нельзя; нашлось чтением.
 *
 * Разметка шкалы проверяется прогоном, а не чтением: это чистая функция, и
 * её ответы можно сверить, а не пересказать.
 */
describe("шкала графика", () => {
  it("верх округляется вверх, иначе высокий столбик упирается в край", () => {
    expect(разметка([{ count: 7 }]).максимум).toBeGreaterThanOrEqual(7);
    expect(разметка([{ count: 23 }]).максимум).toBeGreaterThanOrEqual(23);
    expect(разметка([{ count: 101 }]).максимум).toBeGreaterThanOrEqual(101);
  });

  it("деления начинаются с нуля и идут ровным шагом", () => {
    const { деления } = разметка([{ count: 17 }]);

    expect(деления[0]).toBe(0);
    const шаг = деления[1] - деления[0];
    for (let i = 1; i < деления.length; i++) {
      expect(деления[i] - деления[i - 1]).toBe(шаг);
    }
  });

  /**
   * Деления — по диапазону, а не «всегда пять».
   *
   * При максимуме в три подписи 0…3 честнее, чем 0, 0.6, 1.2: дробных
   * регистраций не бывает.
   */
  it("на маленьких числах шаг остаётся целым", () => {
    for (const максимум of [1, 2, 3, 4]) {
      const { деления } = разметка([{ count: максимум }]);
      for (const в of деления) expect(Number.isInteger(в)).toBe(true);
    }
    expect(круглыйШаг(3)).toBe(1);
  });

  it("шаг берётся из ряда 1-2-5-10", () => {
    expect([1, 2, 5, 10]).toContain(круглыйШаг(4));
    expect(круглыйШаг(40)).toBe(10);
    expect(круглыйШаг(400)).toBe(100);
  });

  /** Месяц без единой регистрации — шкала всё равно есть, поле не пустое. */
  it("пустой месяц не ломает шкалу", () => {
    const { максимум, деления } = разметка([{ count: 0 }, { count: 0 }]);

    expect(максимум).toBeGreaterThan(0);
    expect(деления.length).toBeGreaterThanOrEqual(2);
  });
});

describe("разметка графика", () => {
  const исходник = readFileSync(join(import.meta.dirname, "RegistrationsChart.tsx"), "utf8");

  /** Ноль показывается нулём — и числом, и полоской на оси. */
  it("нулевой день рисуется, а не пропадает", () => {
    expect(исходник).toMatch(/точка\.count === 0 \? "2px"/);
    expect(исходник, "число печатается всегда, в том числе ноль").toContain("{точка.count}");
  });

  it("у каждого столбика есть число и дата", () => {
    expect(исходник).toContain("{деньМесяц(точка.date)}");
    expect(исходник).toContain("{точка.count}");
  });

  it("подсказка показывает полную дату и точное число", () => {
    expect(исходник).toMatch(/group-hover:block/);
    expect(исходник).toContain("{полнаяДата(точка.date)} · {точка.count}");
  });

  /**
   * Столбики и деления считают проценты от одной высоты.
   *
   * Первая редакция этого компонента считала их от разных: число над
   * столбиком занимало место в колонке, и поле для столбиков выходило ниже
   * поля для сетки. Деление «20» оказывалось не там, где верх столбика в
   * двадцать, — график врал бы тихо и правдоподобно.
   */
  it("сетка и столбики лежат в одном поле", () => {
    const поле = исходник.slice(
      исходник.indexOf("const высотаПоля"),
      исходник.indexOf("/** Ширина столбика"),
    );
    const сетка = поле.indexOf("borderTop:");
    const столбики = поле.indexOf("<Столбик");
    const общее = поле.indexOf('<div className="relative h-full">');

    expect(общее, "нет общего блока поля").toBeGreaterThan(-1);
    expect(сетка).toBeGreaterThan(общее);
    expect(столбики).toBeGreaterThan(общее);
    // И число висит над столбиком, а не отъедает высоту колонки.
    expect(исходник).toContain('className="absolute left-0 right-0 text-center text-[10px]');
  });

  /**
   * Подписи дат — в потоке под полем, а не внутри него.
   *
   * Контейнер с фиксированной высотой, куда не влезает полоса дат, даёт
   * крошечную прокрутку внутри карточки. Это известный промах разметки
   * данных, и здесь он закрыт тем, что даты лежат отдельным рядом.
   */
  it("полоса дат вынесена из поля фиксированной высоты", () => {
    const поле = исходник.slice(
      исходник.indexOf("const высотаПоля"),
      исходник.indexOf("/** Ширина столбика"),
    );
    const датыПосле =
      поле.indexOf("деньМесяц") > поле.indexOf("style={{ height: `${высотаПоля}px` }}");
    expect(датыПосле, "даты должны идти после блока поля").toBe(true);
  });

  /** Сетка — сплошные линии: пунктир читается как порог или прогноз. */
  it("сетка не пунктирная", () => {
    expect(исходник).not.toMatch(/border.*dashed/i);
    expect(исходник).toContain('borderTop: "1px solid var(--border)"');
  });
});
