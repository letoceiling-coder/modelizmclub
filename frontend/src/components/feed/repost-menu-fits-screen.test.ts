import { readFileSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";

/**
 * Меню «Поделиться» помещается на экране телефона.
 *
 * Жалоба владельца 05.10, настоящий телефон: в ленте у развёрнутой записи
 * «блок „Поделиться“ сместился».
 *
 * Меню стояло `absolute bottom-full left-0 w-[260px]`, то есть отсчитывалось
 * от левого края своей кнопки. Кнопка «Репост» — третья в строке действий,
 * её левый край на 115 px, и меню занимало 115…375 при любой ширине экрана.
 * Замер на стенде, лента, настоящее касание (Radix и это меню слушают
 * `pointerdown`, программный `click` их не открывает):
 *
 * | Ширина | За правым краем | Пункты |
 * | --- | --- | --- |
 * | 320 | 55 px | все три обрезаны |
 * | 360 | 15 px | все три обрезаны |
 * | 390 и шире | 0 | целиком |
 *
 * Горизонтальной прокрутки у страницы при этом не возникало — снаружи это
 * выглядело не поломкой вёрстки, а просто обрезанным меню, и обычные ворота
 * «ноль горизонтальной прокрутки» его не ловили.
 *
 * Чинится в общем компоненте: `RepostMenu` → `PostActions` → `PostCard`,
 * а `PostCard` рисуют лента, профиль, сообщество, канал и страница записи.
 *
 * Проверяем исходник: в jsdom нет раскладки, 115 и 375 там не получить.
 * Поведение проверено замером в браузере на пяти ширинах.
 */
const ФАЙЛ = join(import.meta.dirname ?? __dirname, "RepostMenu.tsx");

function безКомментариев(): string {
  return readFileSync(ФАЙЛ, "utf8")
    .replace(/\{\s*\/\*[\s\S]*?\*\/\s*\}/g, " ")
    .replace(/\/\*[\s\S]*?\*\//g, " ")
    .replace(/(^|[^:])\/\/.*$/gm, "$1 ");
}

describe("меню «Поделиться» помещается на экране", () => {
  const код = безКомментариев();

  it("меню держится середины своей кнопки, а не её левого края", () => {
    expect(код).toMatch(/absolute bottom-full left-1\/2/);
    expect(код).not.toMatch(/absolute bottom-full left-0/);
  });

  it("ширина меню не больше экрана", () => {
    expect(код).toMatch(/w-\[min\(260px,calc\(100vw-24px\)\)\]/);
    expect(код).not.toMatch(/mb-\[8px\] w-\[260px\]/);
  });

  /*
   * Сдвиг на половину ширины задан в анимации, а не классом.
   *
   * framer-motion пишет `transform` инлайном, и тот перебивает класс
   * целиком: с `-translate-x-1/2` в `className` меню получило бы `left-1/2`
   * без возврата и уехало бы вправо сильнее прежнего. Поэтому `x: "-50%"`
   * стоит во всех трёх состояниях — это центрирование, а не движение.
   */
  it("сдвиг на половину ширины задан в анимации и одинаков во всех состояниях", () => {
    const сдвигов = [...код.matchAll(/x:\s*"-50%"/g)].length;
    expect(сдвигов).toBe(3);
    expect(код).not.toMatch(/className=.*-translate-x-1\/2/);
  });
});
