import { readFileSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";

/**
 * Меню «Поделиться» целиком на экране — и в карточке, и в окне просмотра.
 *
 * Две жалобы владельца на одно меню, и первая была закрыта не до конца.
 *
 * **05.10, телефон:** «блок „Поделиться“ сместился». Меню стояло
 * `absolute bottom-full left-0 w-[260px]`, то есть от левого края своей
 * кнопки — третьей в строке действий, с левым краем на 115 px. Замер:
 * 320 — за правым краем 55 px, 360 — 15 px, от 390 помещалось.
 * Починили центрированием по кнопке и `min(260px,100vw-24px)`.
 *
 * **06.10, живой сайт, 1280:** то же меню в ОКНЕ ПРОСМОТРА записи —
 * «виден только пункт „Поделиться“, пункты выше нажимаются, но не видны».
 * Это и была непроверенная половина: 05.10 смотрели карточку ленты, а у
 * неё обрезающего родителя нет. Панель окна просмотра объявлена
 * `lg:overflow-hidden`. Замер 06.10, /feed → нажатие по фотографии:
 *
 * | Узел | Прямоугольник | Что с ним |
 * | --- | --- | --- |
 * | панель окна | `[860,54,380,792]` | `overflow: hidden` |
 * | кнопка «Репост» | `[931,111,44,44]` | у верхнего края панели |
 * | «Репост в ленту» | `[824,-17,258,40]` | за верхним краем ЭКРАНА |
 * | «Отправить в сообщения» | `[824,22,258,40]` | выше края панели — обрезан |
 * | «Поделиться» | `[824,63,258,40]` | единственный целиком видимый |
 *
 * `elementFromPoint` в середине двух верхних пунктов отдавал затемнение
 * лайтбокса, а не пункт: до них нельзя было ни дотянуться, ни их увидеть.
 *
 * Поднимать слой бесполезно: обрезает `overflow` родителя, и внутри него
 * `z-index` не значит ничего. Поэтому меню вынесено в portal существующим
 * средством проекта — `DropdownMenu` (Radix). Слой — `--z-popover` (55) из
 * шкалы, то есть над лайтбоксом (`--z-modal`, 50).
 *
 * Стало (06.10, после правки, мышь и настоящее касание):
 *
 * | Где | Ширины | Пунктов | Обрезанных или перекрытых |
 * | --- | --- | --- | --- |
 * | окно просмотра | 320, 360, 390, 1280 | 3 | **0** |
 * | лента, профиль, страница записи, канал, сообщество | 360, 1280 | 3 | **0** |
 *
 * На 1280 меню само открылось ВНИЗ (`[824,164]` при кнопке на 111): вверх
 * места не было, и Radix перевернул сторону. Esc закрывает, нажатие и тап
 * мимо закрывают, Enter открывает, стрелки ходят по пунктам.
 *
 * Проверяем исходник: раскладки в jsdom нет, 824 и −17 там не получить.
 * Поведение проверено в браузере — ширины и способы ввода выше.
 */
const СЛОЙ = import.meta.dirname ?? __dirname;

/*
 * Блочные комментарии снимаются ПЕРВЫМИ, и это не вкусовщина.
 *
 * Обратный порядок съедал проверяемый код. Выражение для JSX-комментария
 * `\{\s*\/\*…\*\/\s*\}` нежадное в середине, но начало ищет самое раннее
 * подходящее `{`. В этом файле оно находило `if (guest) {` с примечанием
 * внутри, а закрывалось на `{/* Простая стрелка … *\/}` у кнопки — то есть
 * сносило всё между ними, включая `modal={false}`. Проверка не падала с
 * ошибкой: она искала в пустоте и отвечала «нет такого».
 *
 * Поймано тем, что утверждение краснело на исправленном коде. Та же
 * грабля уже описана в `routes/ad-write-seller-refusal.test.ts`.
 */
function безКомментариев(путь: string): string {
  return readFileSync(join(СЛОЙ, путь), "utf8")
    .replace(/\/\*[\s\S]*?\*\//g, " ")
    .replace(/\{\s*\/\*[\s\S]*?\*\/\s*\}/g, " ")
    .replace(/(^|[^:])\/\/.*$/gm, "$1 ");
}

describe("меню «Поделиться» целиком на экране", () => {
  const код = безКомментариев("RepostMenu.tsx");

  /*
   * Главное. Меню — portal существующего компонента, а не `absolute`
   * внутри кнопки: только так его не обрежет родитель с `overflow`.
   */
  it("меню выводится в portal общим компонентом проекта", () => {
    expect(код).toMatch(/from "@\/components\/ui\/dropdown-menu"/);
    expect(код).toMatch(/<DropdownMenuContent/);
    expect(код).not.toMatch(/absolute bottom-full/);
    /* framer-motion тут больше не рисует меню — анимацию ведёт Radix. */
    expect(код).not.toMatch(/AnimatePresence/);
  });

  /*
   * Края экрана. `side="top"` — просьба, а не приговор: `avoidCollisions`
   * у Radix включён по умолчанию, и при нехватке места сверху меню
   * открывается вниз. `collisionPadding` оставляет зазор от краёв.
   */
  it("учитывает края экрана: не поместилось вверх — откроется вниз", () => {
    expect(код).toMatch(/side="top"/);
    expect(код).toMatch(/collisionPadding=\{\d+\}/);
    /* Запрет переворота сделал бы правку бессмысленной. */
    expect(код).not.toMatch(/avoidCollisions=\{false\}/);
  });

  it("ширина меню не больше экрана", () => {
    expect(код).toMatch(/w-\[min\(260px,calc\(100vw-24px\)\)\]/);
  });

  /*
   * Слой — из шкалы, и берётся он из общего компонента. Числового
   * `z-index` в самом меню быть не должно вовсе.
   */
  it("слой из шкалы, числового z-index нет", () => {
    expect(код).not.toMatch(/z-\[\d/);
    expect(код).not.toMatch(/zIndex/);
    const общий = безКомментариев(join("..", "ui", "dropdown-menu.tsx"));
    expect(общий).toMatch(/z-\[var\(--z-popover\)\]/);
  });

  /*
   * Окно просмотра — свой portal, а не Radix Dialog. Модальный режим
   * погасил бы указатель на всём документе, то есть на самом окне под
   * меню, и правка одного дефекта завела бы другой.
   */
  it("режим не модальный — окно просмотра под меню остаётся живым", () => {
    expect(код).toMatch(/modal=\{false\}/);
  });

  /*
   * Одна реализация на карточку и окно просмотра. `components/RepostMenu.tsx`
   * — это ре-экспорт, а не второй экземпляр; если там появится своя
   * разметка, проверка покраснеет.
   */
  it("реализация одна: второй файл — только ре-экспорт", () => {
    const второй = readFileSync(join(СЛОЙ, "..", "RepostMenu.tsx"), "utf8").trim();
    expect(второй).toBe('export { RepostMenu } from "./feed/RepostMenu";');
  });
});
