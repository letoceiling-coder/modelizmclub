import { readFileSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";

/**
 * Пункт «Как пользоваться» в меню лендинга и блок приглашения.
 *
 * Задание заказчика: пункт стоит в верхнем меню рядом с логотипом,
 * **перед «Объявлениями»**, и виден всегда. Во внутренней шапке
 * (`DesktopTopBar`) он был, а лендинг собирает меню своим списком — и
 * там его не было вовсе. Проверено на проде 04.10: меню лендинга
 * состояло из «Объявлений», «Сообществ», «Каналов», «Как работает» и
 * «Подписки».
 *
 * Из того же списка собирается мобильная шторка меню, поэтому отдельной
 * проверки на телефон не нужно: пункт там появляется тем же кодом.
 *
 * Код читается без комментариев — иначе проверка порядка цепляется за
 * слова в докблоках.
 */
const без = (путь: string) =>
  readFileSync(путь, "utf8")
    .replace(/\/\*[\s\S]*?\*\//g, "")
    .replace(/^\s*\/\/.*$/gm, "");

const ЛЕНДИНГ = join(import.meta.dirname, "..", "..", "routes", "index.tsx");

describe("верхнее меню лендинга", () => {
  it("«Как пользоваться» стоит перед «Объявлениями»", () => {
    const т = без(ЛЕНДИНГ);

    const инструкция = т.indexOf("landing.nav.howToUse");
    const объявления = т.indexOf("landing.nav.ads");

    expect(инструкция, "пункта «Как пользоваться» в меню лендинга нет").toBeGreaterThan(-1);
    expect(объявления, "пункта «Объявления» в меню лендинга нет").toBeGreaterThan(-1);
    expect(инструкция, "«Как пользоваться» оказался после «Объявлений»").toBeLessThan(объявления);
  });

  it("пункт ведёт на страницу инструкции", () => {
    expect(без(ЛЕНДИНГ)).toContain('to: "/how-to-use" as const');
  });
});

describe("блок приглашения в сообщество", () => {
  it("содержит текст с раздаточной карточки", () => {
    const т = без(ЛЕНДИНГ);

    expect(т).toContain("Сообщество, объединяющее единомышленников");
    expect(т).toContain("Присоединяйся к сообществу МоДелизМ");
  });

  it("перечисляет пять возможностей ссылками", () => {
    const т = без(ЛЕНДИНГ);

    for (const название of ["Мессенджер", "Объявления", "Обзоры", "Лента", "Каналы"]) {
      expect(т, `пропала возможность «${название}»`).toContain(`название: "${название}"`);
    }
  });
});
