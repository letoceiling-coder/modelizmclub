import { readFileSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";

/**
 * Предложка не сообщает об отправке, которой не было.
 *
 * До 04.10 форма показывала «Пост отправлен на рассмотрение» после
 * `setTimeout` на 600 мс, не отправляя ничего: серверного маршрута
 * предложки не существует. Человек ждал решения администратора, которому
 * ничего не приходило.
 *
 * Проверка сторожит не вёрстку, а два обещания, которые легко вернуть
 * обратно одной правкой: что ложного подтверждения нет и что подделки
 * отправки через таймер тоже нет.
 *
 * Третья проверка — про серверный маршрут. Она здесь затем, чтобы
 * удаление формы не пережило появление настоящей предложки: как только
 * у компонента появится запрос, проверка про таймер останется верной, а
 * проверка про «ещё не работает» покраснеет и заставит переписать текст.
 */
const КОМПОНЕНТ = join(import.meta.dirname, "SubmitPostSheet.tsx");

/**
 * Код без комментариев.
 *
 * Иначе проверка краснеет на собственном объяснении: в докблоке
 * компонента слово `setTimeout` стоит в рассказе о том, как было, и
 * первая редакция этого теста на нём и упала. Проверять надо то, что
 * исполняется, а не то, чем оно описано.
 */
const текст = () =>
  readFileSync(КОМПОНЕНТ, "utf8")
    .replace(/\/\*[\s\S]*?\*\//g, "")
    .replace(/^\s*\/\/.*$/gm, "");

describe("предложка сообщества", () => {
  it("не сообщает об отправке", () => {
    const т = текст();

    expect(т, "вернулось ложное подтверждение отправки").not.toContain(
      "Пост отправлен на рассмотрение",
    );
    expect(т, "вернулся успешный тост без запроса").not.toMatch(/toast\.success/);
  });

  it("не подделывает отправку таймером", () => {
    const т = текст();

    expect(т, "вернулся setTimeout вместо запроса").not.toContain("setTimeout");
    expect(т, "вернулось состояние отправки без отправки").not.toContain("submitting");
  });

  it("говорит человеку, что предложка не работает", () => {
    const т = текст();

    expect(т).toContain("ещё не работает");
  });
});
