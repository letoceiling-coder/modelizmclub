import { readFileSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";

import { MOBILE_MENU_SECTIONS } from "@/lib/nav";
import { ROUTES } from "@/lib/routes";

/**
 * «Как пользоваться» — один вход на экран. Решение Е1 от 06.10.
 *
 * Было (замер 06.10, `/feed`, гость и вошедший одинаково):
 *
 * | Ширина | В DOM | Видимых | Где |
 * | --- | --- | --- | --- |
 * | 360 | 3 | 0 | обе колонки скрыты, вход в меню |
 * | 768 | 3 | 1 | колонка значков |
 * | 1024 | 3 | **2** | шапка `[152,13,144,33]` **и** колонка `[36,356,40,40]` |
 * | 1280 | 3 | **2** | шапка `[158,13,144,33]` **и** колонка `[30,389,240,44]` |
 *
 * Причина: шапка `DesktopTopBar` включается с 1024, боковая колонка — с
 * 768. Значит на всей ширине, где видна шапка, ссылка уже стояла в
 * колонке. Дубль был не случайным, а по построению.
 *
 * Стало: ссылка живёт в трёх местах, и они не пересекаются по ширине —
 * меню телефона (до 768), боковая колонка (от 768), собственное меню
 * лендинга (у лендинга своей боковой колонки нет).
 *
 * Проверяется исходником, а не отрисовкой: условие — про ширины, на
 * которых включаются разные куски оболочки, а jsdom ширин не знает.
 * Поведение проверено в браузере на четырёх ширинах, обеими ролями.
 */
const СЛОЙ = import.meta.dirname ?? __dirname;

function безКомментариев(файл: string): string {
  return readFileSync(join(СЛОЙ, файл), "utf8")
    .replace(/\{\s*\/\*[\s\S]*?\*\/\s*\}/g, " ")
    .replace(/\/\*[\s\S]*?\*\//g, " ")
    .replace(/(^|[^:])\/\/.*$/gm, "$1 ");
}

describe("«Как пользоваться»: один вход на экран", () => {
  /*
   * Главное утверждение. Если ссылку вернут в шапку — хоть `ROUTES.howToUse`,
   * хоть строкой `/how-to-use`, — проверка краснеет. Комментарии сняты, то
   * есть разбор выше её не питает: упоминание в примечании не считается.
   */
  it("в верхней шапке ссылки нет", () => {
    const шапка = безКомментариев("DesktopTopBar.tsx");
    expect(шапка).not.toMatch(/ROUTES\.howToUse/);
    expect(шапка).not.toMatch(/how-to-use/);
  });

  /* А в колонке — есть: от 768 это единственный вход. */
  it("в боковой колонке ссылка есть", () => {
    const колонка = безКомментариев("Sidebar.tsx");
    expect(колонка).toMatch(/ROUTES\.howToUse/);
  });

  /* До 768 колонки нет вовсе — остаётся меню. */
  it("в меню телефона ссылка есть", () => {
    const пункт = MOBILE_MENU_SECTIONS.find((s) => s.to === ROUTES.howToUse);
    expect(пункт).toBeDefined();
    /* Без `authOnly`: страница нужна как раз тому, кто ещё не вошёл. */
    expect(пункт?.authOnly).toBeUndefined();
  });

  /*
   * Лендинг — свой случай: боковой колонки у него нет ни на одной ширине,
   * и его собственный ряд ссылок на телефоне складывается в шторку. Поэтому
   * пункт в его списке — не дубль колонки, а её замена.
   */
  it("в меню лендинга ссылка есть, и ровно одна", () => {
    const лендинг = безКомментариев(join("..", "..", "routes", "index.tsx"));
    const навигация = лендинг.slice(
      лендинг.indexOf("const navLinks"),
      лендинг.indexOf("const navLinks") + 1800,
    );
    expect(навигация).toMatch(/to: "\/how-to-use" as const/);
    const вНавигации = навигация.match(/"\/how-to-use"/g) ?? [];
    expect(вНавигации).toHaveLength(1);
  });
});
