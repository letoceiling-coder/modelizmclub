import { readFileSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";

/**
 * Панель действий записи: счётчик совпадает с состоянием, отказ слышен,
 * выдуманных чисел нет.
 *
 * Шаг 4 задания: «лайк, сохранение, репост, комментарий с откатом при
 * отказе и одинаковым состоянием во всех списках».
 *
 * Нашлись три вещи, и две из них — одна причина.
 *
 * **Счётчик реакций не двигался.** Замер 06.10 на странице записи: в базе
 * реакция и `reactions_count` равны 1, сердце закрашено, а в кнопке
 * `<span class="tabular-nums" style="opacity: 0">0</span>` — то есть числа
 * на экране нет ни старого, ни нового. Причина не в счётчике: соседний
 * `m.span` анимировал сердце тремя кадрами (`scale: [1, 1.35, 1]`) с
 * пружиной, а framer-motion так не умеет и бросает исключение «Only two
 * keyframes currently supported with spring and inertia animations».
 * Исключение рвало его работу, и `AnimatePresence` внутри
 * `ReducedMotionSwitch` не доводил смену числа. Одно исправление сняло и
 * исключение на странице, и застывший счётчик.
 *
 * **Отказ сохранения молчал.** Откат был, сообщения не было: закладка на
 * миг загоралась и гасла без единого слова. Ворота `check-empty-catch.sh`
 * такое не ловят — обработчик не пустой, он делает откат.
 *
 * **Числа у закладки не существует.** Сервер его не отдаёт (в `stats`
 * только просмотры, реакции, комментарии, репосты), клиент подставляет
 * `saves: 0`. Условие `saves > 0` выполнялось ровно после своего нажатия,
 * и человек видел «1», читаемую как «один человек сохранил».
 *
 * После правок на странице записи, в ленте и в профиле автора: реакция
 * «1 / выделено», закладка «(пусто) / выделено» — одинаково везде, и то же
 * в базе. Исключений ноль.
 */
const КОРЕНЬ = import.meta.dirname ?? __dirname;

function безКомментариев(файл: string): string {
  return readFileSync(join(КОРЕНЬ, файл), "utf8")
    .replace(/\/\*[\s\S]*?\*\//g, " ")
    .replace(/\{\s*\/\*[\s\S]*?\*\/\s*\}/g, " ")
    .replace(/(^|[^:])\/\/.*$/gm, "$1 ");
}

describe("панель действий записи", () => {
  const панель = безКомментариев("PostActions.tsx");
  const карточка = безКомментариев("PostCard.tsx");

  /*
   * Три кадра и пружина несовместимы. Проверяем не «нет пружины вообще» —
   * у соседних кнопок она законна с двумя кадрами, — а именно сочетание.
   */
  it("анимация в три кадра не идёт пружиной", () => {
    const блоки = [...панель.matchAll(/<m\.span[\s\S]{0,400}?>/g)].map((m) => m[0]);
    expect(блоки.length).toBeGreaterThan(0);
    for (const блок of блоки) {
      const триКадра = /scale:\s*\[[^\]]*,[^\]]*,[^\]]*\]/.test(блок);
      const пружина = /type:\s*"spring"/.test(блок);
      expect(триКадра && пружина).toBe(false);
    }
  });

  it("отказ сохранения объявляется, а не только откатывается", () => {
    const блок = карточка.slice(
      карточка.indexOf("const doSave"),
      карточка.indexOf("const toggleSave"),
    );
    expect(блок).not.toBe("");
    expect(блок).toMatch(/bookmarkPost\([\s\S]*?\.catch/);
    expect(блок).toMatch(/toast\.error/);
  });

  it("у закладки нет числа, которого не отдаёт сервер", () => {
    expect(панель).not.toMatch(/saves\s*>\s*0/);
    expect(карточка).not.toMatch(/setSaves/);
  });

  /*
   * Закрашенная закладка — настоящее состояние (`viewer.bookmarked`), и
   * убирать её вместе с числом было нельзя.
   */
  it("состояние закладки осталось", () => {
    expect(панель).toMatch(/fill=\{saved \? "currentColor" : "none"\}/);
  });
});
