import { readFileSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";

/**
 * Каталог догружается сам. Решение Е5 от 06.10.
 *
 * Жалоба владельца: внизу каталога кнопка «Показать ещё», которую приходится
 * нажимать каждый раз. Кнопка осталась, но только запасным ходом при отказе —
 * как и просит решение.
 *
 * Замер 06.10 на стенде (60 объявлений заведено для замера и убрано в том же
 * заходе; страница — 24):
 *
 * | Что проверялось | Результат |
 * | --- | --- |
 * | 1280, прокрутка вниз | 24 → 48 → 61, дальше не растёт |
 * | 360, прокрутка вниз | доезжает до 61 |
 * | страницы в запросах | `2`, `3` — по одному разу |
 * | дубли карточек | 0 |
 * | медленная сеть (ответ +2,5 с) | во время загрузки 28 заглушек и 24 карточки, после — 0 и 48 |
 * | обрыв догрузки | «Не удалось загрузить дальше» + «Повторить»; по нажатию 24 → 48 |
 * | смена сортировки | список пересобран: 61 → 48 |
 * | возврат «Назад» с карточки | 61 объявление и прокрутка 6677 → 6677 |
 * | одна страница (11 объявлений) | сторожа нет, запросов догрузки нет |
 * | ничего не найдено | то же; подвал в окне |
 *
 * ## Что замер показал по дороге
 *
 * **Лишний повтор первой страницы.** Эффект загрузки висел на личности
 * `load`, а та пересобирается от `t`, `filters`, `categoryId` — и что-то
 * менялось уже после монтирования. С кнопкой это был только лишний запрос:
 * человек ещё ничего не нажал. С автоподгрузкой список на глазах сжимался до
 * 24 и отрастал обратно, а страницы 2 и 3 ехали дважды:
 *
 *   +1,6 с page=2 · +1,9 с page=3 · +1,95 с (без page) · +2,2 с page=2 · +2,5 с page=3
 *
 * Теперь сравниваются ПАРАМЕТРЫ, а не личность обработчика, и в трёх
 * прогонах подряд остаются ровно `page=2` и `page=3`.
 *
 * **Две ловушки замера.** Счёт карточек по узлам `a[href^="/ads/"]` давал
 * вдвое больше: у карточки две ссылки на одно объявление, плюс «Разместить
 * объявление» ведёт на `/ads/new`. И положение прокрутки для «Назад» снималось
 * до `scrollIntoView`, который сам прокручивал страницу, — «не совпало»
 * относилось к другому числу.
 *
 * Проверяем исходник: `IntersectionObserver` и прокрутки в jsdom нет.
 * Поведение проверено в браузере — таблица выше.
 */
function читать(путь: string): string {
  /* Блочные комментарии — первыми: иначе выражение для JSX-комментария
     сшивает два далёких узла и съедает код между ними. */
  return readFileSync(join(import.meta.dirname ?? __dirname, путь), "utf8")
    .replace(/\/\*[\s\S]*?\*\//g, " ")
    .replace(/\{\s*\/\*[\s\S]*?\*\/\s*\}/g, " ")
    .replace(/(^|[^:])\/\/.*$/gm, "$1 ");
}

describe("сторож догрузки", () => {
  const код = читать("AutoLoadMore.tsx");

  it("догружает по приближению конца списка", () => {
    expect(код).toMatch(/new IntersectionObserver/);
    expect(код).toMatch(/rootMargin/);
  });

  /*
   * Корень — ближайший прокручиваемый предок. На широком экране
   * прокручивается `<main>` (`lg:overflow-y-auto`), а не документ: с
   * корнем-окном запас уходит за край `main`, тот обрезает сторожа, и
   * наблюдатель молчит до самого низа — запас перестаёт работать там, где
   * он нужен.
   */
  it("корень наблюдателя — прокручиваемый предок, а не окно", () => {
    expect(код).toMatch(/root: прокручиваемыйПредок\(узел\)/);
    expect(код).toMatch(/scrollHeight > узел\.clientHeight/);
  });

  /* Узел нулевой высоты наблюдатель считает непересекающимся. */
  it("у сторожа есть высота", () => {
    expect(код).toMatch(/className="h-px w-full"/);
  });

  it("при отказе — строка и «Повторить» вместо сторожа", () => {
    expect(код).toMatch(/failed &&/);
    expect(код).toMatch(/onClick=\{onRetry\}/);
    expect(код).toMatch(/hasMore && !failed/);
  });

  /*
   * Область для диктора стоит всегда, а не появляется вместе с текстом:
   * появившуюся область диктор может не прочитать.
   */
  it("область для диктора постоянна", () => {
    expect(код).toMatch(/aria-live="polite"/);
    const i = код.indexOf('aria-live="polite"');
    const блок = код.slice(Math.max(0, i - 200), i);
    expect(блок).not.toMatch(/announcement &&/);
  });
});

describe("каталог: догрузка без повторов и дублей", () => {
  const код = читать(join("..", "..", "routes", "ads.index.tsx"));

  it("кнопки «Показать ещё» в каталоге больше нет", () => {
    expect(код).toMatch(/<AutoLoadMore/);
    expect(код).not.toMatch(/pages\.ads\.showMore/);
  });

  /*
   * Одну страницу — один раз. `loadingMore` поднимается уже внутри
   * `loadMore`, и два вызова в одном кадре увидели бы прежнее `false` оба;
   * `заказано` сравнивается синхронно, до любого await.
   */
  it("одна страница заказывается один раз", () => {
    /*
     * Границы — тело самого `loadMore`. Срез от начала файла здесь не
     * годится: `load()` стоит выше и тоже содержит `await fetchListings`,
     * и проверка «до отметки нет await» краснела на верном коде.
     */
    const тело = код.slice(код.indexOf("const loadMore"), код.indexOf("const ключЗапроса"));
    const запрет = тело.indexOf("if (заказано.current >= nextPage) return;");
    const отметка = тело.indexOf("заказано.current = nextPage;");
    const запрос = тело.indexOf("await fetchListings");
    expect(запрет).toBeGreaterThan(-1);
    expect(отметка).toBeGreaterThan(запрет);
    /* Отметка ставится ДО сетевого вызова — иначе второй вызов в том же
       кадре успеет проскочить. */
    expect(отметка).toBeLessThan(запрос);
  });

  /* Страницы сервера сдвигаются, пока человек листает: одна карточка может
     приехать дважды. */
  it("догруженное дописывается без дублей", () => {
    expect(код).toMatch(/const было = new Set\(prev\.map\(\(a\) => a\.id\)\)/);
    expect(код).toMatch(/result\.filter\(\(a\) => !было\.has\(a\.id\)\)/);
  });

  /* Отказ больше не выключает догрузку навсегда. */
  it("отказ догрузки оставляет путь назад", () => {
    expect(код).toMatch(/setMoreFailed\(true\)/);
    const блок = код.slice(код.indexOf("const loadMore"), код.indexOf("const ключЗапроса"));
    expect(блок).not.toMatch(/setHasMore\(false\);\s*reportReadFailure/);
  });

  /* Запрос повторяется от смены параметров, а не личности `load`. */
  it("тот же отбор не перезапрашивается", () => {
    expect(код).toMatch(/if \(прошлыйКлюч\.current === ключЗапроса\) return;/);
    expect(код).toMatch(/const ключЗапроса = useMemo\(/);
  });

  /*
   * Возврат «Назад»: догруженное помнится. Кэш модульный, и писать его на
   * сервере нельзя — процесс Node живёт сутками, и ответ одному посетителю
   * не должен зависеть от предыдущего.
   */
  it("догруженное помнится только в браузере", () => {
    expect(код).toMatch(/function запомнить/);
    const блок = код.slice(
      код.indexOf("function запомнить"),
      код.indexOf("function запомнить") + 400,
    );
    expect(блок).toMatch(/if \(typeof window === "undefined"\) return;/);
  });

  /* Высота должна вернуться до отрисовки, иначе восстанавливать прокрутку
     роутеру не во что. */
  it("восстановление — до отрисовки", () => {
    expect(код).toMatch(
      /useLayoutEffect\(\(\) => \{\s*const сохранённое = догруженное\.get\(ключЗапроса\)/,
    );
  });
});
