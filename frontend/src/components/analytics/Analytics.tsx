import { useEffect, useRef, useState } from "react";
import { useRouterState } from "@tanstack/react-router";
import { loadAnalyticsIfConsented, onAnalyticsConsent } from "@/lib/cookie-consent";
import { isMetrikaStarted, metrikaHit } from "@/lib/analytics/metrika";

/**
 * Единственное место, где живёт счётчик на странице.
 *
 * Делает две вещи, каждую из которых легко забыть по отдельности:
 *
 * **Грузит при повторном заходе.** Баннер зовёт `loadAnalyticsIfConsented`
 * только в момент выбора, а показывается он один раз в жизни. Без вызова на
 * монтировании счётчик работал бы ровно у тех, кто прямо сейчас нажал
 * «Принять», и ни у кого больше.
 *
 * **Считает переходы.** Приложение одностраничное: после первой загрузки
 * адрес меняет роутер, и Метрика об этом не узнаёт. Без `hit` на смену
 * адреса в отчётах остался бы один просмотр на всю сессию, а воронка
 * «каталог → карточка → сделка» не собралась бы вовсе.
 */
export function Analytics() {
  /*
   * Путь, а не полный адрес.
   *
   * `location.href` у роутера включает параметры запроса, и до 22.09 просмотр
   * уходил на каждую их правку: лента стирает `?composer=open` немедленно
   * после перехода — два просмотра одной страницы подряд; мессенджер пишет
   * `?chat=…` на каждый щелчок по диалогу — просмотр на каждый диалог;
   * каталог — на каждый фильтр. Отчёты по этим разделам завышались в разы, а
   * «страницы входа» и отказы считались по мусору.
   *
   * В адрес самого просмотра параметры при этом уходят: они осмысленны,
   * считать по ним не надо.
   */
  const pathname = useRouterState({ select: (s) => s.location.pathname });
  const href = useRouterState({ select: (s) => s.location.href });

  /*
   * Загрузка асинхронна (динамический импорт), поэтому первый просмотр
   * привязан к признаку запуска, а не к монтированию. До 22.09 здесь стояла
   * проверка `isMetrikaLoaded()` без такого признака: на первом кадре она
   * всегда отвечала «нет», а `[href]` больше не менялся — и посетитель,
   * зашедший на одну страницу и ушедший, не давал ни просмотра, ни визита.
   * То есть в отчётах его не было вовсе.
   */
  const [запущена, setЗапущена] = useState(false);

  useEffect(() => {
    const свериться = () => setЗапущена(isMetrikaStarted());
    /*
     * Подписка до вызова: «Принять» в баннере зовёт ту же загрузку, а
     * страница к этому моменту уже смонтирована — без оповещения первый
     * просмотр у согласившегося ушёл бы только со следующей перезагрузкой.
     */
    const off = onAnalyticsConsent(свериться);
    void loadAnalyticsIfConsented().then(свериться);

    return off;
  }, []);

  /** Откуда пришли: внутри приложения `document.referrer` не меняется. */
  const предыдущий = useRef<string | null>(null);

  useEffect(() => {
    if (!запущена) return;
    metrikaHit(href, предыдущий.current ?? undefined);
    предыдущий.current = href;
    /*
     * `href` намеренно вне зависимостей: он меняется вместе с параметрами
     * запроса, а просмотр считается по смене пути. В отправку при этом
     * уходит адрес целиком — тот, что актуален на момент перехода.
     */
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [запущена, pathname]);

  return null;
}
