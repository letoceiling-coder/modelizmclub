import { readFileSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";

/**
 * Правило имени в профиле не строже серверного.
 *
 * Сервер при регистрации держит `PersonName`:
 * `/^[\p{L}\p{M} \x{00A0}'\x{2019}.\x{00B7}\x{2022}-]+$/u` — буквы, знаки,
 * пробел, неразрывный пробел, апострофы `'` и `’`, точка, средняя точка,
 * маркер и дефис. Клиент же проверял `/^[\p{L}\s-]+$/u` — только буквы,
 * пробелы и дефис.
 *
 * Разница запирала профиль. Проверено 06.10 сквозняком:
 *
 * 1. `POST /auth/register` с именем «Анна О'Нил» — **принят**;
 * 2. этой учётке поставлено то же имя, в форме правилось **только
 *    описание** — при сохранении «ФИО: только буквы, пробелы и дефис», в
 *    базе ничего не изменилось.
 *
 * То есть собственное имя не давало сохранить ни описание, ни город, ни
 * аватар, пока человек его не исказит.
 *
 * Клиент может подсказать раньше сервера, но не может запрещать то, что
 * сервер разрешил. Проверяем само правило, а не исходник: правило —
 * вывозимая величина, и его можно спросить напрямую.
 */

/*
 * Правило берём из исходника, а не импортом: `ProfileView.tsx` тянет за
 * собой весь экран профиля, и в этой проверке он не нужен. Выражение
 * вынуто ровно по имени, то есть читается то же, чем пользуется форма.
 */
function правилоИмени(): RegExp {
  const файл = readFileSync(join(import.meta.dirname ?? __dirname, "ProfileView.tsx"), "utf8");
  const m = файл.match(/export const PROFILE_NAME_REGEX = (\/.+\/u);/);
  if (!m) throw new Error("PROFILE_NAME_REGEX не найдено в ProfileView.tsx");
  const [, тело] = m;
  const последний = тело.lastIndexOf("/");
  return new RegExp(тело.slice(1, последний), тело.slice(последний + 1));
}

describe("правило имени в профиле", () => {
  const правило = правилоИмени();

  /** То, что принимает сервер при регистрации, обязан принять и клиент. */
  it.each([
    "Анна О'Нил",
    "Анна О’Нил",
    "А. Петров",
    "Жан-Люк Пикар",
    "Анна Мария",
    "Иван Петров",
    "Пётр Ильи·ч",
  ])("принимает «%s» — его принимает сервер", (имя) => {
    expect(правило.test(имя)).toBe(true);
  });

  /** А вот это сервер не принимает, и клиенту принимать незачем. */
  it.each(["Аня <script>", "Имя123", "user@example.com", "Имя_Фамилия", "Имя(А)"])(
    "отклоняет «%s»",
    (имя) => {
      expect(правило.test(имя)).toBe(false);
    },
  );

  /*
   * Отдельно: именно апостроф был тем знаком, на котором профиль запирался.
   * Если правило сузят обратно, эта проверка покраснеет первой.
   */
  it("апостроф разрешён — на нём и запирался профиль", () => {
    expect(правило.test("О'Нил")).toBe(true);
    expect(правило.test("О’Нил")).toBe(true);
  });
});

describe("отказ сохранения профиля называется словами", () => {
  const исходник = readFileSync(join(import.meta.dirname ?? __dirname, "ProfileView.tsx"), "utf8")
    .replace(/\/\*[\s\S]*?\*\//g, " ")
    .replace(/(^|[^:])\/\/.*$/gm, "$1 ");

  /*
   * Стояло `err instanceof Error ? err.message : …` — сообщение браузера
   * предпочиталось своему, и при отказе сети человек видел «Failed to
   * fetch». Замер подтвердил: именно эта строка и показывалась.
   */
  it("показывается не err.message, а разобранный текст", () => {
    /*
     * Границу берём по разметке `<FriendRequiredDialog`, а не по имени:
     * то же слово стоит в импорте, то есть **раньше** начала среза, и срез
     * выходил пустым — проверка искала в пустоте и отвечала «нет такого».
     */
    const блок = исходник.slice(
      исходник.indexOf("profileUpdated"),
      исходник.indexOf("<FriendRequiredDialog"),
    );
    expect(блок).toMatch(/formatApiErrorMessage\(err, t\("pages\.profile\.profileSaveFailed"\)\)/);
    expect(блок).not.toMatch(/err instanceof Error \? err\.message/);
  });
});
