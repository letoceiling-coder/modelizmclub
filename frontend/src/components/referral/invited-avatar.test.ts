import { readFileSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";

/**
 * У приглашённого без фотографии — инициалы, а не значок битой картинки.
 *
 * Здесь был свой <img>, и он был сломан: атрибуты вёрстки попали внутрь
 * шаблонной строки адреса, после `seed=`. Адрес заглушки уезжал с
 * переносами строк и фигурными скобками внутри, а сам <img> оставался без
 * `width`/`height` — то есть без резерва места под картинку.
 *
 * Правка не в том, чтобы починить адрес. Общий `UserAvatar` для того и
 * заведён: он рисует инициалы, когда фотографии нет, и не ходит за
 * заглушкой к чужому серверу.
 */
const СПИСОК = join(import.meta.dirname, "InvitedFriendsSection.tsx");

describe("аватар в списке приглашённых", () => {
  const текст = readFileSync(СПИСОК, "utf8");

  it("берётся общий, а не собирается на месте", () => {
    expect(текст).toContain("UserAvatar");
    expect(текст, "остался свой <img>").not.toMatch(/<img\b/);
  });

  it("адрес картинки не собирается руками", () => {
    expect(текст, "заглушка с чужого сервера").not.toContain("dicebear");
  });

  /*
   * Прямая проверка на ту самую опечатку: атрибут JSX внутри шаблонной
   * строки. Первая проверка её не поймала бы, если бы <img> заменили на
   * что-то другое, оставив сборку адреса.
   */
  it("атрибутов вёрстки внутри строк нет", () => {
    expect(текст, "атрибут JSX оказался внутри строки").not.toMatch(
      /`[^`]*\n\s*(width|height|loading|decoding)=/,
    );
  });
});
