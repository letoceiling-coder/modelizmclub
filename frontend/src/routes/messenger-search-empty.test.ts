import { readFileSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";

/**
 * Пустой поиск и пустой мессенджер — разные ответы.
 *
 * Было одно состояние на оба случая: запрос, который ничему не совпал,
 * показывал «Нет диалогов. Начните общение в категориях или найдите
 * друзей» и кнопку «Найти друзей».
 *
 * Замер 05.10, учётка А с двумя переписками, 360 и 1280: запрос «щщщщ»
 * давал ноль строк и ровно этот текст. То есть сервис утверждал, что
 * переписок нет, когда они есть и просто не совпали, и предлагал действие
 * не из той задачи — заводить друзей вместо того, чтобы поправить запрос.
 *
 * После правки на обеих ширинах: «Ничего не найдено», в пояснении сам
 * запрос, действие «Очистить поиск». Нажатие возвращает список: 2 → 0 →
 * очистка → 2, поле пустое, исключений ноль.
 *
 * Проверяем исходник: в jsdom нет ни списка диалогов, ни запроса к API.
 * Поведение проверено замером в браузере.
 */
const ФАЙЛ = join(import.meta.dirname ?? __dirname, "messenger.tsx");

function безКомментариев(): string {
  return readFileSync(ФАЙЛ, "utf8")
    .replace(/\{\s*\/\*[\s\S]*?\*\/\s*\}/g, " ")
    .replace(/\/\*[\s\S]*?\*\//g, " ")
    .replace(/(^|[^:])\/\/.*$/gm, "$1 ");
}

describe("пустой результат поиска по диалогам", () => {
  const код = безКомментариев();

  it("пустой список при запросе и без запроса — разные ветки", () => {
    expect(код).toMatch(/filtered\.length === 0 && query\.trim\(\)/);
  });

  it("при непопавшем запросе показывается своё состояние, а не «Нет диалогов»", () => {
    expect(код).toMatch(/<EmptySearch\s+query=\{query\}/);
    expect(код).toMatch(/function EmptySearch/);
  });

  /*
   * Действие — очистить запрос. Кнопка «Найти друзей» остаётся только у
   * настоящего отсутствия переписок: предлагать её человеку, который
   * ошибся в написании, значит отвечать не на его вопрос.
   */
  it("действие очищает поиск, а не уводит искать друзей", () => {
    const блок = код.slice(
      код.indexOf("function EmptySearch"),
      код.indexOf("function EmptyDialogs"),
    );
    expect(блок).toMatch(/onClick:\s*onClear/);
    expect(блок).not.toMatch(/findFriends/);
    expect(код).toMatch(/onClear=\{\(\) => setQuery\(""\)\}/);
  });

  it("в пояснении виден сам запрос", () => {
    const блок = код.slice(
      код.indexOf("function EmptySearch"),
      код.indexOf("function EmptyDialogs"),
    );
    expect(блок).toMatch(/searchEmptyDesc.*query/s);
  });
});
