const ФАЙЛ = join(import.meta.dirname ?? __dirname, "index.tsx");

function безКомментариев(): string {
  /* Блочные комментарии — первыми: иначе выражение для JSX-комментария
     сшивает два далёких узла и съедает код между ними. */
  return readFileSync(ФАЙЛ, "utf8")
    .replace(/\/\*[\s\S]*?\*\//g, " ")
    .replace(/\{\s*\/\*[\s\S]*?\*\/\s*\}/g, " ")
    .replace(/(^|[^:])\/\/.*$/gm, "$1 ");
}

