import { readFileSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";

/**
 * Лендинг: порядок секций, шапка и подсказка прокрутки. ТЗ 2.1–2.2,
 * решения владельца D7 и D11.
 *
 * ## Порядок секций
 *
 * Было (замер 07.10, девять секций на экране, гость и вошедший одинаково):
 *
 * | № | Секция | 360 | 1280 |
 * | --- | --- | --- | --- |
 * | 0 | первый экран «МоДелизМ» | 743 | 760 |
 * | 1 | **завершающий призыв** «Сообщество, объединяющее…» | 1072 | 634 |
 * | 2 | «Что есть в МоДелизМ» | 2043 | 886 |
 * | 3 | «Популярные объявления» | 555 | 507 |
 * | 4 | «Всё, что движется и летает» | 1114 | 617 |
 * | 5 | «Три шага до сообщества» | 789 | 430 |
 * | 6 | «Простая подписка» | 546 | 785 |
 * | 7 | «Почему моделисты выбирают нас» | 1067 | 474 |
 * | 8 | «Часто спрашивают» | 629 | 612 |
 *
 * То есть предложение присоединиться стояло вторым — раньше, чем человек
 * увидел хоть что-нибудь, за чем присоединяться. По ТЗ 2.1 оно десятое.
 *
 * ## «Листайте» и стрелка
 *
 * Решение D7 велело убрать и ничем не заменять. В сессии 1 по нему было
 * записано «в исходниках слова „Листайте“ нет» — отрицательное утверждение,
 * проверенное не до конца: искали в содержимом лендинга из базы, а строка
 * лежала в словаре и выводилась только от 640 px (`hidden sm:flex`).
 * Поэтому на телефоне её не видели. Замер 07.10 до правки: на 1280
 * подсказка есть, на 360 нет; после — нет на обеих.
 *
 * ## «Как пользоваться» и «Как работает»
 *
 * Разбор D11, висевшего с сессии 1 как «по смыслу не сверял». Сверено
 * 07.10 по содержимому базы:
 *
 * | Адрес | Заголовок | Что внутри |
 * | --- | --- | --- |
 * | `/how-to-use` | «Как пользоваться» | краткий обзор и запись экрана — инструкция |
 * | `/how-it-works` | «Как работает платформа» | объяснение сервиса |
 *
 * Страницы не дублируют друг друга — это ровно те два назначения, которые
 * ТЗ 2.2 и просит различать. Сливать нечего. А вот подпись «Как работает»
 * в шапке вела не на страницу, а на якорь `#how` этого же лендинга, и
 * стояла рядом с «Как пользоваться»: одна подпись на два разных места.
 * Якорь убран, страница осталась и доступна из подвала.
 *
 * Шапка после правки — ровно пять основных ссылок ТЗ 2.2 плюс действия по
 * роли: гостю «Войти» и «Создать аккаунт», вошедшему «Кабинет».
 *
 * Проверяем исходник: порядок секций и состав шапки — это разметка, а
 * ширины и роли в jsdom не воспроизвести. Поведение проверено в браузере.
 */
const ФАЙЛ = join(import.meta.dirname ?? __dirname, "index.tsx");

function безКомментариев(): string {
  /* Блочные комментарии — первыми: иначе выражение для JSX-комментария
     сшивает два далёких узла и съедает код между ними. */
  return readFileSync(ФАЙЛ, "utf8")
    .replace(/\/\*[\s\S]*?\*\//g, " ")
    .replace(/\{\s*\/\*[\s\S]*?\*\/\s*\}/g, " ")
    .replace(/(^|[^:])\/\/.*$/gm, "$1 ");
}

describe("лендинг: порядок секций по ТЗ 2.1", () => {
  const код = безКомментариев();
  const тело = код.slice(код.indexOf("<main>"), код.indexOf("</main>"));
  const порядок = [...тело.matchAll(/<([A-Z][A-Za-z]*) \/>/g)].map((m) => m[1]);

  it("завершающий призыв — последний, а не второй", () => {
    expect(порядок.at(-1)).toBe("CommunityInvite");
    expect(порядок.indexOf("CommunityInvite")).toBeGreaterThan(порядок.indexOf("FaqSection"));
  });

  it("порядок секций — тот, что в ТЗ 2.1", () => {
    expect(порядок).toEqual([
      "Hero",
      "FirstHundredBanner",
      "QuickSections",
      "PopularListings",
      "CategoriesSection",
      "StepsTimeline",
      "PricingSection",
      "WhyChoose",
      "FaqSection",
      "CommunityInvite",
    ]);
  });
});

describe("лендинг: подсказки прокрутки нет (D7)", () => {
  const код = безКомментариев();

  it("ни слова «Листайте», ни его ключа", () => {
    expect(код).not.toMatch(/landing\.hero\.scroll/);
    expect(код).not.toMatch(/Листайте/);
  });

  /* «Ничем не заменять» — то есть и отскока вместо стрелки быть не должно. */
  it("отскока вместо стрелки тоже нет", () => {
    expect(код).not.toMatch(/animate=\{\{ y: \[0, 7, 0\] \}\}/);
    expect(код).not.toMatch(/ChevronDown/);
  });

  it("ключ убран и из словаря", () => {
    const словарь = readFileSync(
      join(import.meta.dirname ?? __dirname, "..", "lib", "i18n", "locales", "ru.ts"),
      "utf8",
    );
    expect(словарь).not.toMatch(/scroll: "Листайте"/);
  });
});

describe("лендинг: шапка — пять основных ссылок ТЗ 2.2", () => {
  const код = безКомментариев();
  /*
   * Границы среза — от объявления списка до его зависимостей. Сначала
   * конец был взят по `const [sheetOpen`, которого в этом файле нет вовсе:
   * `indexOf` вернул −1, срез вышел пустым, и проверка краснела на верном
   * коде с «expected [] to equal [пять адресов]». Тот же промах, что уже
   * был в сторожах профиля и объявления, — поэтому конец ищется по строке,
   * которая в файле точно есть, и её наличие проверяется отдельно.
   */
  const начало = код.indexOf("const navLinks");
  const конец = код.indexOf("[t, communitiesEnabled]", начало);
  const блок = код.slice(начало, конец);

  it("срез списка ссылок непустой — иначе проверки ниже ничего не значат", () => {
    expect(начало).toBeGreaterThan(-1);
    expect(конец).toBeGreaterThan(начало);
    expect(блок.length).toBeGreaterThan(200);
  });

  it("в шапке ровно пять основных ссылок", () => {
    const адреса = [...блок.matchAll(/to: "([^"]+)" as const/g)].map((m) => m[1]);
    expect(адреса).toEqual(["/how-to-use", "/ads", "/communities", "/channels", "/subscription"]);
  });

  /*
   * Якорь «Как работает» убран: одна подпись вела в два разных места.
   * Вместе с ним ушла и ветка отрисовки якорных ссылок — недостижимый
   * случай, на который tsc честно ругался.
   */
  it("якоря «Как работает» в шапке нет", () => {
    expect(блок).not.toMatch(/kind: "hash"/);
    expect(код).not.toMatch(/landing\.nav\.how"/);
    expect(код).not.toMatch(/l\.kind === "hash"/);
  });

  /* Сама секция «Три шага» остаётся целью для внешних ссылок на `#how`. */
  it("цель якоря на странице осталась", () => {
    expect(код).toMatch(/id="how"/);
  });
});
