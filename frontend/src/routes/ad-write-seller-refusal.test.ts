import { readFileSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";

/**
 * «Написать продавцу»: отказ «нужна дружба» показывается окном с кнопкой
 * «Добавить», а не строкой без действия.
 *
 * Правило владельца из сессии 4: не-друг без подписки получает окно
 * «Добавьте пользователя в друзья, чтобы написать ему» с кнопкой
 * «Добавить». На профиле и на странице друзей оно стояло — обе зовут
 * общий `FriendRequiredDialog`. Страница объявления была третьим
 * обработчиком того же отказа и про него не знала: код ответа не
 * разбирался вовсе, и `formatApiErrorMessage` показывал текст сервера
 * всплывающим сообщением.
 *
 * Замер 06.10, учётка без подписки и не друг продавца, 1280:
 *
 * | | Было | Стало |
 * | --- | --- | --- |
 * | Ответ сервера | 403 `friendship_required` | то же |
 * | Что видно | строка без кнопки | окно «Добавьте… в друзья» |
 * | Можно ли выполнить условие | **нет** | «Добавить» → заявка `4 → 8` в базе |
 *
 * Подписчику по-прежнему открывается переписка — проверено тем же замером.
 *
 * Проверяем исходник: ответ сервера и окно Radix в jsdom не поднять.
 * Поведение проверено в браузере, вплоть до строки в `friend_requests`.
 */
const ФАЙЛ = join(import.meta.dirname ?? __dirname, "ads.$id.tsx");

/*
 * Блочные комментарии снимаются ПЕРВЫМИ, и это не вкусовщина.
 *
 * В остальных сторожах порядок обратный — сперва `{/* … *\/}`, потом
 * блочные, — и там он безвреден. Здесь он съедал сам проверяемый код:
 * выражение для JSX-комментария нежадное в середине, но начало ищет самое
 * раннее подходящее, и в этом файле оно находило `{` задолго до разбора
 * отказа, а закрывалось уже после него. Проверка при этом не падала с
 * ошибкой — она просто искала в пустоте и отвечала «нет такого».
 *
 * Поймано тем, что утверждение краснело и на исправленном коде.
 */
function безКомментариев(): string {
  return readFileSync(ФАЙЛ, "utf8")
    .replace(/\/\*[\s\S]*?\*\//g, " ")
    .replace(/\{\s*\/\*[\s\S]*?\*\/\s*\}/g, " ")
    .replace(/(^|[^:])\/\/.*$/gm, "$1 ");
}

describe("отказ «нужна дружба» на странице объявления", () => {
  const код = безКомментариев();

  it("код отказа разбирается, а не показывается строкой", () => {
    expect(код).toMatch(/код === "friendship_required"/);
  });

  it("показывается то же окно, что на профиле и у друзей", () => {
    expect(код).toMatch(/<FriendRequiredDialog/);
    expect(код).toMatch(/from "@\/components\/friends\/FriendRequiredDialog"/);
  });

  /*
   * Окно без работающей кнопки — то же самое, что строка: условие названо,
   * выполнить его нельзя. Поэтому сторожим не только окно, но и заявку.
   */
  it("кнопка «Добавить» отправляет заявку в друзья", () => {
    expect(код).toMatch(/sendFriendRequest\(id\)/);
  });

  it("окно не заводится своё — берётся общий компонент", () => {
    // Своя разметка диалога здесь означала бы четвёртую копию правила.
    const свои = [...код.matchAll(/writeNeedFriendTitle/g)].length;
    expect(свои).toBe(0);
  });
});
