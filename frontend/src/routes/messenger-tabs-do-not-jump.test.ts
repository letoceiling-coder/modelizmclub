import { readFileSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";

/**
 * Лента вкладок мессенджера липнет к краям вкладок и не отдаёт жест наружу.
 *
 * Жалоба владельца 05.10: на телефоне вкладки «скачут, неудобно выглядят».
 *
 * Замер на стенде, 360 px: лента 301 px при содержимом 464 — переполнение
 * 163 px. `scroll-snap-type` был `none`, и каждая остановка пальца
 * оставляла вкладку обрезанной посередине: на 60 пикселях «Личные» и
 * «Ещё», на 120 — «Сделки». Сдвиг раскладки при этом нулевой, то есть дело
 * не в счётчиках, которые приезжают позже.
 *
 * Второе: `overscroll-behavior-x` был `auto`. Горизонтальный жест у края
 * ленты уходит странице и системе — на iOS это включает возврат назад, и
 * экран уезжает целиком, хотя человек листал вкладки.
 *
 * Проверяем исходник, а не поведение: прокрутку с привязкой в jsdom не
 * воспроизвести — там нет ни раскладки, ни инерции. Поведение проверено
 * замером в браузере, здесь сторожим, что свойства не исчезнут.
 *
 * Код читается без комментариев: иначе проверка цепляется за этот докблок
 * и за объяснение в самом messenger.tsx.
 */
const ФАЙЛ = join(import.meta.dirname ?? __dirname, "messenger.tsx");

function безКомментариев(): string {
  return readFileSync(ФАЙЛ, "utf8")
    .replace(/\{\s*\/\*[\s\S]*?\*\/\s*\}/g, " ")
    .replace(/\/\*[\s\S]*?\*\//g, " ")
    .replace(/(^|[^:])\/\/.*$/gm, "$1 ");
}

describe("вкладки мессенджера не скачут", () => {
  const код = безКомментариев();

  it("лента липнет к краям вкладок", () => {
    expect(код).toMatch(/scrollSnapType:\s*"x proximity"/);
  });

  /*
   * `proximity`, а не `mandatory`: рядом живёт эффект, который сам
   * подкручивает ленту к выбранной вкладке. При `mandatory` браузер доводил
   * бы её ещё раз после него — один жест, два движения, то есть новое
   * дрожание вместо старого.
   */
  it("привязка мягкая, иначе она подерётся с подкруткой к активной вкладке", () => {
    expect(код).not.toMatch(/scrollSnapType:\s*"x mandatory"/);
    expect(код).toMatch(/scrollIntoView|scrollTo\(\{\s*left/);
  });

  it("жест не уходит странице и системе", () => {
    expect(код).toMatch(/overscrollBehaviorX:\s*"contain"/);
  });

  it("точки привязки стоят на самих вкладках, а не только на ленте", () => {
    const точек = [...код.matchAll(/scrollSnapAlign:\s*"start"/g)].length;
    expect(точек).toBeGreaterThanOrEqual(2);
  });

  it("высота нажатия вкладки не ниже 44 px", () => {
    expect(код).toMatch(/TAP_TARGET_ROW_44/);
  });
});
