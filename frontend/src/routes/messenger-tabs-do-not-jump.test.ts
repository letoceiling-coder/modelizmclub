import { readFileSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";

/**
 * Лента вкладок мессенджера липнет к краям вкладок и не отдаёт жест наружу.
 *
 * Жалоба владельца 05.10: на телефоне вкладки «скачут, неудобно выглядят».
 *
 * Замер на стенде, 360 px: лента 301 px при содержимом 464 — переполнение
 * 163 px. `scroll-snap-type` был `none`, и каждая остановка пальца
 * оставляла вкладку обрезанной посередине: на 60 пикселях «Личные» и
 * «Ещё», на 120 — «Сделки». Сдвиг раскладки при этом нулевой, то есть дело
 * не в счётчиках, которые приезжают позже.
 *
 * Второе: `overscroll-behavior-x` был `auto`. Горизонтальный жест у края
 * ленты уходит странице и системе — на iOS это включает возврат назад, и
 * экран уезжает целиком, хотя человек листал вкладки.
 *
 * Проверяем исходник, а не поведение: прокрутку с привязкой в jsdom не
 * воспроизвести — там нет ни раскладки, ни инерции. Поведение проверено
 * замером в браузере, здесь сторожим, что свойства не исчезнут.
 *
 * Код читается без комментариев: иначе проверка цепляется за этот докблок
 * и за объяснение в самом messenger.tsx.
 */
const ФАЙЛ = join(import.meta.dirname ?? __dirname, "messenger.tsx");

function безКомментариев(): string {
  return readFileSync(ФАЙЛ, "utf8")
    .replace(/\{\s*\/\*[\s\S]*?\*\/\s*\}/g, " ")
    .replace(/\/\*[\s\S]*?\*\//g, " ")
    .replace(/(^|[^:])\/\/.*$/gm, "$1 ");
}

describe("вкладки мессенджера не скачут", () => {
  const код = безКомментариев();
  /** Тело `tabButtonStyle` — чтобы утверждения о вкладке не ловили чужой код. */
  const стиль = код.slice(код.indexOf("function tabButtonStyle"), код.indexOf("function TabLabel"));

  it("лента липнет к краям вкладок", () => {
    expect(код).toMatch(/scrollSnapType:\s*"x proximity"/);
  });

  /*
   * `proximity`, а не `mandatory`: рядом живёт эффект, который сам
   * подкручивает ленту к выбранной вкладке. При `mandatory` браузер доводил
   * бы её ещё раз после него — один жест, два движения, то есть новое
   * дрожание вместо старого.
   */
  it("привязка мягкая, иначе она подерётся с подкруткой к активной вкладке", () => {
    expect(код).not.toMatch(/scrollSnapType:\s*"x mandatory"/);
    expect(код).toMatch(/scrollIntoView|scrollTo\(\{\s*left/);
  });

  it("жест не уходит странице и системе", () => {
    expect(код).toMatch(/overscrollBehaviorX:\s*"contain"/);
  });

  it("точки привязки стоят на самих вкладках, а не только на ленте", () => {
    const точек = [...код.matchAll(/scrollSnapAlign:\s*"start"/g)].length;
    expect(точек).toBeGreaterThanOrEqual(2);
  });

  /*
   * Раньше здесь стояло `expect(код).toMatch(/TAP_TARGET_ROW_44/)`.
   *
   * Утверждение было верным по букве и вредным по существу: оно сторожило
   * накладку — псевдоэлемент `position:absolute` высотой 44 px внутри
   * кнопки высотой 32. Накладка давала зону нажатия, но вылезала за кнопку
   * на 6 px вниз, а лента объявлена `overflow-x: auto`, и этого довольно,
   * чтобы вторая ось перестала быть `visible` и тоже стала `auto`. У ленты
   * заводилась вертикальная прокрутка: 32 px при содержимом 37.
   *
   * Теперь 44 px — настоящая высота кнопки, и проверка требует её, а не
   * накладку. Это строже: прежнее утверждение проходило и при кнопке
   * высотой 32, нынешнее — нет.
   */
  it("высота нажатия вкладки не ниже 44 px и задана самой кнопке", () => {
    // Искать по всему файлу нельзя: `minHeight: 44` стоит и у поля ввода
    // переписки, и утверждение проходило бы, даже потеряй вкладка высоту.
    // Проверено откатом: без этой привязки подмена 44 на 32 не краснила.
    expect(стиль).toMatch(/minHeight:\s*44/);
    expect(код).not.toMatch(/TAP_TARGET_ROW_44/);
  });

  /*
   * Жалоба владельца 05.10, настоящий телефон: «верхний ряд категорий
   * разъезжается». Замер на стенде при ширинах 320, 360, 390 и 430 нашёл
   * три причины, и все три — число в пикселях там, где нужен запас.
   */
  describe("ряд не разъезжается", () => {
    it("у ленты ровно одна ось прокрутки", () => {
      expect(код).toMatch(/overflowY:\s*"hidden"/);
    });

    /*
     * Жёсткая высота ломается от увеличенного шрифта системы: при
     * минимальном размере шрифта 24 px подпись занимала 36 px в кнопке
     * высотой 32 и вылезала из неё вместе с подчёркиванием.
     */
    it("высота вкладки — нижний предел, а не жёсткое число", () => {
      expect(стиль).not.toMatch(/\bheight:\s*32\b/);
    });

    /*
     * Место под счётчик держит невидимая копия «99+» в той же клетке сетки.
     * Стояло `min-w-[28px]` с обещанием «место под „99+“ целиком», и
     * обещание не выполнялось: при шрифте 12 px «99+» занимает 30,1 px и
     * расширял вкладку с 99,6 до 101,7; при шрифте 19 px — 46,5 px, и
     * вкладка прыгала со 126,2 на 144,7. Любое число в пикселях — догадка
     * об одном размере шрифта.
     */
    it("ширину счётчика резервирует невидимое «99+», а не число в пикселях", () => {
      const счётчик = код.slice(
        код.indexOf("function TabCount"),
        код.indexOf("const TAB_LABEL_KEY"),
      );
      expect(счётчик).not.toBe("");
      expect(счётчик).toMatch(/invisible[^>]*\[grid-area:1\/1\][\s\S]*?99\+/);
      expect(счётчик).not.toMatch(/min-w-\[/);
    });

    /*
     * Кружок тоже не фиксируется по высоте: при шрифте 19 и 24 px цифры
     * требуют 22 и 28 px, а кружок был зажат на 18.
     */
    it("высота кружка — нижний предел", () => {
      const счётчик = код.slice(
        код.indexOf("function TabCount"),
        код.indexOf("const TAB_LABEL_KEY"),
      );
      expect(счётчик).toMatch(/min-h-\[18px\]/);
      // `(?<!min-)` обязателен: граница слова стоит и перед `h` в
      // `min-h-[18px]`, поэтому без неё проверка ловит сама себя.
      expect(счётчик).not.toMatch(/(?<!min-)h-\[18px\]/);
    });
  });
});
