import { readFileSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";

/**
 * Отметка о прочтении уходит после того, как разобрана граница
 * «Новые сообщения», а не раньше.
 *
 * Отметка двигает курсор прочитанного на последнее сообщение, а именно по
 * этому курсору считается, где начинается непрочитанное. Пока отметка шла
 * первой, граница стирала саму себя.
 *
 * Расхождение жило между двумя входами в переписку — тот самый случай, про
 * который `CLAUDE.md` говорит «прямая загрузка и переход внутри идут по
 * разным веткам». Замер 06.10, учётка А, три непрочитанных от Б, 1280:
 *
 * | Как вошли | Меток было | Стало |
 * | --- | --- | --- |
 * | прямая ссылка `?chat=` | **0** | 1, ниже неё ровно 3 |
 * | переход внутри приложения | 1 | 1, ниже неё ровно 3 |
 *
 * При переходе внутри приложения отметка сходила с рук случайно: список
 * диалогов уже загружен, и эффект границы успевал прочитать прежний курсор
 * в том же проходе. Порядок был не задан, а совпал.
 *
 * Отметка при этом **не отменена**, только отложена: после правки
 * непрочитанное гаснет на обоих входах (3 → 0, проверено замером). Это
 * важнее самой границы: не гаснущий счётчик заметят все.
 *
 * Проверяем исходник: порядок эффектов в jsdom не воспроизвести — там нет
 * ни запросов, ни разметки переписки. Поведение проверено в браузере.
 */
const ФАЙЛ = join(import.meta.dirname ?? __dirname, "messenger.tsx");

function безКомментариев(): string {
  return readFileSync(ФАЙЛ, "utf8")
    .replace(/\{\s*\/\*[\s\S]*?\*\/\s*\}/g, " ")
    .replace(/\/\*[\s\S]*?\*\//g, " ")
    .replace(/(^|[^:])\/\/.*$/gm, "$1 ");
}

describe("порядок: граница «Новые сообщения», потом отметка о прочтении", () => {
  const код = безКомментариев();

  it("отметка о прочтении идёт ровно из одного места", () => {
    const вызовов = [...код.matchAll(/messengerCache\.markRead\(/g)].length;
    // Один в отложенном эффекте, один запасной в нём же, один в списке
    // диалогов (нажатие по строке другого диалога). Было пять.
    expect(вызовов).toBeLessThanOrEqual(3);
  });

  it("разбор адреса не отмечает диалог прочитанным", () => {
    // `selectDialog` вызывается из эффекта синхронизации с `?chat=` — это
    // и есть вход по прямой ссылке.
    const блок = код.slice(
      код.indexOf("const selectDialog ="),
      код.indexOf("const byConversation"),
    );
    expect(блок).not.toMatch(/markRead/);
  });

  it("выбор диалога в списке не отмечает его сам", () => {
    const блок = код.slice(
      код.indexOf("const handleSelect ="),
      код.indexOf("const handleSelect =") + 400,
    );
    expect(блок).not.toMatch(/markRead/);
  });

  it("отметка ждёт разбора границы", () => {
    expect(код).toMatch(
      /if \(anchorResolvedFor === activeId\) \{\s*messengerCache\.markRead\(activeId\);/,
    );
  });

  /*
   * Запасной выход нужен для переписки, которой нет в списке (удалена,
   * чужая): якорю там взяться неоткуда. Но без проверки «список уже
   * загружен» он срабатывает ровно в защищаемом окне — при заходе по
   * прямой ссылке список ещё пуст, диалог «не найден», отметка уходит
   * первой. Так и случилось в первой попытке правки: метка по прямой
   * ссылке осталась нулевой, и поймал это замер, а не чтение.
   */
  it("запасной выход ждёт загрузки списка диалогов", () => {
    expect(код).toMatch(/if \(!loading && !dlgs\.some\(\(d\) => d\.id === activeId\)\)/);
  });

  it("граница отмечает, что разобрана, состоянием — иначе отметка не узнает", () => {
    expect(код).toMatch(/setAnchorResolvedFor\(activeId\)/);
  });
});
