import { existsSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";

/**
 * У проигрывателя обзора ровно один набор настроек.
 *
 * Жалоба владельца 05.10, настоящий телефон: «при нажатии на видео
 * дублируются элементы управления качеством и скоростью».
 *
 * Так и было. У `<video>` стоит `controls`, то есть движок рисует своё
 * меню, а в нём уже есть скорость воспроизведения. Поверх него висела своя
 * шестерёнка `ReviewPlayerSettings` с той же скоростью. Замер на стенде
 * (учётка-подписчик, 360 и 1280, видео в формате, который сборка умеет
 * открывать): своя кнопка «Настройки плеера» 36×36 и родные
 * `-internal-media-controls-playback-speed-button` и
 * `-internal-media-controls-overflow-button` одновременно — два набора.
 *
 * «Качество» в своей накладке выбора не предлагало вовсе: подпись и слово
 * «Авто» текстом, без единого варианта. То есть скорость дублировалась, а
 * качество обещалось и не давалось.
 *
 * Оставлены родные: они работают с клавиатуры (Enter по «Смотреть» даёт
 * проигрыватель, пробел по нему ставит на паузу — проверено), читаются
 * диктором и одинаковы на телефоне и на компьютере.
 *
 * Проверяем исходник: в jsdom нет ни раскладки, ни медиадвижка, и теневое
 * дерево родных элементов управления оттуда не видно вовсе. Поведение
 * проверено замером в браузере, здесь сторожим, что накладка не вернётся.
 */
const КОРЕНЬ = import.meta.dirname ?? __dirname;
const СТРАНИЦА = join(КОРЕНЬ, "reviews.$id.tsx");

function безКомментариев(путь: string): string {
  return readFileSync(путь, "utf8")
    .replace(/\{\s*\/\*[\s\S]*?\*\/\s*\}/g, " ")
    .replace(/\/\*[\s\S]*?\*\//g, " ")
    .replace(/(^|[^:])\/\/.*$/gm, "$1 ");
}

describe("проигрыватель обзора: один набор настроек", () => {
  const код = безКомментариев(СТРАНИЦА);

  it("родные элементы управления на месте", () => {
    // Именно они дают скорость, перемотку, звук и полноэкранный режим.
    expect(код).toMatch(/<video[\s\S]{0,400}?\bcontrols\b/);
  });

  it("своей накладки настроек над видео нет", () => {
    expect(код).not.toMatch(/PlayerSettings/);
    expect(
      existsSync(join(КОРЕНЬ, "..", "components", "reviews", "ReviewPlayerSettings.tsx")),
    ).toBe(false);
  });

  /*
   * Ключи перевода убраны вместе с накладкой: вернуть её молча, одними
   * классами, не получится — придётся вернуть и подписи, а это видно в
   * обзоре правки.
   */
  it("подписи своей накладки не вернулись в словарь", () => {
    const словарь = readFileSync(join(КОРЕНЬ, "..", "lib", "i18n", "locales", "ru.ts"), "utf8");
    expect(словарь).not.toMatch(/reviewPlayer/);
  });

  /*
   * Отдельно про скорость: это ровно то, что дублировалось. Своего выбора
   * скорости на странице быть не должно — ни списком, ни кнопками.
   */
  it("своего выбора скорости на странице нет", () => {
    expect(код).not.toMatch(/playbackRate/);
  });
});
