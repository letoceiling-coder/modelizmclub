import { readFileSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import { итогПриглашения } from "./referral";

/**
 * Подпись у приглашения говорит, что по нему начислено.
 *
 * До этой правки подпись была одна на все закрытые приглашения — «Бонус
 * начислен», — и бралась из статуса. Но статус `completed` ставится и
 * когда баллов не дали: исчерпан предел `max_paid_invites` или тот же
 * телефон уже приносил награду. Человек читал «Бонус начислен», а баланс
 * не рос.
 */
const МЕСТА = [
  join(import.meta.dirname, "..", "routes", "referral.tsx"),
  join(import.meta.dirname, "..", "components", "referral", "InvitedFriendsSection.tsx"),
  join(import.meta.dirname, "..", "components", "admin", "ReferralProgramAdminCard.tsx"),
];

const читать = (путь: string) => readFileSync(путь, "utf8");

describe("итог приглашения", () => {
  it("ждущее приглашение не обещает начисления", () => {
    const { подпись, начислено } = итогПриглашения({ status: "pending", points: 0 });

    expect(начислено).toBe(false);
    expect(подпись).toMatch(/телефон/i);
    expect(подпись).not.toMatch(/начислен/i);
  });

  it("оплаченное называет число, а не просто факт", () => {
    const { подпись, начислено } = итогПриглашения({ status: "completed", points: 100 });

    expect(начислено).toBe(true);
    expect(подпись).toContain("100");
    expect(подпись).toContain("баллов");
  });

  it("склонение считается по числу", () => {
    expect(итогПриглашения({ status: "completed", points: 1 }).подпись).toContain("1 балл");
    expect(итогПриглашения({ status: "completed", points: 2 }).подпись).toContain("2 балла");
    expect(итогПриглашения({ status: "completed", points: 11 }).подпись).toContain("11 баллов");
  });

  /*
   * Главный случай. Предел исчерпан или телефон повторился — приглашение
   * закрыто, а баллов нет. Обещать начисление здесь и было дефектом.
   */
  it("закрытое без баллов не выдаёт себя за начисленное", () => {
    const { подпись, начислено } = итогПриглашения({
      status: "completed",
      points: 0,
      listingCredits: 0,
    });

    expect(начислено).toBe(false);
    /*
     * Проверяем не отсутствие корня «начисл», а отсутствие утверждения:
     * «Без начисления» — честная подпись, и она этот корень содержит.
     * Дефектом было заявление «Начислено…» там, где не начислено.
     */
    expect(подпись).not.toMatch(/^Начислено/);
    expect(подпись).toContain("Без начисления");
  });

  /** Старые приглашения оплачены размещением, а не баллами. */
  it("старая награда размещением так и называется", () => {
    const { подпись, начислено } = итогПриглашения({
      status: "completed",
      points: 0,
      listingCredits: 1,
    });

    expect(начислено).toBe(true);
    expect(подпись).toContain("размещение");
    expect(подпись).not.toContain("балл");
  });

  /**
   * Третий канал старой награды — дни подписки.
   *
   * Прежний код (`reward_subscription_days` в настройках акции) писал их в
   * ту же строку и тем же update, что и штуки размещений. Пропустить их
   * значило бы повторить исходный дефект для третьего канала: «Без
   * начисления» там, где начислено.
   */
  it("старая награда днями подписки так и называется", () => {
    const { подпись, начислено } = итогПриглашения({
      status: "completed",
      points: 0,
      listingCredits: 0,
      subscriptionDays: 30,
    });

    expect(начислено).toBe(true);
    expect(подпись).toContain("30 дней подписки");
  });

  /** Каналов могло сработать два сразу — подпись называет оба. */
  it("две награды в одной строке не теряются", () => {
    const { подпись } = итогПриглашения({
      status: "completed",
      points: 0,
      listingCredits: 1,
      subscriptionDays: 7,
    });

    expect(подпись).toContain("1 размещение");
    expect(подпись).toContain("7 дней подписки");
  });

  it("два размещения склоняются", () => {
    expect(
      итогПриглашения({ status: "completed", points: 0, listingCredits: 2 }).подпись,
    ).toContain("2 размещения");
  });

  /**
   * Подпись одна на три места.
   *
   * Их и было три, и расходились они уже сейчас: «Ожидает подтверждения
   * телефона», «Ждёт телефон», «Бонус начислен». Третье место — админское,
   * и оно врало ровно так же.
   */
  it("все три места берут подпись из одного помощника", () => {
    for (const путь of МЕСТА) {
      const текст = читать(путь);

      /*
       * Регистр не важен: две страницы берут готовый значок
       * `<ИтогПриглашения>`, админская таблица — саму функцию
       * `итогПриглашения()`, потому что рисует её в ячейке своей вёрсткой.
       */
      expect(текст, `${путь}: подпись собирается на месте`).toMatch(/итогПриглашения/i);
      expect(текст, `${путь}: осталась подпись из одного статуса`).not.toContain("Бонус начислен");
    }
  });
});
