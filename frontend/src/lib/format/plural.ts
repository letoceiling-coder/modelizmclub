/**
 * Русское склонение по числу.
 *
 * Живёт отдельным модулем, а не рядом с компонентом: экспорт не-компонента
 * из файла с компонентами ломает горячую перезагрузку, и eslint про это
 * предупреждает. Заодно помощник пригодится не только баллам.
 */
export function склонение(n: number, одна: string, две: string, пять: string): string {
  const сто = Math.abs(n) % 100;
  const десять = сто % 10;

  // 11–14 — исключение: иначе выходит «11 балл».
  if (сто >= 11 && сто <= 14) return пять;
  if (десять === 1) return одна;
  if (десять >= 2 && десять <= 4) return две;

  return пять;
}

/** «балл», «балла», «баллов». */
export function словоБаллы(n: number): string {
  return склонение(n, "балл", "балла", "баллов");
}
