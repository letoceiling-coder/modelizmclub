/*
 * Одно правило на все страницы, где стоит панель: лента, сообщества,
 * каналы, друзья, профиль, запись.
 *
 * До 18.09 адрес зависел от варианта панели. В ленте название вело на
 * направление, а в сообществах и каналах — в тот же список с
 * `?taxonomy_id=`: «Авиация» в сообществах показывала «Вы пока не в одном
 * сообществе» (по направлению не нашлось ни одного из 19 сообществ, и
 * страница рисовала пустоту «моих»), в каналах оставляла в «Каналах». Из
 * пятнадцати направлений сообщества не находились ни в одном, каналы — в
 * двух, по одному (прод 18.09). Панель называется «Найди своих» и ведёт к
 * своим, а не сужает соседний список.
 *
 * Фильтр списка по `taxonomy_id` у сообществ и каналов остался в их
 * маршрутах — панель на него больше не ссылается (см. отчёт ветки fix/rail-unified-behavior).
 */

type RailTarget = { id: string; slug?: string };

/** Название — на страницу своего уровня: направления, комнаты, подкомнаты. */
export function railNameHref(node: RailTarget): string {
  return `/categories/${node.slug ?? node.id}`;
}

/**
 * Значок чата ведёт в чат этого уровня. Уровень у чата ровно один:
 * `ChatService::isDescendantOf` отказывает узлу без родителя, то есть
 * комната есть у подкатегории и не бывает у направления.
 *
 * Поэтому у направления значка нет — раньше он вёл на список комнат, то
 * есть туда же, куда теперь ведёт название. Две кнопки в одно место, и
 * одна из них обещает чат, которого на этом уровне не существует.
 *
 * Без `?tab=`: комната и так открывается чатом, а параметр со значением по
 * умолчанию дал бы той же странице второй адрес.
 */
export function railChatHref(node: RailTarget): string {
  return `/categories/${node.slug ?? node.id}`;
}

/** «Все посты направления» внутри раскрытого узла — отбор ленты. */
export function railFilterHref(id: string): string {
  return `/feed?taxonomy_id=${id}`;
}
