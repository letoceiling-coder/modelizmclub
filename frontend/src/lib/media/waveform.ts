/**
 * Столбики для голосового сообщения, когда настоящей огибающей нет.
 *
 * Сервер огибающую не считает, а рисовать ровную полоску — значит показать
 * пользователю нечто, похожее на тишину. Здесь детерминированный шум от
 * идентификатора сообщения: у одного и того же сообщения рисунок всегда
 * одинаковый, у разных — разный.
 *
 * Название `makeMockWaveform` сохранено: функция используется в боевом
 * режиме, а не только в демо, и переименование задело бы четыре места без
 * пользы. Жила она в `lib/mock` и тянула за собой весь файл с демо-данными
 * в главный чанк — см. комментарий в lib/user-registry.
 */
export function makeMockWaveform(seed: number): number[] {
  const bars = 32;
  const out: number[] = [];
  let s = seed;
  for (let i = 0; i < bars; i++) {
    s = (s * 9301 + 49297) % 233280;
    const n = s / 233280;
    out.push(0.25 + n * 0.75);
  }
  return out;
}
