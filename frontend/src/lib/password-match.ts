/**
 * Состояние поля «Повторите пароль» — решение Ж1 от 09.10.
 *
 * До правки о несовпадении человек узнавал только после нажатия «Создать
 * аккаунт», и то всплывающим сообщением поверх страницы: замер 09.10 на
 * 360 px показал, что при пароле `Parol1234!` и повторе `Parol1234?` на
 * экране нет ни текста со словом «совпада», ни красной рамки, ни
 * `aria-invalid` — поле выглядит так же, как верно заполненное.
 *
 * Правило отделено от разметки, потому что мест с повтором пароля три:
 * регистрация, восстановление и смена пароля в настройках. Одно правило на
 * три формы — иначе через месяц они разойдутся.
 *
 * Состояния и когда какое:
 *
 * | Состояние  | Когда                                        | Что на экране            |
 * | ---------- | -------------------------------------------- | ------------------------ |
 * | `empty`    | повтор пуст                                  | ничего                   |
 * | `typing`   | повтор совпадает с началом пароля            | ничего, поле нейтрально  |
 * | `mismatch` | повтор расходится с паролем                  | рамка и «Пароли не совпадают» |
 * | `match`    | повтор равен паролю                          | «Пароли совпадают»       |
 *
 * `left` — человек ушёл из поля (blur). Уход с неполным повтором тоже даёт
 * `mismatch`: пока курсор в поле, недобранный повтор — это ещё набор, а не
 * ошибка, и краснеть на каждой букве значит обвинять человека в том, что он
 * ещё печатает.
 *
 * Пустой повтор при уходе остаётся `empty`, а не краснеет: человек,
 * прошедший поле насквозь, ничего не ввёл неверно. Незаполненность ловится
 * отправкой формы — там она названа как незаполненность, а не как
 * несовпадение.
 */
export type PasswordMatchState = "empty" | "typing" | "mismatch" | "match";

export function passwordMatchState(
  password: string,
  confirmation: string,
  options: { left?: boolean } = {},
): PasswordMatchState {
  if (confirmation === "") return "empty";
  if (confirmation === password) return "match";
  // Повтор — начало пароля: человек ещё печатает. Уход из поля превращает
  // «ещё печатает» в «не дописал».
  if (password.startsWith(confirmation)) return options.left ? "mismatch" : "typing";
  return "mismatch";
}
