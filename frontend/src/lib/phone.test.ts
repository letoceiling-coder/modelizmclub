import { describe, expect, it } from "vitest";
import { formatRuPhone, isPhoneComplete, phoneDigits, phoneDigitsLeft, phoneE164 } from "./phone";

/**
 * Таблица примеров — контракт решения Ж2.
 *
 * Те же самые строки проверяет `backend/tests/Unit/PhoneNormalizerTest.php`:
 * пункт 6 решения требует, чтобы сервер приводил номер к тому же виду по
 * тому же правилу и чтобы тесты на сервере и клиенте шли по одним примерам.
 * Правя эту таблицу, правьте и ту — иначе два правила снова разойдутся, как
 * до 09.10.
 */
const ПОЛНЫЕ: Array<[string, string]> = [
  // [что ввели или вставили, что должно получиться]
  ["9384100024", "+79384100024"],
  ["79384100024", "+79384100024"],
  ["89384100024", "+79384100024"],
  ["+79384100024", "+79384100024"],
  ["+7 938 410-00-24", "+79384100024"],
  ["8 (938) 410-00-24", "+79384100024"],
  ["938 410 00 24", "+79384100024"],
  ["+7(938)410-00-24", "+79384100024"],
  ["8-938-410-00-24", "+79384100024"],
  ["  +7 938 410 00 24  ", "+79384100024"],
  // Лишние цифры отбрасываются (пункт 3 решения).
  ["93841000241", "+79384100024"],
  ["893841000249", "+79384100024"],
  // Номер со снимка владельца.
  ["+79384100024", "+79384100024"],
];

const НЕПОЛНЫЕ: string[] = [
  "",
  "+",
  "+7",
  "7",
  "8",
  "9",
  "938",
  "938410002", // девять цифр
  "8938410002", // приставка плюс девять цифр
];

describe("решение Ж2: десять цифр после приставки +7", () => {
  it.each(ПОЛНЫЕ)("«%s» даёт %s", (ввод, ожидание) => {
    expect(phoneE164(ввод)).toBe(ожидание);
    expect(isPhoneComplete(ввод)).toBe(true);
    expect(phoneDigitsLeft(ввод)).toBe(0);
  });

  it("все полные примеры дают один и тот же номер", () => {
    const разные = new Set(ПОЛНЫЕ.map(([ввод]) => phoneE164(ввод)));
    expect(разные, "примеры должны сходиться в один номер").toEqual(new Set(["+79384100024"]));
  });

  it.each(НЕПОЛНЫЕ)("«%s» — номер неполон, на сервер не уходит", (ввод) => {
    expect(phoneE164(ввод)).toBeNull();
    expect(isPhoneComplete(ввод)).toBe(false);
  });

  describe("приставка видна и не стирается", () => {
    it("пустое поле показывает +7", () => {
      expect(formatRuPhone("")).toBe("+7");
    });

    it("стирание всего не убирает приставку", () => {
      // Человек выделил всё и нажал Delete: в обработчик приходит пустая
      // строка, а поле обязано остаться с «+7».
      expect(formatRuPhone("")).toBe("+7");
      expect(formatRuPhone("+7")).toBe("+7");
    });

    it("«8» и «7» в пустом поле уходят в приставку, а не в номер", () => {
      expect(formatRuPhone("8")).toBe("+7");
      expect(formatRuPhone("7")).toBe("+7");
      expect(phoneDigits("8")).toBe("");
      expect(phoneDigits("7")).toBe("");
    });

    it("«9» становится первой цифрой номера", () => {
      expect(formatRuPhone("9")).toBe("+7 (9");
      expect(phoneDigits("9")).toBe("9");
    });

    it("«+» сам по себе игнорируется", () => {
      expect(formatRuPhone("+")).toBe("+7");
      expect(phoneDigits("+")).toBe("");
    });
  });

  describe("набор поверх своей приставки", () => {
    /*
     * В поле уже стоит «+7», и в обработчик приходит приставка вместе с
     * набранным. Замер 09.10 показал, что без отдельного снятия приставки
     * правило съедало её семёрку, а набранная восьмёрка становилась первой
     * цифрой номера: «89384100024» давало «+7 (893) 841-00-02».
     */
    const набор: Array<[string, string]> = [
      ["+78", "+7"], // восьмёрка поверх приставки уходит в приставку
      ["+77", "+7"], // семёрка — тоже
      ["+79", "+7 (9"], // девятка становится первой цифрой
      ["+7+", "+7"], // плюс игнорируется
      ["+7 ", "+7"], // пробел тоже
      ["+789384100024", "+7 (938) 410-00-24"], // вставка 11 цифр поверх приставки
      ["+79384100024", "+7 (938) 410-00-24"], // вставка 10 цифр поверх приставки
      ["+7 (938) 410-00-24", "+7 (938) 410-00-24"], // уже отформатированное
    ];
    it.each(набор)("«%s» показывается как %s", (ввод, вид) => {
      expect(formatRuPhone(ввод)).toBe(вид);
    });

    it("посимвольный набор 89384100024 поверх приставки даёт верный номер", () => {
      // Так печатает человек: каждый знак дописывается к тому, что в поле.
      let поле = formatRuPhone("");
      for (const знак of "89384100024") поле = formatRuPhone(поле + знак);
      expect(поле).toBe("+7 (938) 410-00-24");
      expect(phoneE164(поле)).toBe("+79384100024");
    });

    it("посимвольный набор 79384100024 поверх приставки даёт тот же номер", () => {
      let поле = formatRuPhone("");
      for (const знак of "79384100024") поле = formatRuPhone(поле + знак);
      expect(phoneE164(поле)).toBe("+79384100024");
    });

    it("посимвольный набор +7 938 410-00-24 даёт тот же номер", () => {
      let поле = formatRuPhone("");
      for (const знак of "+7 938 410-00-24") поле = formatRuPhone(поле + знак);
      expect(phoneE164(поле)).toBe("+79384100024");
    });

    it("посимвольный набор десяти цифр даёт тот же номер", () => {
      let поле = formatRuPhone("");
      for (const знак of "9384100024") поле = formatRuPhone(поле + знак);
      expect(phoneE164(поле)).toBe("+79384100024");
    });
  });

  describe("вид по мере набора", () => {
    const шаги: Array<[string, string]> = [
      ["9", "+7 (9"],
      ["93", "+7 (93"],
      ["938", "+7 (938)"],
      ["9384", "+7 (938) 4"],
      ["938410", "+7 (938) 410"],
      ["9384100", "+7 (938) 410-0"],
      ["93841000", "+7 (938) 410-00"],
      ["938410002", "+7 (938) 410-00-2"],
      ["9384100024", "+7 (938) 410-00-24"],
    ];
    it.each(шаги)("«%s» показывается как %s", (ввод, вид) => {
      expect(formatRuPhone(ввод)).toBe(вид);
    });
  });

  describe("сколько цифр не хватает", () => {
    it("пустое поле — десять", () => {
      expect(phoneDigitsLeft("")).toBe(10);
    });
    it("после приставки всё ещё десять", () => {
      expect(phoneDigitsLeft("8")).toBe(10);
    });
    it("девять цифр — одна", () => {
      expect(phoneDigitsLeft("938410002")).toBe(1);
    });
    it("полный номер — ноль", () => {
      expect(phoneDigitsLeft("9384100024")).toBe(0);
    });
  });

  it("десятизначный номер, начатый с 8, набрать нельзя — и это записано", () => {
    /* Парный тест на сервере — `test_расхождение_с_полем_десять_цифр_начатых_с_восьмёрки`
       в `backend/tests/Unit/PhoneNormalizerTest.php`: там записано, что
       сервер такой номер принимает. Единственное расхождение двух правил, и
       оно названо с обеих сторон. */
    /*
     * Городской петербургский 8123456789: первая 8 уходит в приставку, и
     * остаётся девять цифр. Сервер такой номер принимает, то есть поле
     * строже сервера — но строже ровно на номер, на который нельзя
     * прислать SMS. Решения владельца нет, вопрос в MORNING.md.
     *
     * Проверка стоит здесь не как одобрение, а чтобы расхождение было
     * видно в прогоне, а не всплыло жалобой.
     */
    expect(phoneDigits("8123456789")).toBe("123456789");
    expect(isPhoneComplete("8123456789")).toBe(false);
    // Одиннадцатью цифрами тот же номер вводится без потерь.
    expect(phoneE164("78123456789")).toBe("+78123456789");
  });
});
