import { readFileSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";

/**
 * Первый кадр списка каналов не зависит от модульного кэша.
 *
 * `/channels` бросала «Hydration failed because the server rendered HTML
 * didn't match the client» — по одному исключению на загрузку, у гостя и у
 * вошедшего одинаково.
 *
 * Механизм ровно тот, которому `CLAUDE.md` посвящает отдельное правило:
 * «модульное состояние (реестры, кэши, сторы) на сервере не копится между
 * запросами: процесс Node живёт сутками, и ответ одному посетителю не
 * должен зависеть от предыдущего. Так 14.09 падала страница канала после
 * страницы сообщества — только на прогретом сервере».
 *
 * Здесь `channelsCache` — модульная `let`, и писал в неё `fetchChannels`,
 * которую загрузчик маршрута зовёт **и на сервере**. После первого запроса
 * кэш оставался тёплым и возвращал пустой массив. Пустой массив истинный,
 * поэтому `useState(() => !getCachedChannels(...))` давало на сервере
 * `loading === false`, а в браузере, где кэш пуст, — `true`.
 *
 * Расхождение видно глазами: сервер рисовал пустое состояние, браузер на
 * первом кадре — скелеты. Замер 06.10: серверная разметка три запроса
 * подряд содержала пустое состояние; dev-сборка назвала узел —
 * `className="flex flex-col gap-[8px]"` против
 * `className="flex flex-col items-center…"`.
 *
 * После правки: ноль расхождений на `/channels` у обеих ролей, в том числе
 * при заходе сразу после `/communities` — том самом «прогретом» случае. И
 * ноль на обходе 16 маршрутов × 2 роли.
 *
 * Проверяем исходник: гидрацию в jsdom не воспроизвести — там нет ни
 * серверной отрисовки, ни второго прохода.
 */
const ФАЙЛ = join(import.meta.dirname ?? __dirname, "channels.ts");

function безКомментариев(): string {
  return readFileSync(ФАЙЛ, "utf8")
    .replace(/\/\*[\s\S]*?\*\//g, " ")
    .replace(/(^|[^:])\/\/.*$/gm, "$1 ");
}

describe("первый кадр списка каналов", () => {
  const код = безКомментариев();
  const хук = код.slice(код.indexOf("export function useChannels"));

  it("признак загрузки берётся из данных загрузчика, а не из кэша", () => {
    expect(хук).toMatch(/useState\(первыйКадр\.length === 0\)/);
    // В инициализаторах состояния кэша быть не должно вовсе.
    const инициализаторы = [...хук.matchAll(/useState\([^)]*\)/g)].map((m) => m[0]);
    expect(инициализаторы.length).toBeGreaterThan(0);
    for (const и of инициализаторы) expect(и).not.toMatch(/getCachedChannels/);
  });

  it("посев кэша не идёт в теле рендера", () => {
    const доЭффекта = хук.slice(0, хук.indexOf("useEffect"));
    expect(доЭффекта).not.toMatch(/seedChannelsCache/);
    expect(хук).toMatch(/seedChannelsCache/);
  });

  /*
   * Кэш браузерный. Без этой проверки правка выше чинит только симптом:
   * сервер продолжал бы копить состояние между запросами, и следующая
   * страница, читающая тот же кэш, повторила бы историю.
   */
  it("кэш не пишется на сервере", () => {
    /*
     * Границу блока берём по следующей функции, а не по комментарию
     * `// ---- hooks ----`: комментарии здесь сняты, и якорь по нему
     * давал -1. И отрицание должно быть привязано к этому блоку:
     * присвоение `channelsCache = { taxonomyId, list }` законно живёт в
     * `seedChannelsCache`, и проверка по всему файлу краснела на
     * исправленном коде.
     *
     * Вторая попытка была не лучше: я снимал guard подстановкой и проверял
     * отсутствие голого присвоения — но без guard строка ровно голым
     * присвоением и становится, то есть проверка опровергала сама себя.
     * Теперь просто: каждое присвоение кэшу должно стоять за проверкой на
     * браузер. Оба раза поймано тем, что утверждение краснело на
     * исправленном коде.
     */
    const нач = код.indexOf("export async function fetchChannels");
    const кон = код.indexOf("export function", нач + 10);
    const fetchБлок = код.slice(нач, кон > нач ? кон : undefined);
    const присвоения = fetchБлок.split("\n").filter((l) => /channelsCache\s*=\s*\{/.test(l));
    expect(присвоения.length).toBeGreaterThan(0);
    // Каждое присвоение кэшу — за проверкой на браузер.
    for (const строка of присвоения) {
      expect(строка).toMatch(/typeof window !== "undefined"/);
    }
  });
});
