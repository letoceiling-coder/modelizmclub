import type { Dialog } from "@/lib/mock";

/**
 * Чат попадает во вкладку «Сделки» ровно тогда, когда за ним стоит сделка из
 * раздела «Сделки»: безопасная (у неё свой тип чата) или обычная, отмеченная
 * продавцом. Вкладка и раздел — одно и то же.
 *
 * Раньше сюда попадал и любой личный чат с объявлением — вопрос «ещё
 * продаётся?» считался сделкой. Замер 16.09 на проде: у 9 из 10 человек со
 * сделками число во вкладке не совпадало с разделом. Такие чаты теперь в
 * «Личных», карточка объявления в них остаётся.
 */
export function isDealDialog(d: Pick<Dialog, "type" | "ordinaryDeal">): boolean {
  return d.type === "deal" || Boolean(d.ordinaryDeal);
}
