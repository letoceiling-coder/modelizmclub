/*
 * Правая панель направлений — по маршруту, а не по вкусу страницы.
 *
 * Правило от 11.09: панель есть на ленте, в сообществах, каналах и друзьях;
 * её нет в мессенджере, обзорах, каталоге объявлений, моих объявлениях,
 * избранном, настройках и балансе.
 *
 * До этого каждая страница решала сама (`rightColumn={false}`), и одна и та
 * же страница решала по-разному: у друзей, сообщества, канала, профиля и
 * чужого профиля ветки загрузки, «не найдено» и гостевой заглушки шли без
 * панели, а основная — с ней. Скелетон, ожидание маршрута и экран ошибки
 * рисовали панель всегда — даже по дороге в мессенджер. Теперь ответ один на
 * адрес, и оболочка берёт его сама: страница, её скелетон и её ошибка
 * получают одну раскладку.
 *
 * Страницы вне правила сохраняют то, что было: профиль, чужой профиль,
 * уведомления и рефералы — с панелью. Запись `/post/…` тоже с панелью: её
 * открывают из ленты, и карточка остаётся той же ширины, что в ленте. Всё
 * остальное — без панели, центр на всю оставшуюся ширину.
 */
const WITH_RAIL: readonly RegExp[] = [
  /^\/feed(\/|$)/,
  // список и страница сообщества, но не форма создания
  /^\/communities(\/(?!new(\/|$)).*)?$/,
  /^\/channels\/?$/,
  /^\/channel\/[^/]+/,
  /^\/friends(\/|$)/,
  /^\/post\/[^/]+/,
  /^\/profile(\/|$)/,
  /^\/user\/[^/]+/,
  /^\/notifications(\/|$)/,
  /^\/referral(\/|$)/,
];

export function hasDirectionsRail(pathname: string): boolean {
  return WITH_RAIL.some((re) => re.test(pathname));
}
