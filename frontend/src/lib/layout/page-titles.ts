/*
 * Заголовок первого уровня для страниц, у которых его нет на экране.
 *
 * Аудит 04.10 прошёл по 55 открытым маршрутам прода: на одиннадцати не было
 * ни одного `<h1>`. Среди них лента, мессенджер, профиль, сделки, друзья,
 * обзоры и настройки — то есть почти весь вход для вошедшего.
 *
 * Чтение с экрана строит по заголовкам оглавление страницы и прыгает по ним
 * командой. Страница без `<h1>` в этом оглавлении начинается ниоткуда: куда
 * человек попал, становится понятно только из адресной строки.
 *
 * Видимый заголовок сюда не годится. У ленты его нет намеренно — она
 * начинается с записей, как и задумано, — и дорисовать «Лента» над ними
 * значит поменять вид страницы ради ориентира, который нужен не глазами.
 * Поэтому заголовок есть в разметке и скрыт визуально (`sr-only`).
 *
 * Таблица по адресу, а не проп у страницы, — по тому же доводу, что у правой
 * колонки в `rails.ts`: ответ один на адрес, и оболочка берёт его сама. Иначе
 * скелетон, ожидание маршрута и экран ошибки остались бы без заголовка, хотя
 * это те же страницы.
 *
 * Страницы с видимым `<h1>` сюда не попадают — иначе их заголовок удвоится.
 * Заголовок бывает не в самом файле маршрута, а в компоненте, который тот
 * отрисовывает: так /profile получил второй `<h1>` — свой из `ProfileView`
 * и скрытый отсюда. Проверка исходников файла маршрута этого не видит,
 * поймал замер на стенде 05.10. Отсюда правило: страницу вносят в таблицу
 * после замера в браузере, а не после чтения одного файла.
 * За этим следит `page-titles.test.ts`: он читает исходники маршрутов и
 * краснеет, если страница из таблицы завела себе видимый заголовок. Так из
 * первоначального списка выпали `/friends`, `/deals`, `/reviews/upload` и
 * `/communities/new`: заголовок у них есть, просто гость его не видит —
 * вместо содержимого там заслон входа. Замер гостем показал бы их пустыми,
 * и без этой проверки они получили бы второй заголовок у вошедшего.
 *
 * Переадресации (`/safe-deals`, `/wallet`, `/balance`) здесь не нужны: своей
 * страницы у них нет, они уводят на другую.
 *
 * `/settings` сюда тоже не годится, и это стоило отдельного замера. Адрес
 * оболочка берёт у своего совпадения маршрута, а у дочерних страниц настроек
 * оно равно родительскому `/settings` — правило `^\/settings\/?$` срабатывало
 * и на `/settings/wallet`, и там выходило два заголовка: скрытый «Настройки»
 * и свой. Поэтому у страницы настроек заголовок стоит в ней самой.
 */
export const PAGE_TITLES: readonly (readonly [RegExp, string])[] = [
  [/^\/feed\/?$/, "nav.feed"],
  [/^\/messenger\/?$/, "nav.messenger"],
  [/^\/reviews\/?$/, "nav.reviews"],
  [/^\/channels\/new\/?$/, "pages.channels.createChannel"],
];

/** Ключ перевода для скрытого заголовка страницы, либо null — у неё свой. */
export function pageTitleKey(pathname: string): string | null {
  // Более узкое правило раньше общего: /reviews/upload до /reviews.
  for (const [re, key] of [...PAGE_TITLES].sort(
    (a, b) => b[0].source.length - a[0].source.length,
  )) {
    if (re.test(pathname)) return key;
  }
  return null;
}
