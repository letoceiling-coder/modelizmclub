/**
 * Нажатие на свой аватар в шапке: открыть профиль или меню.
 *
 * Аватар — кнопка меню Radix, и меню у мыши открывается наведением
 * (useHoverDropdown). Нажатие Radix понимал как «переключить меню» и
 * закрывал уже открытое наведением: на проде 17.09 наведение → меню
 * открыто, нажатие → меню закрыто, адрес остался /feed. Профиль по аватару
 * не открывался никак.
 *
 * Мышью нажатие ведёт в профиль — меню она уже видела наведением. Касание
 * и перо наведения не знают, им нажатие по-прежнему открывает меню (в нём
 * первым пунктом «Профиль»); клавиатура идёт через Enter/Space, которые
 * Radix обрабатывает сам.
 */
export function avatarPressOpensProfile(e: {
  pointerType: string;
  button: number;
  ctrlKey: boolean;
}): boolean {
  return e.pointerType === "mouse" && e.button === 0 && !e.ctrlKey;
}
