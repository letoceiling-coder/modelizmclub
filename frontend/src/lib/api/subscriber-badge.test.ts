import { describe, expect, it } from "vitest";
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { mapApiUser } from "@/lib/api/auth";

/*
 * Значок «Pro» в шапке профиля.
 *
 * Разметка была написана под поле `user.subscription`, которого не
 * заполнял ни один маппер: `mapApiUser` его не ставил, `/auth/me` не
 * отдавал, публичный профиль тоже. Условие было ложным всегда, и ни один
 * подписчик отметки не получал. Найдено разбором 03.10.
 *
 * Поэтому здесь две проверки разной природы: маппер — что признак с
 * сервера доезжает до модели; чтение разметки — что разметка смотрит
 * именно на него. Без второй маппер можно починить, а значок останется
 * привязан к мёртвому полю, и тест будет зелёным.
 */
describe("признак подписчика доезжает от сервера до модели", () => {
  const базовый = { uuid: "u-1", id: 1, email: "a@b.c" };

  it("is_subscriber: true становится isSubscriber", () => {
    expect(mapApiUser({ ...базовый, is_subscriber: true }).isSubscriber).toBe(true);
  });

  it("без поля в ответе признака нет", () => {
    expect(mapApiUser(базовый).isSubscriber).toBe(false);
  });

  it("льгота «подписка не требуется» подписчиком не делает", () => {
    const u = mapApiUser({ ...базовый, subscription_exempt: true });
    expect(u.subscriptionExempt).toBe(true);
    expect(u.isSubscriber).toBe(false);
  });
});

describe("шапка профиля смотрит на признак, а не на мёртвое поле", () => {
  // Путь от каталога теста, а не от cwd: иначе проверка зависит от того,
  // откуда запущен vitest.
  const разметка = readFileSync(
    join(import.meta.dirname, "../../components/profile/ProfileView.tsx"),
    "utf8",
  );

  it("условие значка — user.isSubscriber", () => {
    expect(разметка).toContain("{user.isSubscriber && (");
  });

  it("на user.subscription разметка больше не опирается", () => {
    expect(разметка).not.toContain("user.subscription &&");
  });
});

/**
 * Подпись значка — действующий тариф, а не слово «Pro».
 *
 * Жалоба владельца 06.10: у имени «Pro», а тариф — «Год». Это не придирка к
 * слову: «Pro» — НАЗВАНИЕ ДРУГОГО ТАРИФА. В `subscription_plans` их пять:
 * Базовый, Pro (499 ₽ / 30 дней), Месяц, Полгода, Год. То есть значок
 * называл чужой тариф, и дороже действительного.
 *
 * Замер 06.10, учётка подписчика на тарифе «Год»:
 *
 * | Где | Было | Стало |
 * | --- | --- | --- |
 * | свой профиль | «Pro» | «Год», подсказка «Подписка „Год“» |
 * | чужой профиль (смотрит другой человек) | «Pro» | «Подписка» |
 *
 * На чужом профиле тариф не показывается намеренно: сервер отдаёт только
 * признак `is_subscriber`, и раскрывать посторонним, сколько человек
 * заплатил, никто не просил. Нейтральное «Подписка» верно при любом тарифе
 * и ни одному не противоречит.
 */
describe("значок у имени называет действующий тариф", () => {
  const разметка = readFileSync(
    join(import.meta.dirname, "../../components/profile/ProfileView.tsx"),
    "utf8",
  )
    .replace(/\/\*[\s\S]*?\*\//g, " ")
    .replace(/\{\s*\/\*[\s\S]*?\*\/\s*\}/g, " ")
    .replace(/(^|[^:])\/\/.*$/gm, "$1 ");

  it("слова «Pro» в разметке нет", () => {
    expect(разметка).not.toMatch(/<BadgeCheck size=\{10\} \/> Pro/);
  });

  it("подпись берётся из тарифа: badge_label, иначе название", () => {
    expect(разметка).toMatch(
      /свояПодписка\?\.plan\?\.badge_label \?\? свояПодписка\?\.plan\?\.name/,
    );
  });

  /*
   * Тариф спрашивается только на своём профиле. `useMySubscription` вернул бы
   * НАШУ подписку, и на чужом профиле значок показывал бы наш тариф — хуже
   * прежнего «Pro».
   */
  it("на чужом профиле тариф не показывается", () => {
    expect(разметка).toMatch(/const подписьТарифа = isOwn/);
    expect(разметка).toMatch(/planBadgeFallback/);
  });
});

/**
 * Подсказка у каждого значка свёрнутой колонки.
 *
 * Обход 06.10 на 768, 1024 и 1280: у всех четырнадцати значков навигации
 * `title` есть, и только у кнопки «Развернуть меню» его не было — она одна в
 * ряду молчала под курсором. `aria-label` диктору её называл, подсказки не
 * давал.
 */
describe("свёрнутая колонка: подсказки у значков", () => {
  const колонка = readFileSync(
    join(import.meta.dirname, "../../components/layout/Sidebar.tsx"),
    "utf8",
  );

  it("у кнопки свернуть/развернуть есть подсказка", () => {
    const блок = колонка.slice(
      колонка.indexOf("const toggle ="),
      колонка.indexOf("const groups ="),
    );
    expect(блок).toMatch(/title=\{t\(next \? "nav\.expandMenu" : "nav\.collapseMenu"\)\}/);
  });

  it("у значков навигации подсказка остаётся", () => {
    expect(колонка).toMatch(/title=\{compact \? t\(labelKey\) : undefined\}/);
  });
});
