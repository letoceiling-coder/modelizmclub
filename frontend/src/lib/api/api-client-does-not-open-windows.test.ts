import { describe, expect, it } from "vitest";
import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

/**
 * Ответ сервера не открывает окон. Решение З3 от 09.10.
 *
 * `lib/api/client.ts` рассылал `modelizm:access-gate` на каждый неудачный
 * запрос с кодом `phone_not_verified` или `subscription_required`. Запрос
 * мог быть фоновым — счётчик непрочитанного, чат сообщества, закладки, —
 * и тогда окно всплывало поверх страницы само собой, без единого нажатия.
 * Человек закрывал, следующий фоновый запрос открывал снова. Это четвёртая
 * жалоба владельца, и ровно та же регрессия случилась 07.09 (`CLAUDE.md`,
 * «Проверять до выкатки, а не после»).
 *
 * Проверка смотрит исходный файл, а не поведение, и это сознательно.
 * Поведение здесь не воспроизвести честно: событие рассылается из перехвата
 * `fetch` в обработке неуспешного ответа, и чтобы до него добраться, надо
 * подменить сеть, токен и `window` — то есть проверять подмену, а не код.
 * А вопрос простой и ровно про текст: рассылает этот модуль события доступа
 * или нет. Ср. `deploy/scripts/check-empty-catch.sh` — там та же мера для
 * пустых `catch`.
 */
describe("lib/api/client", () => {
  const source = readFileSync(fileURLToPath(new URL("./client.ts", import.meta.url)), "utf8");

  it("не рассылает событие доступа", () => {
    const code = source
      .split("\n")
      .filter((line) => !line.trimStart().startsWith("*"))
      .filter((line) => !line.trimStart().startsWith("//"))
      .filter((line) => !line.trimStart().startsWith("/*"))
      .join("\n");

    expect(
      code,
      "Ответ сервера снова открывает окно доступа. По решению З3 окно открывает " +
        "нажатие, а не ответ: фоновый запрос не знает, что человек хотел сделать, " +
        "и подтверждение номера ему ничего не даёт.",
    ).not.toContain("modelizm:access-gate");
  });

  it("код отказа остаётся доступен вызывающему", () => {
    // Окна нет, но причина отказа должна доходить до места, где её можно
    // показать словами: `ApiError` несёт тело ответа целиком.
    expect(source).toContain("new ApiError(res.status");
  });
});
