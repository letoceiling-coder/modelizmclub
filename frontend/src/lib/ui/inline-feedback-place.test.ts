import { describe, expect, it } from "vitest";
import { разместитьОтклик } from "@/lib/ui/inline-feedback-place";

const экран = { width: 400, height: 800 };
const подпись = { width: 160, height: 28 };

describe("место отклика у кнопки", () => {
  it("по умолчанию над кнопкой и по её центру", () => {
    const м = разместитьОтклик({ top: 300, left: 200, width: 32, height: 32 }, подпись, экран);
    expect(м.top).toBe(300 - 28 - 8);
    // Центр кнопки 216, половина подписи 80.
    expect(м.left).toBe(136);
  });

  /*
   * Ради этого случая и написано: кнопка «в избранное» стоит в правом
   * верхнем углу карточки, и у верхних карточек списка над ней места нет.
   * Подпись уехала бы за экран — то есть отклик есть, а человек его не
   * видит, и на глаз это неотличимо от «ничего не произошло».
   */
  it("у верхнего края переезжает под кнопку", () => {
    const м = разместитьОтклик({ top: 10, left: 200, width: 32, height: 32 }, подпись, экран);
    expect(м.top).toBe(10 + 32 + 8);
  });

  it("у правого края прижимается, а не вылезает", () => {
    // Кнопка в правом верхнем углу карточки, подпись шире её втрое.
    const м = разместитьОтклик({ top: 300, left: 360, width: 32, height: 32 }, подпись, экран);
    expect(м.left).toBe(400 - 160 - 8);
    expect(м.left + подпись.width).toBeLessThanOrEqual(экран.width);
  });

  it("у левого края тоже прижимается", () => {
    const м = разместитьОтклик({ top: 300, left: 4, width: 32, height: 32 }, подпись, экран);
    expect(м.left).toBe(8);
  });

  it("подпись шире экрана прижимается к левому полю, а не уходит в минус", () => {
    // Узкий телефон и длинная подпись: отрицательный left увёл бы текст за
    // край, и начало фразы стало бы нечитаемым.
    const м = разместитьОтклик(
      { top: 300, left: 10, width: 32, height: 32 },
      { width: 500, height: 28 },
      экран,
    );
    expect(м.left).toBe(8);
  });

  it("вырожденно низкий экран: подпись прижата к нижнему полю", () => {
    /*
     * Прежняя проверка здесь была зелёной на пустом месте: при кнопке внизу
     * подпись уходит вверх, и нижняя отсечка не задействована вовсе.
     *
     * Задействовать её можно только на экране в пару сотен пикселей — это не
     * телефон, а встроенный кадр или окно, ужатое до полосы. Отсечка и
     * держится как сторож для таких случаев, а не как рабочий путь: без неё
     * подпись ушла бы за нижний край.
     */
    const узкий = { width: 400, height: 80 };
    const м = разместитьОтклик({ top: 4, left: 200, width: 32, height: 40 }, подпись, узкий);
    expect(м.top).toBe(узкий.height - подпись.height - 8);
    expect(м.top + подпись.height).toBeLessThanOrEqual(узкий.height);
  });
});
