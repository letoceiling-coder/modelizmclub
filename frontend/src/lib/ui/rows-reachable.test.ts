import { readFileSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";

/**
 * До каждого элемента любой горизонтальной строки можно дойти мышью.
 * Решение Е3 от 06.10.
 *
 * Жалоба владельца: ряд вкладок профиля обрезан справа, мышью до остальных
 * вкладок не добраться. Обход всех строк вкладок и фильтров показал класс,
 * а не одно место. Замер 06.10, вошедший, колесо мыши над строкой:
 *
 * | Где | Ширина | Переполнение | Колесо | Стрелки |
 * | --- | --- | --- | --- | --- |
 * | профиль, вкладки | 360 | 746 px | нет | нет |
 * | профиль, вкладки | 1280 | 501 px | нет | нет |
 * | лента, фильтры | 360 | 180 px | нет | нет |
 * | обзоры, фильтры | 360 | 75 px | нет | нет |
 * | мои объявления | 360 | 431 px | есть | нет |
 * | мои объявления | 1280 | 113 px | есть | нет |
 * | сообщения, разделы | 360 | 172 px | есть | нет |
 *
 * Пальцем все семь листались родной прокруткой — поэтому на телефоне
 * ничего не заметно, а мышью часть элементов была недостижима вовсе.
 *
 * Стало (06.10, профиль, восемь вкладок):
 *
 * | Способ | 360 | 768 | 1024 | 1280 |
 * | --- | --- | --- | --- | --- |
 * | только мышь (стрелки) | 8/8 | 8/8 | 8/8 | 8/8 |
 * | только клавиатура | 8/8 | — | — | 8/8 |
 * | только касание | листается | — | — | — |
 *
 * Колесо на правом краю отдаёт прокрутку странице: 0 → 300 на всех четырёх
 * ширинах. Нажатие по дальней вкладке работает — маска края нажатий не
 * перехватывает. При пальце стрелки скрыты.
 *
 * Поведение самого `wheelScrollTarget` проверяет `scroll-row.test.ts`;
 * здесь — что общая оснастка на месте и что её применили ВЕЗДЕ, а не в
 * одном профиле. Раскладки в jsdom нет, 746 и 302 там не получить.
 */
const КОРЕНЬ = join(import.meta.dirname ?? __dirname, "..", "..");

function читать(путь: string): string {
  /* Блочные комментарии — первыми: иначе выражение для JSX-комментария
     сшивает два далёких узла и съедает код между ними. */
  return readFileSync(join(КОРЕНЬ, путь), "utf8")
    .replace(/\/\*[\s\S]*?\*\//g, " ")
    .replace(/\{\s*\/\*[\s\S]*?\*\/\s*\}/g, " ")
    .replace(/(^|[^:])\/\/.*$/gm, "$1 ");
}

/** Все строки, которые замер нашёл переполненными, и их файлы. */
const СТРОКИ: { где: string; путь: string }[] = [
  {
    где: "вкладки сущности (профиль, сообщество, канал, направление)",
    путь: "components/entity/EntityTabs.tsx",
  },
  { где: "фильтры ленты", путь: "components/feed/FeedFilterTabs.tsx" },
  { где: "полоса my-ads и похожих объявлений", путь: "components/ui/HorizontalScrollNav.tsx" },
  { где: "разделы сообщений", путь: "routes/messenger.tsx" },
  { где: "категории обзоров", путь: "routes/reviews.index.tsx" },
  { где: "вкладки друзей", путь: "routes/friends.tsx" },
];

describe("общая оснастка листания", () => {
  const оснастка = читать("lib/ui/scroll-row.ts");

  it("края считаются в одном месте", () => {
    expect(оснастка).toMatch(/export function useRowEdges/);
    expect(оснастка).toMatch(/const слева = row\.scrollLeft > 1;/);
    expect(оснастка).toMatch(/new ResizeObserver\(пересчитать\)/);
  });

  /*
   * Состав ряда меняется позже размеров — и это не то же самое.
   *
   * У обзоров категории приезжают запросом: на первом кадре в ряду одна
   * кнопка, переполнения нет. Потом приходят категории, ряд переполняется
   * на 75 px, а `ResizeObserver` молчит — сам ряд во всю ширину, его размер
   * не изменился, а новых детей он не слушает. Замер 06.10 на `/reviews`
   * 360: маска и `overflow-y` на месте, стрелок ноль.
   */
  it("замечает элементы, пришедшие запросом", () => {
    expect(оснастка).toMatch(/new MutationObserver/);
    expect(оснастка).toMatch(/состав\.observe\(row, \{ childList: true \}\)/);
  });

  /*
   * Шаг — до следующего элемента, а не на долю ширины. С шагом 70 % на 360
   * «Приглашённые» (136 px при ряде 302) не оказывались целиком видны ни на
   * одной остановке: 7 вкладок из 8.
   */
  it("стрелка листает до следующего элемента", () => {
    expect(оснастка).toMatch(/el\.offsetLeft \+ el\.offsetWidth > правый - 1/);
    expect(оснастка).not.toMatch(/clientWidth \* 0\.7/);
  });

  /*
   * Узел ряда может появиться позже первого кадра. `/friends` до разбора
   * сессии рисует гостевую заглушку, и `ref.current` в эффекте монтирования
   * равен null — эффект после этого не прицеплялся никогда: ни колеса, ни
   * стрелок, хотя ряд на экране был и страница работала.
   *
   * Поймано инструментом: запись внутри пересчёта краёв не появилась ни
   * разу, тогда как сам хук вызывался 18 раз. Выполнялось тело, но не
   * эффект.
   */
  it("прицепляется к ряду, пришедшему позже первого кадра", () => {
    expect(оснастка).toMatch(/function useRowNode/);
    expect(оснастка).toMatch(/if \(ref\.current !== узел\) setУзел\(ref\.current\);/);
    /* Эффекты висят на узле, а не на ссылке: ссылка не меняется никогда. */
    expect(оснастка).not.toMatch(/\}, \[ref, пересчитать/);
    expect(оснастка).not.toMatch(/\}, \[ref, \.\.\.deps\]/);
  });

  /* Подчёркивание вкладки — отдельный ребёнок с `position: absolute`, и шаг
     «до следующего» уводил бы к нему, а не к следующей вкладке. */
  it("накладки не считаются элементами ряда", () => {
    expect(оснастка).toMatch(/getComputedStyle\(el\)\.position !== "absolute"/);
  });

  it("затухание — маской, а не накладкой", () => {
    expect(оснастка).toMatch(/linear-gradient\(to right, transparent 0/);
  });

  /*
   * Колесо на краю отдаёт прокрутку странице. В `wheelScrollTarget` это
   * `null`, и единственный `preventDefault` стоит ПОСЛЕ проверки на null —
   * иначе упёршийся ряд съедал бы прокрутку страницы.
   */
  it("колесо на краю не отменяет событие", () => {
    expect(оснастка).toMatch(/if \(maxScroll <= 0\) return null;/);
    const обработчик = оснастка.slice(
      оснастка.indexOf("const onWheel"),
      оснастка.indexOf("let pointerId"),
    );
    expect(обработчик.indexOf("if (target === null) return;")).toBeGreaterThan(0);
    expect(обработчик.indexOf("if (target === null) return;")).toBeLessThan(
      обработчик.indexOf("e.preventDefault()"),
    );
  });
});

describe("стрелки по краям", () => {
  const стрелки = читать("components/ui/ScrollRowArrows.tsx");

  it("только для точного указателя — пальцу они не нужны", () => {
    expect(стрелки).toMatch(/pointer-fine:grid/);
    expect(стрелки).toMatch(/hidden w-7/);
  });

  it("вне обхода клавиатурой: у неё свои стрелки, Home и End", () => {
    expect(стрелки).toMatch(/aria-hidden/);
    expect(стрелки).toMatch(/tabIndex=\{-1\}/);
  });
});

describe("оснастку применили во всех переполненных строках", () => {
  it.each(СТРОКИ)("$где", ({ путь }) => {
    const код = читать(путь);
    expect(код).toMatch(/useRowEdges/);
    expect(код).toMatch(/<ScrollRowArrows/);
    /*
     * Вторая ось задана явно. При `overflow-x: auto` и `overflow-y: visible`
     * CSS вычисляет вторую ось как `auto`, строка становится вертикальным
     * прокручиваемым узлом, и Chromium съедает ПЕРВОЕ колесо на её краю:
     * замер 06.10, 1280, три колеса по 300 — было 0, 300, 600 вместо
     * 300, 600, 900.
     */
    expect(код).toMatch(/overflow-y-hidden|overflowY: "hidden"/);
  });

  /*
   * Второй реализации нет. Своё колесо держали `HorizontalScrollNav`
   * (и отменяло любое вертикальное движение, то есть съедало прокрутку
   * страницы на краю) и сам мессенджер — свой счёт краёв слово в слово.
   */
  it.each(СТРОКИ)("$где — без своего колеса и своего счёта краёв", ({ путь }) => {
    const код = читать(путь);
    expect(код).not.toMatch(/addEventListener\("wheel"/);
    expect(код).not.toMatch(/scrollWidth - row\.clientWidth/);
  });
});

describe("вкладки: клавиатура и семантика", () => {
  const вкладки = читать("components/entity/EntityTabs.tsx");

  /* Было: роли стояли, а поведения при них не было — разметка обещала
     диктору навигацию, которой не существовало. */
  it("роли и стрелки клавиатуры на месте", () => {
    expect(вкладки).toMatch(/role="tablist"/);
    expect(вкладки).toMatch(/role="tab"/);
    expect(вкладки).toMatch(/aria-selected=\{isActive\}/);
    expect(вкладки).toMatch(/e\.key === "Home"/);
    expect(вкладки).toMatch(/e\.key === "End"/);
    expect(вкладки).toMatch(/tabIndex=\{isActive \? 0 : -1\}/);
  });

  it("выбранная вкладка сама входит в видимую область", () => {
    expect(вкладки).toMatch(/row\.scrollTo\(\{ left: Math\.max\(0, left\), behavior \}\)/);
  });
});
