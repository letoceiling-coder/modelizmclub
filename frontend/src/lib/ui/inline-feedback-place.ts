/**
 * Где показать отклик у кнопки.
 *
 * Отдельной чистой функцией: ошибка в расчёте даёт подпись за краем экрана —
 * то есть отклик есть, а человек его не видит, и на глаз это неотличимо от
 * «ничего не произошло».
 */

export interface Прямоугольник {
  top: number;
  left: number;
  width: number;
  height: number;
}

export interface Место {
  top: number;
  left: number;
  /** Подпись над кнопкой или под ней. */
  снизу: boolean;
}

/** Зазор между кнопкой и подписью. */
const ЗАЗОР = 8;

/** Отступ от края экрана: вплотную подпись читается плохо. */
const ПОЛЯ = 8;

export function разместитьОтклик(
  кнопка: Прямоугольник,
  подпись: { width: number; height: number },
  экран: { width: number; height: number },
): Место {
  /*
   * Сверху, если там есть место. Снизу — только когда сверху не помещается:
   * у кнопки в шапке или у верхнего края карточки подпись иначе уехала бы за
   * экран.
   */
  const сверхуHelp = кнопка.top - подпись.height - ЗАЗОР;
  const снизу = сверхуHelp < ПОЛЯ;
  const top = снизу ? кнопка.top + кнопка.height + ЗАЗОР : сверхуHelp;

  /*
   * По центру кнопки, но не за краем. Кнопка «в избранное» стоит в правом
   * верхнем углу карточки, и подпись «Убрано из избранного» шире её втрое —
   * без прижатия половина текста оказывалась бы за экраном.
   */
  const поЦентру = кнопка.left + кнопка.width / 2 - подпись.width / 2;
  const максимум = Math.max(ПОЛЯ, экран.width - подпись.width - ПОЛЯ);
  const left = Math.min(Math.max(поЦентру, ПОЛЯ), максимум);

  return {
    top: Math.min(Math.max(top, ПОЛЯ), Math.max(ПОЛЯ, экран.height - подпись.height - ПОЛЯ)),
    left,
    снизу,
  };
}
