/**
 * Показать узел и поставить в него фокус — для первого проблемного места формы.
 *
 * Решение Ж1 от 09.10 требует, чтобы нажатие по «Создать аккаунт» при
 * незаполненной форме не только называло каждое незаполненное место, но и
 * прокручивало первое из них в видимую область. На телефоне это не
 * украшение: замер на 360×640 показал, что форма регистрации выше окна, и
 * при открытой клавиатуре видно от трёх до четырёх полей из шести. Назвать
 * ошибку у поля, которого не видно, — то же самое, что не назвать.
 *
 * Прокрутка и фокус разделены намеренно. `focus()` сам прокручивает, но
 * прижимает узел к краю окна — под клавиатурой или под полосой согласия на
 * cookie. Поэтому сначала `scrollIntoView` с `block: "center"`, затем
 * `focus({ preventScroll: true })`, который фокус ставит, а прокрутку не
 * трогает.
 *
 * `prefers-reduced-motion` уважается: плавная прокрутка при включённой
 * настройке — ровно то, от чего человек её включил.
 */
export function revealAndFocus(el: HTMLElement | null | undefined): boolean {
  if (!el) return false;

  const плавно =
    typeof window !== "undefined" &&
    !(window.matchMedia?.("(prefers-reduced-motion: reduce)").matches ?? false);

  el.scrollIntoView?.({ block: "center", behavior: плавно ? "smooth" : "auto" });
  el.focus?.({ preventScroll: true });
  return true;
}
