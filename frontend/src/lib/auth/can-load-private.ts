import { getToken } from "@/lib/api/client";
import { isDemoMode } from "@/lib/demo-mode";

/**
 * Стоит ли вообще начинать загрузку личных данных.
 *
 * Гость на денежных страницах видит их под окном входа — так задумано:
 * `requireAuth` намеренно не уводит на /login, страница открывается сама,
 * как только вход удался. Но загрузка при этом всё равно начиналась.
 *
 * Аудит 04.10, гостем: `/settings/wallet` отправлял три запроса и получал
 * три 401 (`/wallet`, `/wallet/transactions`, `/bonus-points`),
 * `/settings/requisites` — два, `/settings/payment-methods` — один. Шесть
 * заведомо отказных запросов и шесть красных строк в консоли на каждое
 * открытие: отказы перестают значить что-либо, когда они ожидаемы.
 *
 * Зовётся из эффектов, поэтому `getToken()` здесь уместен: расхождения
 * гидрации в эффекте не бывает. В разметке нужен `useHasToken()`.
 *
 * Демо-режим проходит без токена намеренно: `fetchWalletBalance` и соседи
 * сами отдают демо-значения, и отключить их значило бы показать пустой
 * кошелёк там, где должен быть пример.
 */
export function canLoadPrivateData(): boolean {
  return isDemoMode() || Boolean(getToken());
}
