import { useCallback, useRef } from "react";

/**
 * Ключ идемпотентности одной попытки оплаты.
 *
 * Бэкенд по этому ключу узнаёт повтор: `PaymentRecorder::createPending` при
 * совпадении ключа и пользователя возвращает уже созданный платёж, а
 * `VtbPaymentGateway` — уже открытый заказ в банке, не создавая второго.
 * Работает это ровно до тех пор, пока ключ у повторного вызова тот же.
 *
 * До 08.09 в `lib/api/payment.ts` и `lib/api/wallet.ts` жили две одинаковые
 * функции `newIdempotencyKey()`, возвращавшие свежий `crypto.randomUUID()` на
 * каждый вызов. Комментарий над ними обещал защиту от двойного нажатия —
 * со случайным ключом на каждый вызов такой защиты не существует: два нажатия
 * дают два разных ключа, бэкенд видит две несвязанные попытки и честно
 * открывает два заказа в банке. На проде так накопилось 44 висящих `pending`,
 * старейший от 19.07.
 *
 * Ключ должен переживать повторный вызов внутри одной попытки и меняться,
 * когда попытка новая. Что считать новой попыткой, решает `scope` —
 * строка, описывающая, за что платят: другой тариф, другая сумма, другое
 * объявление. Плюс явный `reset()` после успеха.
 */

/** Одна попытка: за что платят и какой ключ ей выдан. */
export interface PaymentAttempt {
  scope: string;
  key: string;
}

/** Свежий ключ. UUID, где он есть; иначе время плюс случайный хвост. */
export function newPaymentKey(): string {
  const c = globalThis.crypto;
  if (c && typeof c.randomUUID === "function") return c.randomUUID();
  return `pay-${Date.now()}-${Math.random().toString(36).slice(2)}`;
}

/**
 * Ключ для текущей попытки: прежний, пока область та же.
 *
 * Чистая функция — состояние держит вызывающий, поэтому её можно проверить
 * без React и без сети. `mint` подменяется в тестах.
 */
export function keyForScope(
  current: PaymentAttempt | null,
  scope: string,
  mint: () => string = newPaymentKey,
): PaymentAttempt {
  if (current !== null && current.scope === scope) return current;

  return { scope, key: mint() };
}

/**
 * Ключ попытки оплаты, живущий в компоненте.
 *
 * `key(scope)` вызывается в обработчике нажатия и возвращает один и тот же
 * ключ, сколько бы раз по кнопке ни нажали, — пока не изменилась область и
 * пока не позвали `reset()`. Область передаётся в момент нажатия, а не при
 * вызове хука: способ оплаты и сумма часто выбираются тем же нажатием.
 *
 * Хранится в `ref`, а не в состоянии, по двум причинам: ключ не влияет на
 * разметку, и он нужен синхронно внутри обработчика — обновление состояния
 * к этому моменту ещё не применилось бы, и второе нажатие успело бы
 * прочитать пустое значение.
 *
 * `reset()` зовётся после успеха — то есть когда попытка завершилась и
 * следующая должна стать отдельным платежом, — и при осознанном отказе:
 * человек закрыл окно оплаты, чтобы начать заново. Уход на страницу банка
 * сбрасывать не нужно: компонент размонтируется, ref умирает вместе с ним, и
 * вернувшийся с оплаты человек начинает с чистого ключа.
 */
export function usePaymentAttempt(): {
  key: (scope: string) => string;
  reset: () => void;
} {
  const attempt = useRef<PaymentAttempt | null>(null);

  const key = useCallback((scope: string) => {
    attempt.current = keyForScope(attempt.current, scope);

    return attempt.current.key;
  }, []);

  const reset = useCallback(() => {
    attempt.current = null;
  }, []);

  return { key, reset };
}
