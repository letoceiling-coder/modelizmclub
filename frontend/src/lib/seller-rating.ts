/**
 * Показывать ли рейтинг продавца и как его читать.
 *
 * Одно правило на все места, где рейтинг выводится: карточка продавца на
 * странице объявления и карточка списка в каталоге. До C5 правило стояло
 * в одном месте и звучало как «рейтинг больше нуля», а число отзывов не
 * учитывало — то есть продавец без единого отзыва мог показать звёзды,
 * если бы рейтинг откуда-то взялся ненулевым.
 */

/**
 * Рейтинг показывается, только когда за ним стоят отзывы.
 *
 * Ноль рядом со звездой читается как плохая оценка, а не как «оценок
 * пока нет» — это разные ответы, и второй вернее.
 */
export function hasSellerRating(rating: number, reviews: number | undefined): boolean {
  return rating > 0 && (reviews ?? 0) > 0;
}

/** «4,9» — с запятой, как принято в русском тексте. */
export function formatSellerRating(rating: number): string {
  return rating.toFixed(1).replace(".", ",");
}

/** Склонение: 1 отзыв, 2 отзыва, 5 отзывов, 11 отзывов. */
export function reviewsNoun(n: number): string {
  const сотня = n % 100;
  if (сотня >= 11 && сотня <= 14) return "отзывов";
  switch (n % 10) {
    case 1:
      return "отзыв";
    case 2:
    case 3:
    case 4:
      return "отзыва";
    default:
      return "отзывов";
  }
}
