/**
 * Российский номер телефона: одно правило на весь проект.
 *
 * Решение Ж2 от 09.10: человек вводит **десять цифр** после постоянной
 * приставки «+7». Как бы он ни начал — с 8, с 7, с +7 или с 9, — получается
 * один и тот же номер.
 *
 * Правило лежит отдельно от поля ввода, потому что телефон вводится в пяти
 * местах: окно подтверждения номера, настройки аккаунта, реквизиты,
 * мастер объявления, админка. До 09.10 правило было в двух видах —
 * `formatRuPhone` в компоненте поля и `PhoneNormalizer::normalize` на
 * сервере, — а окно подтверждения номера (то самое, со снимка владельца)
 * не пользовалось ни одним: там стоял обычный `<input type="tel">`, куда
 * уходило ровно то, что набрал человек.
 *
 * ## Правило
 *
 * 1. Из строки берутся только цифры.
 * 2. Первая цифра 7 или 8 считается приставкой и отбрасывается — так
 *    написано в решении Ж2. Это работает и при наборе («8» в пустом поле не
 *    становится первой цифрой номера), и при вставке 11-значного номера.
 * 3. Остаются первые десять цифр; лишние отбрасываются.
 * 4. Номер полон при ровно десяти цифрах. Храним и отправляем как
 *    `+7` плюс эти десять цифр.
 *
 * ## Чего правило сознательно не умеет
 *
 * Десятизначный номер, начинающийся с 8, — например городской
 * петербургский `8123456789` — набрать десятью цифрами нельзя: первая 8
 * уйдёт в приставку, и останется девять цифр. Вставить его можно
 * одиннадцатью (`78123456789`). Сервер такой номер принимает
 * (`PhoneNormalizer` допускает любые `+7` и десять цифр), то есть правило
 * поля строже серверного — но строже ровно на номер, на который нельзя
 * прислать SMS, а поле существует для подтверждения по SMS. Решения
 * владельца по городским номерам нет; вопрос вынесен в MORNING.md.
 */

/** Сколько цифр в номере после приставки +7. */
export const PHONE_DIGITS = 10;

/**
 * Десять цифр номера из любой строки. Возвращает от нуля до десяти цифр —
 * неполный номер это не ошибка, а состояние набора.
 */
export function phoneDigits(raw: string): string {
  const строка = String(raw ?? "");

  /*
   * Своя приставка снимается до разбора цифр.
   *
   * Поле показывает «+7» всегда, и это «+7» приходит в обработчик вместе с
   * набранным. Если не снять его отдельно, правило пункта 2 съест семёрку
   * приставки, а набранная человеком восьмёрка станет первой цифрой номера:
   * замер 09.10 в окне подтверждения номера дал на «89384100024» вид
   * «+7 (893) 841-00-02» вместо «+7 (938) 410-00-24».
   *
   * Снимается именно литерал «+7», а не любая семёрка: в строке без
   * приставки («89384100024» из буфера) снимать нечего, и правило пункта 2
   * работает как написано.
   */
  const остаток = строка.startsWith("+7") ? строка.slice(2) : строка;

  let digits = остаток.replace(/\D/g, "");
  // Пункт 2 правила: приставка в десять цифр не попадает.
  if (digits.startsWith("7") || digits.startsWith("8")) digits = digits.slice(1);
  return digits.slice(0, PHONE_DIGITS);
}

/** Номер набран полностью. */
export function isPhoneComplete(raw: string): boolean {
  return phoneDigits(raw).length === PHONE_DIGITS;
}

/**
 * Вид для показа: `+7 (9XX) XXX-XX-XX`, с приставкой всегда на месте.
 *
 * Пустой ввод даёт `+7` — приставка видна и не стирается. До 09.10 пустое
 * поле было пустым, и приставка появлялась только после первой цифры.
 */
export function formatRuPhone(raw: string): string {
  const d = phoneDigits(raw);
  let out = "+7";
  if (d.length > 0) out += ` (${d.slice(0, 3)}`;
  if (d.length >= 3) out += ")";
  if (d.length > 3) out += ` ${d.slice(3, 6)}`;
  if (d.length > 6) out += `-${d.slice(6, 8)}`;
  if (d.length > 8) out += `-${d.slice(8, 10)}`;
  return out;
}

/**
 * Вид для сервера и хранения: `+79XXXXXXXXX`. `null`, пока номер неполон —
 * отправлять половину номера незачем.
 */
export function phoneE164(raw: string): string | null {
  const d = phoneDigits(raw);
  return d.length === PHONE_DIGITS ? `+7${d}` : null;
}

/** Сколько цифр ещё не хватает. Ноль — номер полон. */
export function phoneDigitsLeft(raw: string): number {
  return PHONE_DIGITS - phoneDigits(raw).length;
}
