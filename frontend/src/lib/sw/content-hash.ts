/**
 * Содержимое файла зашито в его имя — обновлять нечего.
 *
 * Сборка даёт файлам имена вида `PostCard-jC9uqpiM.js`: хеш содержимого внутри
 * имени. Изменилось содержимое — изменился адрес. Значит ответ из кеша по этому
 * адресу устареть не может **никогда**, и перепроверка в сети — чистая потеря.
 *
 * Замерено на проде 03.10. Два перехода на `/feed` дали три полные волны
 * запросов по тем же тридцати семи файлам: кеш отвечал, а `fetch` всё равно
 * уходил. Вес набора — 479 КБ в сжатом виде, и столько же уходило лишним
 * трафиком на каждый просмотр страницы. Браузер при этом девять раз ругался
 * «preload is found, but is not used because it is a cross-world service worker
 * resource mismatch» — предзагрузка документа не сходилась с запросом
 * worker'а, то есть первый заход качал эти файлы дважды.
 *
 * Докблок `sw.ts` при этом прямо называл их «файлы с хешем в имени» — знание
 * было, вывод из него не сделан.
 *
 * Отдельным модулем, а не внутри `sw.ts`: верхний уровень worker'а читает
 * `self.__WB_MANIFEST`, которого вне worker'а нет, и проверке пришлось бы его
 * подделывать. Чистая функция в своём файле проверяется без подделок.
 */
export function hasContentHash(pathname: string): boolean {
  if (!pathname.startsWith("/assets/")) return false;

  const name = pathname.slice(pathname.lastIndexOf("/") + 1);

  /*
   * Имя из восьми и более знаков хеша перед расширением: `что-то-<хеш>.ext`.
   * Хеш у vite — base64url, то есть буквы, цифры, `-` и `_`.
   *
   * Правило узкое намеренно. Всё, что не опознано, остаётся на
   * stale-while-revalidate: у `/pwa/иконок` и прочего без хеша адрес не
   * меняется вместе с содержимым, и кеш навсегда пришпилил бы старое.
   */
  return /-[A-Za-z0-9_-]{8,}\.[a-z0-9]+$/.test(name);
}
