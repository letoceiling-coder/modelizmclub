import type { ID, User } from "@/lib/mock";

/**
 * Реестр пользователей, приходящих из API: авторы, продавцы, собеседники.
 *
 * Раньше жил в `lib/mock` вместе с демо-данными, и из-за этого весь файл на
 * 108 КБ попадал в главный чанк боевой сборки. Импортировали оттуда всего
 * семь значений — остальные сто с лишним импортов были типами, которые
 * стираются, — но выбросить массивы сборщик не мог: `ads` строится вызовом
 * `rawAds.map(...)` на уровне модуля, а вызов Rollup считает потенциально
 * нечистым и оставляет весь граф. Та же ловушка, что была с иконками.
 *
 * Здесь только рантайм: ни одного демо-объекта, ни одной вымышленной
 * личности.
 */
const users: Record<ID, User> = {};

/**
 * Нейтральная заглушка вместо неизвестного пользователя.
 *
 * Именно нейтральная, а не демо-личность: неразрешённый автор показывается
 * как «Пользователь», а не как выдуманный человек с именем и городом.
 */
const placeholder = (id: ID): User => ({
  id,
  name: "Пользователь",
  city: "",
  interests: "",
  avatar: "",
});

/**
 * Дописать в реестр то, что стало известно.
 *
 * Принимает часть записи, а не всю: функция и так сливает новое поверх
 * прежнего, и требовать полного `User` было бы требованием данных, которых у
 * вызывающего нет. Присутствие знает про человека только идентификатор и
 * то, в сети ли он; карточка объявления — имя и аватар; профиль — всё
 * остальное. Прежняя сигнатура требовала `User` целиком, и три вызова из
 * `realtime/presence` не проходили проверку типов.
 *
 * `id` обязателен — по нему и складывается запись.
 */
export function registerUser(user: Partial<User> & { id: ID }): void {
  if (!user?.id) return;
  users[user.id] = { ...placeholder(user.id), ...users[user.id], ...user };
}

export const userById = (id: ID): User => users[id] ?? placeholder(id);
