/**
 * Подогреть моноширинный шрифт, пока браузер свободен.
 *
 * IBM Plex Mono (`--font-mono`) на первом экране ленты не встречается, и
 * браузер не качает его, пока шрифт не понадобится. Понадобился он впервые
 * после перехода — в мессенджере, где им набрано время: первый кадр метки
 * рисовался запасным моноширинным, потом приезжал Plex Mono другой ширины.
 * Прижатая вправо метка «сегодня в 17:14» вырастала с 86 до 99 px и
 * сдвигала свой левый край — CLS на переходе /feed → /messenger (замер
 * 11.09, 375: файлы шрифта запрошены через 60 мс после клика).
 *
 * Не preload в <head>: первый экран шрифт не использует, и тянуть его
 * наравне с тем, что на экране, значило бы отнимать у первой отрисовки.
 * Здесь — после загрузки, в простое. Текст с кириллицей и латиницей:
 * fontsource режет начертание по алфавитам, и грузится только то
 * подмножество, чьи символы переданы.
 */
const SAMPLE = "сегодня вчера 0123456789 Aa";

let warmed = false;

export function warmMonoFont(): void {
  if (warmed || typeof document === "undefined" || !document.fonts?.load) return;
  warmed = true;
  const load = () => {
    void document.fonts.load('400 11px "IBM Plex Mono"', SAMPLE).catch(() => {
      /* шрифт не приехал — метка покажется запасным, как раньше */
    });
  };
  // requestIdleCallback нет в Safari до 18 — там просто с задержкой.
  if (typeof window.requestIdleCallback === "function") {
    window.requestIdleCallback(load, { timeout: 3000 });
  } else {
    setTimeout(load, 1500);
  }
}
