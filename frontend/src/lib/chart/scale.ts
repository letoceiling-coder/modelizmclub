/**
 * Разметка вертикальной шкалы столбчатого графика.
 *
 * Живёт отдельным модулем, а не рядом с компонентом: экспорт не-компонента
 * из файла с компонентами ломает горячую перезагрузку, и eslint про это
 * предупреждает. Заодно шкала — чистая функция, и её можно проверить
 * прогоном, а не чтением.
 */

/**
 * Верх шкалы и деления.
 *
 * Верх округляется вверх до круглого, иначе самый высокий столбик упирается
 * в край и выглядит обрезанным. Деления — по диапазону, а не «всегда пять»:
 * при максимуме в три подписи 0…3 честнее, чем 0, 0,6, 1,2 — дробных
 * регистраций не бывает.
 */
export function разметка(data: Array<{ count: number }>): { максимум: number; деления: number[] } {
  const наибольшее = data.reduce((m, т) => Math.max(m, т.count), 0);

  if (наибольшее === 0) {
    // Ни одной регистрации за месяц — шкала всё равно нужна, иначе поле пустое.
    return { максимум: 1, деления: [0, 1] };
  }

  const шаг = круглыйШаг(наибольшее);
  const верх = Math.ceil(наибольшее / шаг) * шаг;
  const деления: number[] = [];
  for (let v = 0; v <= верх; v += шаг) деления.push(v);

  return { максимум: верх, деления };
}

/** Шаг деления: 1, 2, 5, 10, 20, 50… — чтобы подписи читались с ходу. */
export function круглыйШаг(наибольшее: number): number {
  const целевых = 4;
  const грубый = наибольшее / целевых;
  const порядок = Math.pow(10, Math.floor(Math.log10(Math.max(грубый, 1))));
  const нормаль = грубый / порядок;
  const множитель = нормаль <= 1 ? 1 : нормаль <= 2 ? 2 : нормаль <= 5 ? 5 : 10;

  return Math.max(1, множитель * порядок);
}
