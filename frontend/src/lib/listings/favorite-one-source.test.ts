import { readFileSync, readdirSync, statSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { describe, expect, it } from "vitest";

/**
 * Избранное объявления переключается одним способом.
 *
 * ЗАЧЕМ ТЕСТ ПО ИСХОДНИКАМ, а не по поведению. Рендера компонентов в этом
 * наборе нет, да и проверять надо не поведение одной карточки, а то, что
 * второй реализации не появилось. Аудит 03.10 нашёл именно это: логика
 * переключения была написана трижды почти слово в слово (`CatalogCard`,
 * `routes/index.tsx`, `routes/ads.$id.tsx`), а в `AdCard` стояла четвёртая,
 * сломанная — `useState(false)` без стора и без сервера.
 *
 * Поведение каждой копии проверить можно; то, что копий больше не будет, —
 * нельзя. Отсюда проверка на запрет: кто напишет пятую, узнает об этом здесь,
 * а не через полгода, когда она разойдётся с остальными.
 */
/*
 * Через `fileURLToPath`, а не `.pathname`: каталог проекта называется
 * по-русски, и `pathname` отдаёт его percent-кодировкой —
 * `/Users/neeklo/%D0%BC%D0%BE...`, по которой `readdirSync` не находит ничего.
 */
const SRC = fileURLToPath(new URL("../..", import.meta.url));

/**
 * Единственные места, которым позволено звать запись избранного напрямую:
 * сам клиент API, хук и возобновление действия после входа.
 */
const РАЗРЕШЁННЫЕ = [
  "lib/api/listings.ts",
  "lib/listings/use-favorite-ad.ts",
  "lib/gate/resumable.ts",
];

/**
 * Кто имеет право рисовать кнопку «в избранное» без хука — и почему.
 *
 * Список, а не правило по признакам: отличить «держит состояние у себя» от
 * «получает его пропсом» регулярным выражением надёжно нельзя, а ошибка в
 * обе стороны одинаково плоха — ложная находка учит отключать проверку,
 * пропуск возвращает ту же поломку. Новый файл в списке — осознанное
 * решение, а не недосмотр.
 */
const БЕЗ_ХУКА_ПО_ДЕЛУ: Record<string, string> = {
  // Панель действий на странице объявления: `saved` и `onToggleSave` приходят
  // пропсами из `routes/ads.$id.tsx`, своего состояния нет.
  "components/ads/AdActionPanel.tsx": "получает отметку и обработчик пропсами",
  // Витрина оформления: кнопки без поведения, нажимать нечего.
  "routes/admin.design-system.tsx": "показывает вид кнопки, а не её работу",
};

function исходники(каталог: string): string[] {
  const найдено: string[] = [];

  for (const имя of readdirSync(каталог)) {
    const путь = join(каталог, имя);

    if (statSync(путь).isDirectory()) {
      найдено.push(...исходники(путь));
    } else if (/\.tsx?$/.test(имя) && !имя.includes(".test.") && !имя.endsWith(".d.ts")) {
      найдено.push(путь);
    }
  }

  return найдено;
}

const все = исходники(SRC)
  .filter((путь) => !путь.endsWith("routeTree.gen.ts"))
  .map((путь) => ({
    имя: путь.slice(SRC.length).replace(/^\/+/, ""),
    текст: readFileSync(путь, "utf8"),
  }));

describe("избранное объявления — один источник", () => {
  it("набор исходников прочитан", () => {
    // Иначе обе проверки ниже зелены просто потому, что ничего не нашли:
    // пустая проверка и пройденная выглядят одинаково.
    expect(все.length).toBeGreaterThan(300);
  });

  it("запись избранного зовут только хук и возобновление после входа", () => {
    const нарушители = все
      .filter(({ текст }) => /\b(?:add|remove)FavoriteListing\b/.test(текст))
      .map(({ имя }) => имя)
      .filter((имя) => !РАЗРЕШЁННЫЕ.includes(имя));

    expect(
      нарушители,
      "Переключать избранное — через useFavoriteAd(). Прямой вызов заводит пятую " +
        "копию оптимистичного обновления, и откат с тостом придётся писать заново.",
    ).toEqual([]);
  });

  it("кнопка «в избранное» берёт отметку из хука, а не из своего useState", () => {
    /*
     * Признак кнопки — подпись для читающих программ: «В избранное» /
     * «Убрать из избранного» либо ключ перевода `favAdd`/`favRemove`. Значок
     * `<Heart>` сам по себе признаком не служит — он же стоит в счётчиках.
     *
     * Ровно та ошибка, что была в AdCard: `useState(false)` рядом с
     * сердечком. Начальное значение всегда «не отмечено», запись никуда не
     * идёт, состояние умирает с размонтированием.
     */
    const подпись = /избранно|favAdd|favRemove/;

    const нарушители = все
      .filter(({ текст }) => подпись.test(текст) && /<(?:Heart|Bookmark)\b/.test(текст))
      .filter(({ текст }) => !/useFavoriteAd\s*\(/.test(текст))
      .map(({ имя }) => имя)
      .filter((имя) => !(имя in БЕЗ_ХУКА_ПО_ДЕЛУ));

    expect(
      нарушители,
      "Отметка «в избранном» приходит из стора через useFavoriteAd(), а не из " +
        "useState компонента: стор наполняется с сервера при восстановлении сессии.",
    ).toEqual([]);
  });
});
