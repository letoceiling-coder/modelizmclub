import type { CdekPickupPoint } from "@/lib/api/cdek";

/**
 * Поиск пункта выдачи по улице — по адресам, которые уже пришли в ответе.
 *
 * Геокодер здесь не нужен и был бы вреден: список пунктов города приезжает
 * целиком и вместе с полными адресами, а геокодер — это ещё один сторонний
 * ключ, лимит запросов и задержка на каждую нажатую букву ради того, что уже
 * лежит в памяти. Координаты в ответе тоже есть, но для поиска по улице они
 * не требуются.
 *
 * Города, где пунктов много, — Москва, Петербург, Екатеринбург: две сотни
 * строк, по которым человек листал глазами. Искал он при этом улицу, а не
 * название пункта: названия у СДЭК служебные («MSK1234»).
 */

/**
 * Слова, которые человек пишет, а различать по ним нечего.
 *
 * Выбрасываются только из запроса. В адресе они остаются: «ул» в запросе
 * ничего не сужает, но «улица» в адресе — часть строки, по которой ищем.
 *
 * Сюда не входит «дом»: номер дома различает отлично, а вот само слово —
 * нет, поэтому оно здесь, а цифра рядом остаётся.
 */
/*
 * Сокращённые типы («мкр», «наб», «пр») совпадением по началу не ловятся:
 * «микрорайон» не начинается с «мкр». Поэтому тип улицы не сравнивается
 * вовсе — он выброшен с обеих сторон, и «микрорайон 5» находит «мкр. 5» по
 * номеру.
 *
 * Чего это не закрывает: сокращённое **имя** — «Б. Якиманка» против
 * «Большая Якиманка». Имена перечислить нельзя, и притворяться, что закрыли,
 * хуже, чем сказать прямо.
 */
const ПУСТЫЕ_СЛОВА = new Set([
  "г",
  "гор",
  "город",
  "ул",
  "улица",
  "пр",
  "прт",
  "проспект",
  "пер",
  "переулок",
  "ш",
  "шоссе",
  "б",
  "бр",
  "бульвар",
  "наб",
  "набережная",
  "пл",
  "площадь",
  "д",
  "дом",
  "к",
  "корп",
  "корпус",
  "стр",
  "строение",
  "влд",
  "владение",
  "оф",
  "офис",
  "пом",
  "помещение",
  "мкр",
  "мкрн",
  "микрорайон",
  "кв",
  "квл",
  "квартал",
  "проезд",
  "линия",
  "тракт",
  "км",
  "тупик",
  "аллея",
  "просп",
]);

/**
 * Привести к виду, в котором строки сравнимы.
 *
 * «ё» к «е» — иначе «Зелёная» не найдётся по «зеленая», а как именно написан
 * адрес у СДЭК, человек не знает. Знаки препинания к пробелам: «ул.Ленина,12»
 * и «ул. Ленина, 12» — одно и то же.
 */
export function нормализовать(s: string): string {
  return (
    s
      .toLowerCase()
      .replace(/ё/g, "е")
      .replace(/[^0-9a-zа-я]+/gi, " ")
      /*
       * Цифры и буквы разделяются: номер дома пишут и «12к1», и «12, корп. 1»,
       * и «12А». Без разделения «12к1» не совпадало ни с чем — ни одно слово
       * адреса с него не начинается, — а пункт при этом в списке есть.
       *
       * Обе стороны проходят одно и то же преобразование, поэтому «12А» в
       * запросе находит «12А» в адресе, как и раньше.
       */
      .replace(/(\d)([a-zа-я])/g, "$1 $2")
      .replace(/([a-zа-я])(\d)/g, "$1 $2")
      .replace(/\s+/g, " ")
      .trim()
  );
}

function слова(s: string): string[] {
  const n = нормализовать(s);

  return n === "" ? [] : n.split(" ");
}

/** Текст, по которому ищем: адрес и название пункта. */
function текст(p: CdekPickupPoint): string {
  return нормализовать(`${p.address ?? ""} ${p.name ?? ""}`);
}

/**
 * Совпадение по началу слова, а не по подстроке.
 *
 * Подстрока находит «Ленина» по запросу «нина» и заодно половину города по
 * любым трём буквам. Человек набирает начало улицы, а не её середину.
 */
/**
 * Число в запросе — это номер, и он совпадает целиком.
 *
 * По началу «1» совпадало бы и с домом 1, и с 12, и со 125, и с корпусом 1 —
 * то есть номер дома, единственное, что по-настоящему сужает поиск, не сужал
 * бы почти ничего. «Ленина 12к1» находил оба корпуса.
 */
const ЧИСЛО = /^\d+$/;

function совпадает(словаПункта: string[], кусок: string): boolean {
  if (кусок === "") return true;

  if (ЧИСЛО.test(кусок)) {
    return словаПункта.includes(кусок);
  }

  return словаПункта.some((w) => w.startsWith(кусок));
}

function разбить(s: string): string[] {
  return s === "" ? [] : s.split(" ");
}

/**
 * Кусок запроса что-то различает?
 *
 * Отсеиваются слова-пустышки и одиночные буквы. Одиночная буква — почти
 * всегда осколок сокращения: «пр-т» после нормализации распадается на «пр» и
 * «т», «б-р» — на «б» и «р», «2-я» — на «2» и «я». Пустышки закрывали только
 * первую половину, и «Ленинский пр-т» не находил ничего: требовалось слово,
 * начинающееся на «т», а экран при этом уверенно сообщал, что пункта нет.
 *
 * Цифра остаётся: номер дома различает отлично, и «12» — это не осколок.
 */
function значимое(w: string): boolean {
  if (ПУСТЫЕ_СЛОВА.has(w)) return false;

  return w.length > 1 || /\d/.test(w);
}

/**
 * Отобрать пункты по запросу.
 *
 * Все слова запроса должны найтись — каждое началом какого-нибудь слова в
 * адресе или названии. «ленина 12» находит «улица Ленина, д. 12» и не
 * находит «улица Ленина, д. 3».
 *
 * Пустой запрос возвращает список как есть: это не «ничего не найдено», а
 * «ничего не спрашивали».
 */
export function искатьПункты(points: CdekPickupPoint[], query: string): CdekPickupPoint[] {
  const куски = слова(query).filter(значимое);
  if (куски.length === 0) return points;

  /*
   * Слова считаются один раз на пункт, а не на каждое сравнение внутри
   * сортировки: иначе строки разбирались бы заново ~2·n·log n раз на каждую
   * нажатую букву.
   */
  const первый = куски[0];

  return (
    points
      .map((p) => ({ p, слова: разбить(текст(p)) }))
      .filter(({ слова }) => куски.every((к) => совпадает(слова, к)))
      .map((строка) => ({ ...строка, место: позиция(строка.слова, первый) }))
      /*
       * Выше — тот, у кого совпадение ближе к началу адреса. «Начинается с
       * запроса» здесь не бывает ни у кого: адреса СДЭК начинаются с города
       * («г. Москва, …»), улица стоит третьим словом, а название пункта —
       * последним.
       */
      .sort((a, b) => a.место - b.место)
      .map(({ p }) => p)
  );
}

/** Насколько рано в адресе встретилось искомое слово. */
function позиция(словаПункта: string[], кусок: string): number {
  const i = словаПункта.findIndex((w) => совпадает([w], кусок));

  return i < 0 ? Number.MAX_SAFE_INTEGER : i;
}
