import { describe, expect, it } from "vitest";
import { искатьПункты, нормализовать } from "@/lib/delivery/pvz-search";
import type { CdekPickupPoint } from "@/lib/api/cdek";

const пункт = (id: string, address: string, name = `MSK${id}`): CdekPickupPoint => ({
  id,
  name,
  address,
  city: "Москва",
  latitude: null,
  longitude: null,
  type: "PVZ",
});

const пункты: CdekPickupPoint[] = [
  пункт("1", "г. Москва, ул. Ленина, д. 12"),
  пункт("2", "г. Москва, ул. Ленина, д. 3, корп. 2"),
  пункт("3", "г. Москва, Зелёная улица, д. 5"),
  пункт("4", "г. Москва, Ленинский проспект, д. 40"),
  пункт("5", "г. Москва, ул. Тверская, д. 1", "Пункт у Ленинки"),
];

const адреса = (ps: CdekPickupPoint[]) => ps.map((p) => p.id);

describe("поиск пункта по адресу", () => {
  it("пустой запрос — список как есть", () => {
    // Это не «ничего не найдено», а «ничего не спрашивали».
    expect(адреса(искатьПункты(пункты, ""))).toEqual(["1", "2", "3", "4", "5"]);
    expect(адреса(искатьПункты(пункты, "   "))).toEqual(["1", "2", "3", "4", "5"]);
  });

  it("улица находится по началу названия", () => {
    expect(адреса(искатьПункты(пункты, "ленина"))).toEqual(["1", "2"]);
  });

  it("улица и дом вместе сужают до одного", () => {
    expect(адреса(искатьПункты(пункты, "ленина 12"))).toEqual(["1"]);
    expect(адреса(искатьПункты(пункты, "ленина 3"))).toEqual(["2"]);
  });

  /*
   * Ради этого и написано по началу слова, а не по подстроке: подстрока
   * находит «Ленина» по запросу «нина», а по любым трём буквам — половину
   * города. Человек набирает начало улицы, а не её середину.
   */
  it("середина слова не считается совпадением", () => {
    expect(адреса(искатьПункты(пункты, "нина"))).toEqual([]);
  });

  it("«ё» и «е» — одно и то же", () => {
    // Как именно написан адрес у СДЭК, человек не знает.
    expect(адреса(искатьПункты(пункты, "зеленая"))).toEqual(["3"]);
    expect(адреса(искатьПункты(пункты, "зелёная"))).toEqual(["3"]);
  });

  it("знаки препинания и регистр не мешают", () => {
    expect(адреса(искатьПункты(пункты, "ул.Ленина,12"))).toEqual(["1"]);
    expect(адреса(искатьПункты(пункты, "ЛЕНИНА 12"))).toEqual(["1"]);
  });

  it("слова-пустышки из запроса выбрасываются", () => {
    // «ул», «д», «г» ничего не сужают: они есть почти в каждом адресе.
    expect(адреса(искатьПункты(пункты, "г ул д"))).toEqual(["1", "2", "3", "4", "5"]);
    expect(адреса(искатьПункты(пункты, "ул ленина д 12"))).toEqual(["1"]);
  });

  it("название пункта тоже ищется", () => {
    expect(адреса(искатьПункты(пункты, "ленинки"))).toEqual(["5"]);
  });

  it("совпадение ближе к началу адреса поднимает пункт выше", () => {
    /*
     * «Начинается с запроса» здесь не бывает ни у кого: адреса СДЭК
     * начинаются с города. У пункта 4 улица стоит третьим словом, у пункта 5
     * совпадение — в названии, то есть в самом хвосте.
     */
    const r = адреса(искатьПункты(пункты, "ленин"));
    expect(r).toContain("4");
    expect(r.indexOf("4")).toBeLessThan(r.indexOf("5"));
  });

  it("ничего не найдено — пустой список, а не весь город", () => {
    expect(адреса(искатьПункты(пункты, "несуществующая"))).toEqual([]);
  });

  it("пункт без адреса не роняет поиск", () => {
    // СДЭК отдаёт адрес не всегда: у части пунктов `address_full` пуст.
    const безАдреса: CdekPickupPoint = { id: "9", name: "MSK9", address: null };
    expect(адреса(искатьПункты([...пункты, безАдреса], "msk9"))).toEqual(["9"]);
    expect(адреса(искатьПункты([...пункты, безАдреса], "ленина"))).toEqual(["1", "2"]);
  });
});

describe("нормализация", () => {
  it("режет пунктуацию и схлопывает пробелы", () => {
    expect(нормализовать("  ул.  Ленина,   д. 12  ")).toBe("ул ленина д 12");
  });

  it("латиница остаётся: названия пунктов служебные", () => {
    // Цифры отделяются от букв — так же, как в адресах: «MSK1234» находится
    // и по «msk1234», и по «msk 1234».
    expect(нормализовать("MSK1234")).toBe("msk 1234");
  });
});

describe("сокращения и номера домов", () => {
  const свои: CdekPickupPoint[] = [
    пункт("10", "г. Москва, Ленинский проспект, д. 40"),
    пункт("11", "г. Москва, бульвар Дмитрия Донского, д. 1"),
    пункт("12", "г. Москва, мкр. 5, д. 3"),
    пункт("13", "г. Москва, наб. р. Фонтанки, д. 7"),
    пункт("14", "г. Москва, ул. Ленина, д. 12, корп. 1"),
    пункт("15", "г. Москва, ул. Ленина, д. 12, корп. 2"),
    пункт("16", "г. Москва, 2-я Владимирская ул., д. 4"),
  ];

  /*
   * Ради этого случая одиночные буквы и перестали быть обязательными.
   * «пр-т» после нормализации распадается на «пр» и «т»: «пр» отсеивалось
   * как пустышка, а «т» требовало слова на эту букву — и поиск отвечал
   * «пунктов нет» про пункт, который в списке есть.
   */
  it("«пр-т» и «б-р» находят полные названия", () => {
    expect(адреса(искатьПункты(свои, "ленинский пр-т"))).toEqual(["10"]);
    expect(адреса(искатьПункты(свои, "б-р дмитрия донского"))).toEqual(["11"]);
  });

  it("тип улицы не сравнивается — ни полный, ни сокращённый", () => {
    /*
     * «микрорайон» не начинается с «мкр», поэтому совпадением по началу такое
     * не поймать. Тип улицы выброшен с обеих сторон, и запрос сходится по
     * тому, что различает: номеру и имени.
     */
    expect(адреса(искатьПункты(свои, "микрорайон 5"))).toEqual(["12"]);
    expect(адреса(искатьПункты(свои, "мкр 5"))).toEqual(["12"]);
    expect(адреса(искатьПункты(свои, "набережная фонтанки"))).toEqual(["13"]);
  });

  it("корпус слитно с домом различает корпуса", () => {
    // «12к1» — обычная запись; без разделения цифр и букв она не совпадала ни
    // с чем, а без точного совпадения чисел находила оба корпуса сразу.
    expect(адреса(искатьПункты(свои, "ленина 12к1"))).toEqual(["14"]);
    expect(адреса(искатьПункты(свои, "ленина 12к2"))).toEqual(["15"]);
  });

  it("номер дома совпадает целиком, а не началом", () => {
    // Иначе «1» находило бы и дом 1, и 12, и 125 — то есть единственное, что
    // по-настоящему сужает поиск, не сужало бы почти ничего.
    const дома = [
      пункт("20", "г. Москва, ул. Мира, д. 1"),
      пункт("21", "г. Москва, ул. Мира, д. 12"),
    ];
    expect(адреса(искатьПункты(дома, "мира 1"))).toEqual(["20"]);
    expect(адреса(искатьПункты(дома, "мира 12"))).toEqual(["21"]);
  });

  it("порядковый номер улицы не ломается", () => {
    expect(адреса(искатьПункты(свои, "2-я владимирская"))).toEqual(["16"]);
    expect(адреса(искатьПункты(свои, "2 владимирская"))).toEqual(["16"]);
  });

  it("короткое слово адреса не совпадает со всем подряд", () => {
    // Порог в четыре буквы: «мкр» укладывается в «микрорайон», а «лен» — нет.
    expect(адреса(искатьПункты(свои, "ленинградский"))).toEqual([]);
  });
});
