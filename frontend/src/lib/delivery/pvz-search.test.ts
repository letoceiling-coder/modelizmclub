import { describe, expect, it } from "vitest";
import { искатьПункты, нормализовать } from "@/lib/delivery/pvz-search";
import type { CdekPickupPoint } from "@/lib/api/cdek";

const пункт = (id: string, address: string, name = `MSK${id}`): CdekPickupPoint => ({
  id,
  name,
  address,
  city: "Москва",
  latitude: null,
  longitude: null,
  type: "PVZ",
});

const пункты: CdekPickupPoint[] = [
  пункт("1", "г. Москва, ул. Ленина, д. 12"),
  пункт("2", "г. Москва, ул. Ленина, д. 3, корп. 2"),
  пункт("3", "г. Москва, Зелёная улица, д. 5"),
  пункт("4", "г. Москва, Ленинский проспект, д. 40"),
  пункт("5", "г. Москва, ул. Тверская, д. 1", "Пункт у Ленинки"),
];

const адреса = (ps: CdekPickupPoint[]) => ps.map((p) => p.id);

describe("поиск пункта по адресу", () => {
  it("пустой запрос — список как есть", () => {
    // Это не «ничего не найдено», а «ничего не спрашивали».
    expect(адреса(искатьПункты(пункты, ""))).toEqual(["1", "2", "3", "4", "5"]);
    expect(адреса(искатьПункты(пункты, "   "))).toEqual(["1", "2", "3", "4", "5"]);
  });

  it("улица находится по началу названия", () => {
    expect(адреса(искатьПункты(пункты, "ленина"))).toEqual(["1", "2"]);
  });

  it("улица и дом вместе сужают до одного", () => {
    expect(адреса(искатьПункты(пункты, "ленина 12"))).toEqual(["1"]);
    expect(адреса(искатьПункты(пункты, "ленина 3"))).toEqual(["2"]);
  });

  /*
   * Ради этого и написано по началу слова, а не по подстроке: подстрока
   * находит «Ленина» по запросу «нина», а по любым трём буквам — половину
   * города. Человек набирает начало улицы, а не её середину.
   */
  it("середина слова не считается совпадением", () => {
    expect(адреса(искатьПункты(пункты, "нина"))).toEqual([]);
  });

  it("«ё» и «е» — одно и то же", () => {
    // Как именно написан адрес у СДЭК, человек не знает.
    expect(адреса(искатьПункты(пункты, "зеленая"))).toEqual(["3"]);
    expect(адреса(искатьПункты(пункты, "зелёная"))).toEqual(["3"]);
  });

  it("знаки препинания и регистр не мешают", () => {
    expect(адреса(искатьПункты(пункты, "ул.Ленина,12"))).toEqual(["1"]);
    expect(адреса(искатьПункты(пункты, "ЛЕНИНА 12"))).toEqual(["1"]);
  });

  it("слова-пустышки из запроса выбрасываются", () => {
    // «ул», «д», «г» ничего не сужают: они есть почти в каждом адресе.
    expect(адреса(искатьПункты(пункты, "г ул д"))).toEqual(["1", "2", "3", "4", "5"]);
    expect(адреса(искатьПункты(пункты, "ул ленина д 12"))).toEqual(["1"]);
  });

  it("название пункта тоже ищется", () => {
    expect(адреса(искатьПункты(пункты, "ленинки"))).toEqual(["5"]);
  });

  it("начало запроса поднимает пункт выше", () => {
    /*
     * «Ленинский проспект» начинается с искомого слова, «Пункт у Ленинки» —
     * нет. Человек, набравший «ленин», ждёт улицу первой.
     */
    const r = адреса(искатьПункты(пункты, "ленин"));
    expect(r).toContain("4");
    expect(r.indexOf("4")).toBeLessThan(r.indexOf("5"));
  });

  it("ничего не найдено — пустой список, а не весь город", () => {
    expect(адреса(искатьПункты(пункты, "несуществующая"))).toEqual([]);
  });

  it("пункт без адреса не роняет поиск", () => {
    // СДЭК отдаёт адрес не всегда: у части пунктов `address_full` пуст.
    const безАдреса: CdekPickupPoint = { id: "9", name: "MSK9", address: null };
    expect(адреса(искатьПункты([...пункты, безАдреса], "msk9"))).toEqual(["9"]);
    expect(адреса(искатьПункты([...пункты, безАдреса], "ленина"))).toEqual(["1", "2"]);
  });
});

describe("нормализация", () => {
  it("режет пунктуацию и схлопывает пробелы", () => {
    expect(нормализовать("  ул.  Ленина,   д. 12  ")).toBe("ул ленина д 12");
  });

  it("латиница остаётся: названия пунктов служебные", () => {
    expect(нормализовать("MSK1234")).toBe("msk1234");
  });
});
