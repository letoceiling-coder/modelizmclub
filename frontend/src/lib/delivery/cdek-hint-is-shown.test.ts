import { readFileSync, readdirSync, statSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import { mapListing } from "@/lib/api/listings";

/**
 * Подсказка про пункт отправки доходит до продавца, а не остаётся в ответе.
 *
 * `cdek_hint` сервер считает с 25.09 и отдаёт автору объявления. Приёмка
 * 27.09 нашла, что её никто не показывает: во всём `src` не было ни одного
 * обращения к этому полю. Замер того же дня по боевой базе объясняет цену
 * молчания — профиль доставки во всей базе **один**, и тот у заблокированной
 * учётки, то есть пункт отправки не задал ни один живой продавец. Двадцать
 * четыре объявления предлагают СДЭК, покупатель не видит способа ни у одного,
 * и продавцу об этом нигде не сказано: объявление выглядит целым.
 *
 * Тесты ниже сторожат не вид блока, а то, что он вообще есть и ведёт туда,
 * где дело правится. Ровно это и пропало в прошлый раз: правило на сервере
 * было, а на экране его не было.
 */
const SRC = join(import.meta.dirname, "..", "..");

function файлы(dir: string, out: string[] = []): string[] {
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) файлы(full, out);
    else if (/\.tsx$/.test(name)) out.push(full);
  }
  return out;
}

describe("подсказка про пункт отправки СДЭК", () => {
  it("cdek_hint доходит от ответа до объявления", () => {
    const ad = mapListing({
      uuid: "u-1",
      title: "Набор",
      price_cents: 100000,
      cdek_hint: "Чтобы включить доставку СДЭК, выберите пункт отправки в настройках доставки.",
    } as Parameters<typeof mapListing>[0]);

    expect(ad.cdekHint).toContain("пункт отправки");
  });

  it("покупателю подсказки нет — сервер её не присылает, и поле остаётся пустым", () => {
    const ad = mapListing({
      uuid: "u-2",
      title: "Набор",
      price_cents: 100000,
    } as Parameters<typeof mapListing>[0]);

    expect(ad.cdekHint).toBeNull();
  });

  /**
   * Кто-то её показывает, и рядом ссылка на настройки доставки.
   *
   * Без ссылки подсказка называет недоделку, но не говорит, где её править:
   * «настройки доставки» — четырнадцатый раздел из четырнадцати, руками его
   * ищут долго.
   */
  it("показывается в интерфейсе, и рядом ссылка на настройки доставки", () => {
    const показывают = файлы(SRC).filter((f) => /\bcdekHint\b/.test(readFileSync(f, "utf8")));

    expect(
      показывают.length,
      "cdekHint не читает ни один компонент — подсказка снова молчит",
    ).toBeGreaterThan(0);

    for (const файл of показывают) {
      const текст = readFileSync(файл, "utf8");
      expect(текст, `${файл}: подсказка без ссылки на настройки доставки`).toContain(
        "/settings/delivery",
      );
    }
  });

  /**
   * Форма объявления спрашивает готовность до сохранения.
   *
   * Проверка при сохранении есть и отказывает честно, но человек к этому
   * моменту уже заполнил форму целиком. Ответ берётся с сервера
   * (`meta.cdek_ready`), своего вывода по списку профилей во фронтенде быть
   * не должно — иначе форма и карточка разойдутся.
   */
  it("форма объявления спрашивает готовность у сервера и ведёт в настройки", () => {
    const форма = readFileSync(join(SRC, "routes", "ads.new.tsx"), "utf8");

    expect(форма, "форма не спрашивает готовность").toContain("fetchSellerDelivery");
    expect(форма, "форма не ведёт туда, где выбирают пункт").toContain("/settings/delivery");
  });
});
