import { getToken } from "@/lib/api/client";
import { useHydrated } from "@/hooks/use-hydrated";

/**
 * Есть ли у посетителя токен — для решений, от которых зависит разметка.
 *
 * Токен лежит в localStorage, сервер его не видит и всегда рисует гостя.
 * Если читать токен уже при гидрации, первый кадр браузера рисует вошедшего
 * и расходится с серверной разметкой: React #418 на каждой странице у
 * вошедших (D8, 14.09 — 17 страниц из 21). Пока идёт гидрация, хук отвечает
 * так же, как сервер, сразу после — по токену.
 *
 * В обработчиках и эффектах по-прежнему достаточно `getToken()`: гидрации
 * там нет.
 */
export function useHasToken(): boolean {
  const hydrated = useHydrated();
  return hydrated && Boolean(getToken());
}
