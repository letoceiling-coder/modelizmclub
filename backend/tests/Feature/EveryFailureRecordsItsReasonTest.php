<?php

namespace Tests\Feature;

use PHPUnit\Framework\TestCase;

/**
 * Каждый путь отказа записывает причину, а не только два из девяти.
 *
 * `markFailed` принимает причину необязательными доводами: код `null`,
 * шаг `unknown`. Вызов двумя доводами компилируется, проходит все
 * проверки и записывает ровно то состояние, которое задача велела
 * убрать, — «причина неизвестна».
 *
 * 02.10 таких вызовов нашлось два из девяти, и один из них — тестовый
 * контур, то есть ровно то место, где проверяют три исхода. Проверка
 * трёх исходов показывала бы «неизвестно» там, где причина задана
 * руками.
 *
 * Проверка читает исходники: инвариант не в поведении одного вызова, а
 * в том, что таких вызовов нет нигде. Ср. правило про переход в
 * `docs/known-issues.md`: полнота путей не должна быть предметом памяти.
 */
class EveryFailureRecordsItsReasonTest extends TestCase
{
    private const APP = __DIR__.'/../../app';

    /** @return list<string> */
    private function файлы(string $dir): array
    {
        $out = [];
        foreach (scandir($dir) ?: [] as $name) {
            if ($name === '.' || $name === '..') {
                continue;
            }
            $full = $dir.'/'.$name;
            if (is_dir($full)) {
                $out = array_merge($out, $this->файлы($full));
            } elseif (str_ends_with($name, '.php')) {
                $out[] = $full;
            }
        }

        return $out;
    }

    /**
     * Доводы верхнего уровня в вызове: скобки и массивы внутри не считаем.
     */
    private function доводов(string $вызов): int
    {
        $тело = substr($вызов, strpos($вызов, '(') + 1, -1);
        if (trim($тело) === '') {
            return 0;
        }

        $глубина = 0;
        $сколько = 1;
        foreach (str_split($тело) as $ch) {
            if ($ch === '(' || $ch === '[') {
                $глубина++;
            } elseif ($ch === ')' || $ch === ']') {
                $глубина--;
            } elseif ($ch === ',' && $глубина === 0) {
                $сколько++;
            }
        }

        return $сколько;
    }

    public function test_ни_один_вызов_markFailed_не_оставляет_причину_пустой(): void
    {
        $нарушения = [];
        $всего = 0;

        foreach ($this->файлы(self::APP) as $файл) {
            $код = (string) file_get_contents($файл);
            $смещение = 0;

            while (($поз = strpos($код, '->markFailed(', $смещение)) !== false) {
                $смещение = $поз + 1;
                $начало = $поз + strlen('->markFailed');
                $i = $начало + 1;
                $глубина = 1;
                while ($i < strlen($код) && $глубина > 0) {
                    if ($код[$i] === '(') {
                        $глубина++;
                    } elseif ($код[$i] === ')') {
                        $глубина--;
                    }
                    $i++;
                }
                $вызов = substr($код, $начало, $i - $начало);
                $всего++;

                /*
                 * Пятый довод — шаг обрыва, третий — наш код. Вызов
                 * короче пяти доводов оставляет их умолчаниями, то есть
                 * пишет «причина неизвестна».
                 */
                if ($this->доводов($вызов) < 5) {
                    $строка = substr_count(substr($код, 0, $поз), "\n") + 1;
                    $нарушения[] = basename($файл).':'.$строка;
                }
            }
        }

        // Пустая выборка выглядела бы как успех.
        $this->assertGreaterThanOrEqual(5, $всего, 'вызовы markFailed не найдены — проверка смотрит не туда');
        $this->assertSame([], $нарушения, 'эти вызовы запишут «причина неизвестна»');
    }
}
