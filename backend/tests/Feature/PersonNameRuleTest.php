<?php

namespace Tests\Feature;

use App\Rules\PersonName;
use Illuminate\Support\Facades\Validator;
use Modules\Auth\Http\Requests\RegisterRequest;
use Modules\User\Http\Requests\UpdateProfileRequest;
use PHPUnit\Framework\Attributes\DataProvider;
use Tests\TestCase;

/**
 * Имя человека проходит, опасное — нет, и правило одно на регистрацию и профиль.
 *
 * До 27.09 проверок было две, и они расходились: при регистрации апостроф
 * разрешался, при правке профиля — нет. «O'Neil» регистрировался и потом не
 * мог сохранить профиль, причём отказ приходил на поле имени, которого он не
 * касался, — форма отправляет `display_name` вместе с остальным.
 *
 * Приёмка 27.09 наткнулась на то же с другой стороны: учётки, заведённые
 * командой `qa:seed-accounts` под именами «Приёмка · с подпиской», не могли
 * сохранить ни города, ни строки «о себе».
 */
class PersonNameRuleTest extends TestCase
{
    /** @return list<array{0: string, 1: string}> */
    public static function настоящиеИмена(): array
    {
        return [
            'русское простое' => ['Иван Петров', 'два слова через пробел'],
            'двойная фамилия' => ['Римский-Корсаков', 'дефис'],
            'с инициалом' => ['А. Петров', 'точка после инициала'],
            'ирландское' => ["O'Neil", 'машинописный апостроф'],
            'ирландское типографское' => ['O’Neil', 'типографский апостроф'],
            'французское' => ['Jean-Luc Picard', 'дефис и латиница'],
            'составное со средней точкой' => ['Анна · Мария', 'средняя точка'],
            'немецкое с диакритикой' => ['Jürgen Müller', 'умляуты'],
            'испанское из трёх частей' => ['José María Álvarez', 'акуты'],
            'отчество полностью' => ['Никита Николаевич Клочко', 'три слова'],
            'учётка приёмки' => ['Приёмка · с подпиской', 'та, на которой нашли дефект'],
        ];
    }

    /** @return list<array{0: string, 1: string}> */
    public static function опасноеИЧужое(): array
    {
        return [
            'угловые скобки' => ['<script>alert(1)</script>', 'разметка'],
            'только скобка' => ['Иван <Петров', 'одна угловая скобка'],
            'перевод строки' => ["Иван\nПетров", 'управляющий символ'],
            'возврат каретки' => ["Иван\rПетров", 'управляющий символ'],
            'нулевой байт' => ["Иван\0", 'нулевой байт'],
            'табуляция' => ["Иван\tПетров", 'управляющий символ'],
            'амперсанд' => ['Иван &amp; Пётр', 'сущность разметки'],
            'фигурные скобки' => ['{{ 7*7 }}', 'шаблонная вставка'],
            'обратный слэш' => ['Иван\\Петров', 'путь'],
            'собака' => ['ivan@example.com', 'адрес почты вместо имени'],
        ];
    }

    #[DataProvider('настоящиеИмена')]
    public function test_настоящее_имя_проходит(string $имя, string $чем): void
    {
        $проверка = Validator::make(['display_name' => $имя], ['display_name' => [new PersonName]]);

        $this->assertFalse(
            $проверка->fails(),
            "имя «{$имя}» ({$чем}) должно проходить, а отбилось",
        );
    }

    #[DataProvider('опасноеИЧужое')]
    public function test_опасное_отбивается(string $значение, string $чем): void
    {
        $проверка = Validator::make(['display_name' => $значение], ['display_name' => [new PersonName]]);

        $this->assertTrue(
            $проверка->fails(),
            "«{$чем}» должно отбиваться, а прошло: ".json_encode($значение),
        );
    }

    /**
     * Регистрация и правка профиля судят по одному правилу.
     *
     * Проверяется не текст выражения, а поведение: имя, прошедшее
     * регистрацию, обязано сохраняться в профиле. Расхождение двух
     * выражений именно так и проявлялось.
     */
    public function test_регистрация_и_профиль_согласованы(): void
    {
        $правилаРегистрации = (new RegisterRequest)->rules()['display_name'];
        $правилаПрофиля = (new UpdateProfileRequest)->rules()['display_name'];

        $имяЕсть = fn (array $правила) => collect($правила)
            ->contains(fn ($r) => $r instanceof PersonName);

        $this->assertTrue($имяЕсть($правилаРегистрации), 'регистрация не использует общее правило');
        $this->assertTrue($имяЕсть($правилаПрофиля), 'правка профиля не использует общее правило');

        foreach (array_column(self::настоящиеИмена(), 0) as $имя) {
            foreach ([['регистрация', $правилаРегистрации], ['профиль', $правилаПрофиля]] as [$где, $правила]) {
                $правила = array_values(array_filter($правила, fn ($r) => $r instanceof PersonName));
                $проверка = Validator::make(['display_name' => $имя], ['display_name' => $правила]);
                $this->assertFalse(
                    $проверка->fails(),
                    "«{$имя}» не проходит там, где {$где}",
                );
            }
        }
    }
}
