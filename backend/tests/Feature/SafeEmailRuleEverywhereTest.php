<?php

namespace Tests\Feature;

use App\Rules\SafeEmail;
use Illuminate\Support\Facades\Validator;
use PHPUnit\Framework\Attributes\DataProvider;
use Tests\TestCase;

/**
 * Правило SafeEmail стоит на каждом поле, где адрес приходит извне.
 *
 * Стандартный `email` в Laravel 11 пропускает часть последовательностей с
 * переводом строки (GHSA-5vg9-5847-vvmq, high), а Symfony Mailer потом
 * подставляет адрес в заголовки письма. Заплатки для 11.x нет: composer
 * отказывается ставить любой выпуск от 11.31.0 до 11.56.1, исправлено только
 * в 12.60. Пока перехода нет, дыру закрывает наше правило — значит оно должно
 * стоять везде, а не почти везде.
 *
 * До 26.09 одно поле было забыто: `guest_email` у обратной связи, на открытом
 * маршруте. Через заголовки письма оттуда было не достать — адрес шёл в текст
 * обращения, — но правило существует ровно для того, чтобы следующий
 * `Reply-To` не сделал маршрут проходом.
 *
 * Правило, за которым никто не следит, — не правило. Следит этот тест.
 */
class SafeEmailRuleEverywhereTest extends TestCase
{
    /** Управляющие символы, которыми Symfony Mime может разорвать строку. */
    public static function опасные(): array
    {
        return [
            'перевод строки' => ["a@b.ru\nBcc: chужой@b.ru"],
            'возврат каретки' => ["a@b.ru\rBcc: chужой@b.ru"],
            'CRLF' => ["a@b.ru\r\nBcc: chужой@b.ru"],
            'нулевой байт' => ["a@b.ru\0"],
            'табуляция' => ["a@b.ru\tBcc: chужой@b.ru"],
            'NEL' => ["a@b.ru\u{0085}"],
            'разделитель строк' => ["a@b.ru\u{2028}"],
            'разделитель абзацев' => ["a@b.ru\u{2029}"],
        ];
    }

    #[DataProvider('опасные')]
    public function test_правило_отбивает_управляющие_символы(string $адрес): void
    {
        $проверка = Validator::make(['email' => $адрес], ['email' => ['email', new SafeEmail]]);

        $this->assertTrue(
            $проверка->fails(),
            'адрес с управляющим символом должен отбиваться: '.json_encode($адрес),
        );
    }

    public function test_обычный_адрес_проходит(): void
    {
        $проверка = Validator::make(
            ['email' => 'petr.ivanov+tag@example.ru'],
            ['email' => ['email', new SafeEmail]],
        );

        $this->assertFalse($проверка->fails(), 'законный адрес отбиваться не должен');
    }

    /**
     * Обход исходников: где стоит правило `email`, там стоит и SafeEmail.
     *
     * Ищется само правило, а не имя поля. Первая редакция этой проверки
     * искала ключи вида `*email*` и разбирала только массивы правил —
     * ревью 26.09 показало два прохода, оба вероятных:
     *
     * - правила строкой через вертикальную черту (`'required|email|max:255'`)
     *   проверка молча пропускала;
     * - поле, названное без слова email, не находилось вовсе — а именно
     *   `reply_to` и есть тот сценарий, которым обоснована правка в
     *   `FeedbackController`.
     *
     * Ещё одна ошибка была обратной: захват массива обрывался на первой `]`,
     * поэтому правило с вложенными скобками (`Rule::in([...])`) обрезало
     * SafeEmail из виду и красило правильный код. Теперь скобки считаются.
     */
    public function test_везде_где_есть_правило_email_есть_и_safeemail(): void
    {
        $корень = base_path('app');
        $файлы = new \RecursiveIteratorIterator(new \RecursiveDirectoryIterator($корень));
        $безПравила = [];
        $всего = 0;

        foreach ($файлы as $файл) {
            if ($файл->isDir() || $файл->getExtension() !== 'php') {
                continue;
            }

            $относительный = str_replace($корень.'/', '', $файл->getPathname());

            foreach ($this->объявленияПравил(file_get_contents($файл->getPathname())) as [$поле, $правила]) {
                if (! $this->содержитПравилоEmail($правила)) {
                    continue;
                }

                $всего++;

                if (! str_contains($правила, 'SafeEmail')) {
                    $безПравила[] = "{$относительный}: {$поле}";
                }
            }
        }

        $this->assertGreaterThanOrEqual(
            9,
            $всего,
            'проверка нашла меньше мест, чем было на 26.09 — значит разбор сломался, '
            .'а не поля исчезли. Если поле убрали намеренно, поправьте число здесь.',
        );

        $this->assertSame(
            [],
            $безПравила,
            "Поля с правилом email без SafeEmail:\n  ".implode("\n  ", $безПравила)
            ."\nСтандартный email в Laravel 11 пропускает переводы строки внутри "
            .'закавыченной локальной части, заплатки для 11.x нет.',
        );
    }

    /**
     * Все объявления правил в файле: `'ключ' => <правила>`.
     *
     * Разбор идёт только внутри блоков валидации — тела `rules()`, аргумента
     * `validate(...)` и `Validator::make(...)`. Без этого ограничения в выборку
     * попадают массивы выдачи данных, где `'email'` — имя поля ответа, а не
     * правило: `'user' => ['email' => $u->email]` и подобное. Проверено —
     * таких мест в `app` девять, и все они ложные.
     *
     * @return list<array{0: string, 1: string}>
     */
    private function объявленияПравил(string $текст): array
    {
        $найдено = [];

        foreach ($this->блокиВалидации($текст) as $блок) {
            preg_match_all('/[\'"]([\w.*-]+)[\'"]\s*=>\s*/', $блок, $совпадения, PREG_OFFSET_CAPTURE);

            foreach ($совпадения[0] as $i => [$целое, $смещение]) {
                $поле = $совпадения[1][$i][0];
                $начало = $смещение + strlen($целое);

                if (! isset($блок[$начало])) {
                    continue;
                }

                $найдено[] = [$поле, $блок[$начало] === '['
                    ? $this->массивСоСчётомСкобок($блок, $начало)
                    : $this->доКонцаЗначения($блок, $начало)];
            }
        }

        return $найдено;
    }

    /**
     * Куски файла, внутри которых объявляются правила валидации.
     *
     * @return list<string>
     */
    private function блокиВалидации(string $текст): array
    {
        $блоки = [];

        // Тело метода rules(): от «return [» до закрывающей скобки массива.
        if (preg_match('/function rules\(\)[^{]*\{.*?return\s*\[/s', $текст, $m, PREG_OFFSET_CAPTURE)) {
            $начало = $m[0][1] + strlen($m[0][0]) - 1;
            $блоки[] = $this->массивСоСчётомСкобок($текст, $начало);
        }

        // validate([...]) и Validator::make($data, [...]).
        foreach (['/->validate\s*\(\s*\[/', '/Validator::make\s*\([^,]*,\s*\[/'] as $образец) {
            preg_match_all($образец, $текст, $совпадения, PREG_OFFSET_CAPTURE);

            foreach ($совпадения[0] as [$целое, $смещение]) {
                $блоки[] = $this->массивСоСчётомСкобок($текст, $смещение + strlen($целое) - 1);
            }
        }

        return $блоки;
    }

    private function массивСоСчётомСкобок(string $текст, int $начало): string
    {
        $глубина = 0;
        $длина = strlen($текст);

        for ($i = $начало; $i < $длина; $i++) {
            if ($текст[$i] === '[') {
                $глубина++;
            } elseif ($текст[$i] === ']') {
                $глубина--;

                if ($глубина === 0) {
                    return substr($текст, $начало, $i - $начало + 1);
                }
            }
        }

        return substr($текст, $начало, 400);
    }

    private function доКонцаЗначения(string $текст, int $начало): string
    {
        $конец = strcspn($текст, ",\n", $начало);

        return substr($текст, $начало, $конец);
    }

    /**
     * Есть ли среди правил правило `email` — в массиве или в строке через `|`.
     *
     * Сообщения об ошибках и выдача данных под это не попадают: там значение
     * не является перечнем правил и слова `email` как отдельного правила в нём
     * нет.
     */
    private function содержитПравилоEmail(string $правила): bool
    {
        // Массив: 'email' или 'email:rfc' отдельным элементом.
        if (preg_match('/[\'"]email(:[A-Za-z,]+)?[\'"]/', $правила) === 1) {
            return true;
        }

        // Строка через вертикальную черту: required|email|max:255.
        if (preg_match('/[\'"][^\'"]*(^|\|)email(:[A-Za-z,]+)?(\||[\'"])/', $правила) === 1) {
            return true;
        }

        return false;
    }
}
