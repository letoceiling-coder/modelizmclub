<?php

namespace Tests\Unit;

use App\Support\PhoneNormalizer;
use PHPUnit\Framework\TestCase;

/**
 * Сервер приводит номер к тому же виду, что и поле ввода.
 *
 * Решение Ж2 от 09.10, пункт 6: «Сервер приводит номер к тому же виду по
 * тому же правилу и хранит в едином формате. Тесты на сервере и клиенте —
 * одни и те же примеры.»
 *
 * Таблица примеров совпадает с `frontend/src/lib/phone.test.ts`. Правя одну,
 * правьте и другую: до 09.10 правило существовало в двух видах —
 * `formatRuPhone` в компоненте поля и `PhoneNormalizer::normalize` здесь, —
 * и сходились они только на тех примерах, на которых никто не проверял.
 *
 * ## Где сервер намеренно строже поля
 *
 * Лишние цифры. Поле их отбрасывает (пункт 3 решения: «Лишние цифры
 * отбрасываются»), и на сервер уходит уже ровно одиннадцать. Сам сервер
 * двенадцатизначную строку отвергает и не угадывает, какую цифру выкинуть:
 * строгость в эту сторону разрешена — запрещено обратное, когда интерфейс
 * не даёт ввести то, что сервер принимает.
 */
class PhoneNormalizerTest extends TestCase
{
    /**
     * Те же примеры, что в `frontend/src/lib/phone.test.ts`, кроме строк с
     * лишними цифрами — они разобраны отдельным тестом ниже.
     *
     * @return array<string, array{string, string}>
     */
    public static function полныеНомера(): array
    {
        return [
            'десять цифр' => ['9384100024', '+79384100024'],
            'одиннадцать с семёркой' => ['79384100024', '+79384100024'],
            'одиннадцать с восьмёркой' => ['89384100024', '+79384100024'],
            'с плюсом' => ['+79384100024', '+79384100024'],
            'с пробелами и дефисами' => ['+7 938 410-00-24', '+79384100024'],
            'восьмёрка и скобки' => ['8 (938) 410-00-24', '+79384100024'],
            'десять цифр пробелами' => ['938 410 00 24', '+79384100024'],
            'скобки без пробелов' => ['+7(938)410-00-24', '+79384100024'],
            'через дефисы' => ['8-938-410-00-24', '+79384100024'],
            'с краевыми пробелами' => ['  +7 938 410 00 24  ', '+79384100024'],
        ];
    }

    /**
     * @dataProvider полныеНомера
     */
    public function test_все_записи_номера_дают_один_и_тот_же_вид(string $ввод, string $ожидание): void
    {
        $this->assertSame($ожидание, PhoneNormalizer::normalize($ввод));
    }

    public function test_все_примеры_сходятся_в_один_номер(): void
    {
        $полученные = [];
        foreach (self::полныеНомера() as $имя => [$ввод, $_]) {
            $полученные[$имя] = PhoneNormalizer::normalize($ввод);
        }

        $this->assertSame(
            ['+79384100024'],
            array_values(array_unique($полученные)),
            'записи одного номера разошлись: '.json_encode($полученные, JSON_UNESCAPED_UNICODE),
        );
    }

    /**
     * @return array<string, array{string}>
     */
    public static function неполныеНомера(): array
    {
        return [
            'пусто' => [''],
            'только плюс' => ['+'],
            'только приставка' => ['+7'],
            'одна семёрка' => ['7'],
            'одна восьмёрка' => ['8'],
            'одна девятка' => ['9'],
            'три цифры' => ['938'],
            'девять цифр' => ['938410002'],
        ];
    }

    /**
     * @dataProvider неполныеНомера
     */
    public function test_неполный_номер_не_принимается(string $ввод): void
    {
        $this->assertNull(PhoneNormalizer::normalize($ввод));
    }

    public function test_расхождение_с_полем_десять_цифр_начатых_с_восьмёрки(): void
    {
        /*
         * Единственное место, где правило поля и правило сервера расходятся.
         * Записано тестом нарочно: расхождение должно быть видно в прогоне, а
         * не всплыть жалобой.
         *
         * Поле (решение Ж2, пункт 2): первая 8 — приставка, в десять цифр она
         * не попадает. `8938410002` — это девять цифр номера, то есть номер
         * неполон, и на сервер он не уходит.
         *
         * Сервер: десять цифр, значит это сам номер, приписать приставку —
         * `+78938410002`. Такой номер существует (городские начинаются с 8:
         * Петербург 812, Нижний Новгород 831), и отнимать у сервера право его
         * принять нельзя — это правка прав, которой владелец не просил.
         *
         * Практического вреда нет: поле нужно для подтверждения по SMS, а на
         * городской номер SMS не приходит. Решения владельца по городским
         * номерам нет — вопрос в docs/acceptance/release/MORNING.md.
         *
         * Если владелец решит, что принимаются только мобильные, строже
         * станет сервер, а не поле, и этот тест сменится на проверку отказа.
         */
        $this->assertSame('+78938410002', PhoneNormalizer::normalize('8938410002'));
    }

    public function test_лишние_цифры_сервер_отвергает_а_не_угадывает(): void
    {
        // Поле ввода такую строку до сервера не доносит — оно отбрасывает
        // лишнее само. Но если строка придёт прямо в API, сервер не должен
        // решать за человека, какая цифра лишняя.
        $this->assertNull(PhoneNormalizer::normalize('93841000241'));
        $this->assertNull(PhoneNormalizer::normalize('893841000249'));
    }

    public function test_вид_для_шлюза_без_плюса(): void
    {
        $this->assertSame(
            '79384100024',
            PhoneNormalizer::toSmsGateway('+79384100024'),
        );
    }

    public function test_хранится_единым_видом_плюс_семь_и_десять_цифр(): void
    {
        foreach (self::полныеНомера() as [$ввод, $_]) {
            $this->assertMatchesRegularExpression(
                '/^\+7\d{10}$/',
                (string) PhoneNormalizer::normalize($ввод),
                "номер «{$ввод}» привёлся к неожидаемому виду",
            );
        }
    }
}
