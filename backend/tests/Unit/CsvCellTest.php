<?php

namespace Tests\Unit;

use App\Support\CsvCell;
use PHPUnit\Framework\TestCase;

/**
 * Клетка выгрузки не исполняется как формула.
 *
 * Выгрузки сделок и платежей кладут в CSV название объявления, имена
 * сторон и описание платежа — то есть текст, который пишут
 * пользователи. Эксель считает формулой всё, что начинается с `=`,
 * `+`, `-`, `@`, табуляции или возврата каретки, и считает её при
 * открытии файла, без подтверждения.
 *
 * Воспроизведено 04.10 на выгрузке сделок: объявление с названием
 * `=1+1` уезжало в CSV как есть, то есть в таблице администратора
 * становилось числом 2. С `=HYPERLINK(...)` — ссылкой.
 *
 * Проверки ниже закрепляют и обратную сторону: обычный текст и числа
 * апострофа не получают, иначе бухгалтерская выгрузка перестанет
 * складываться.
 */
class CsvCellTest extends TestCase
{
    public static function опасные(): array
    {
        return [
            'равенство' => ['=1+1'],
            'ссылка' => ['=HYPERLINK("http://example.test";"Счёт")'],
            'плюс' => ['+1+1'],
            'собака' => ['@SUM(A1:A9)'],
            'минус с выражением' => ['-1+1'],
            'табуляция перед формулой' => ["\t=1+1"],
            'возврат каретки перед формулой' => ["\r=1+1"],
        ];
    }

    /** @dataProvider опасные */
    public function test_опасное_начало_получает_апостроф(string $вход): void
    {
        $выход = CsvCell::safe($вход);

        $this->assertSame("'".$вход, $выход);
        $this->assertStringStartsWith("'", $выход, 'формула уехала в таблицу как формула');
    }

    public static function безопасные(): array
    {
        return [
            'название' => ['Пропеллер АШ-62'],
            'имя' => ['Римский-Корсаков Пётр'],
            'почта' => ['buyer@example.test'],
            'сумма' => ['1234,56'],
            'отрицательная сумма' => ['-1234,56'],
            'целое' => ['150'],
            'отрицательное целое' => ['-150'],
            'дата' => ['2026-10-04 02:13:11'],
            'пусто' => [''],
        ];
    }

    /** @dataProvider безопасные */
    public function test_обычное_значение_не_меняется(string $вход): void
    {
        $this->assertSame($вход, CsvCell::safe($вход));
    }

    public function test_null_превращается_в_пустую_строку(): void
    {
        $this->assertSame('', CsvCell::safe(null));
    }

    /**
     * Дефис в начале имени — не формула.
     *
     * `PersonName` разрешает дефис, и имя вида `-Пётр` человек завести
     * может. Апостроф здесь появится, и это верно: от `-Пётр` таблица
     * ничего не посчитает, но и отличить его от `-1+1` по первому
     * символу нельзя, а правило `ЧИСЛО` на `-Пётр` не сработает.
     */
    public function test_дефис_перед_буквами_апостроф_получает(): void
    {
        $this->assertSame("'-Пётр", CsvCell::safe('-Пётр'));
    }

    public function test_строка_обрабатывается_целиком(): void
    {
        $строка = CsvCell::row(['=1+1', 'Пропеллер', null, '-150']);

        $this->assertSame(["'=1+1", 'Пропеллер', '', '-150'], $строка);
    }
}
