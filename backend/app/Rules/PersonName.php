<?php

namespace App\Rules;

use Closure;
use Illuminate\Contracts\Validation\ValidationRule;

/**
 * Имя человека: буквы и знаки, которые в именах действительно бывают.
 *
 * Зачем правило, а не выражение на месте. До 27.09 проверок было две, и они
 * расходились:
 *
 *   регистрация      /^[A-Za-zА-Яа-яЁё\s'\x{2019}-]+$/u   апостроф разрешён
 *   правка профиля   /^[\p{L}\s\-]+$/u                    апострофа нет
 *
 * То есть «O'Neil» регистрировался и потом не мог сохранить профиль:
 * форма отправляет `display_name` вместе с остальными полями, и отказ
 * приходил на имя, которого человек не касался. Приёмка 27.09 наткнулась
 * на это же с другой стороны — учётки, заведённые командой
 * `qa:seed-accounts` под именами «Приёмка · с подпиской», не могли сохранить
 * ни города, ни строки «о себе», потому что средняя точка не проходила.
 *
 * Список составлен по тому, что бывает в настоящих именах: буквы любого
 * алфавита, пробел, дефис (Римский-Корсаков), апостроф в двух начертаниях
 * (O'Neil, O’Neil), точка (А. Петров), средняя точка (Анна · Мария).
 *
 * Перечень разрешающий, а не запрещающий, и это сознательно: угловые скобки,
 * управляющие символы, переводы строки и всё прочее опасное не проходят по
 * построению, а не потому что кто-то вспомнил их перечислить.
 */
class PersonName implements ValidationRule
{
    /**
     * Буквы, пробел, дефис, апострофы, точка, средняя точка.
     *
     * `\p{L}` покрывает кириллицу, латиницу и остальные алфавиты; `\p{M}` —
     * диакритику, которая в некоторых языках приходит отдельным символом
     * (например, «й» из «и» + знак), иначе такое имя отбивалось бы.
     *
     * Пробел записан явным символом, а не классом `\s`. Первая редакция
     * использовала `\s`, и тест это поймал: класс включает перевод строки,
     * возврат каретки и табуляцию, то есть ровно те управляющие символы,
     * которые правило и должно отбивать. Неразрывный пробел добавлен
     * отдельно — его приносят из документов вместе с вставленным текстом.
     */
    public const PATTERN = "/^[\p{L}\p{M} \x{00A0}'\x{2019}.\x{00B7}\x{2022}-]+$/u";

    public const MESSAGE = 'Имя может содержать буквы, пробел, дефис, апостроф и точку.';

    public function validate(string $attribute, mixed $value, Closure $fail): void
    {
        if (! is_string($value)) {
            return;
        }

        // Пустую строку и длину проверяют соседние правила; здесь только состав.
        if ($value === '') {
            return;
        }

        if (preg_match(self::PATTERN, $value) !== 1) {
            $fail(self::MESSAGE);
        }
    }
}
