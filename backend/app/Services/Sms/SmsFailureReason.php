<?php

namespace App\Services\Sms;

/**
 * Почему SMS не ушла — и кто в этом виноват.
 *
 * Решение Ж5 от 09.10: «Сообщение об ошибке не обвиняет пользователя, если
 * причина на стороне сервиса».
 *
 * До 09.10 любой отказ шлюза — нет ключей, не согласована подпись
 * отправителя, кончились деньги, шлюз не ответил, провайдер отклонил
 * конкретный номер — превращался в один и тот же текст: «Оператор связи
 * отклонил отправку на этот номер. Проверьте номер или укажите другой».
 * Человек с правильным номером читал, что номер неправильный, и правил то,
 * что править не нужно. Именно это и было на снимке владельца.
 *
 * Причина ставится **в том месте, где она известна** — у самого `throw` в
 * драйвере, — а не угадывается потом по тексту сообщения. Разбор строки
 * ошибки был бы тем же угадыванием: драйвер меняет формулировку, и разбор
 * молча начинает врать.
 */
enum SmsFailureReason: string
{
    /** Ключей, логина или подписи отправителя нет в настройках. Наша вина. */
    case NotConfigured = 'not_configured';

    /** Шлюз не ответил, ответил ошибкой сети или нечитаемым телом. Наша вина. */
    case GatewayUnavailable = 'gateway_unavailable';

    /**
     * Шлюз отказал, и причина не в номере: счёт, заявка, подпись, лимит —
     * либо шлюз не объяснил. Наша вина, в том числе когда мы не знаем.
     */
    case GatewayRefused = 'gateway_refused';

    /**
     * Шлюз прямо назвал номер неверным или недоступным. Единственная причина,
     * о которой можно сказать человеку «проверьте номер».
     */
    case BadNumber = 'bad_number';

    /**
     * Виноват сервис, а не человек.
     *
     * Неизвестная причина считается нашей: чтобы сказать «дело в номере»,
     * нужно доказательство, а чтобы сказать «дело в нас» — достаточно того,
     * что доказательства нет.
     */
    public function ourFault(): bool
    {
        return $this !== self::BadNumber;
    }

    /** Что показать человеку. */
    public function message(): string
    {
        return $this === self::BadNumber
            ? 'Оператор связи отклонил отправку на этот номер. Проверьте номер или укажите другой.'
            : 'Сейчас не получается отправить код. Попробуйте позже или напишите в поддержку.';
    }

    /** Машинный код для клиента. */
    public function clientCode(): string
    {
        return $this === self::BadNumber ? 'sms_provider_rejected' : 'sms_service_unavailable';
    }

    /** Короткое объяснение для админки — без ключей и без номеров. */
    public function adminHint(): string
    {
        return match ($this) {
            self::NotConfigured => 'Шлюз SMS не настроен: нет логина, пароля, токена или подписи отправителя.',
            self::GatewayUnavailable => 'Шлюз SMS не отвечает или ответил нечитаемо.',
            self::GatewayRefused => 'Шлюз SMS отказал в отправке: проверьте баланс, заявку на подпись отправителя и лимиты.',
            self::BadNumber => 'Шлюз SMS назвал номер получателя неверным.',
        };
    }
}
