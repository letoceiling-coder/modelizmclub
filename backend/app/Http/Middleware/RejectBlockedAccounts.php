<?php

namespace App\Http\Middleware;

use App\Enums\UserStatus;
use App\Models\User;
use Closure;
use Illuminate\Http\Request;
use Illuminate\Support\Facades\Auth;
use Symfony\Component\HttpFoundation\Response;

/**
 * Заблокированный и удалённый не действуют по уже выданному токену.
 *
 * Проверка статуса стояла только на входе: `AuthService::login` и
 * `OAuthService` отказывают заблокированному. Но токен, выданный до
 * блокировки, не отзывался и не проверялся, и запрос с ним проходил как
 * обычный. Воспроизведено 04.10 на `/api/v1/auth/me`:
 *
 *     токен выдан активному           → 200
 *     статус сменён на blocked        → 200, токенов осталось 1
 *
 * То есть блокировка в админке закрывала человеку только вход, а открытую
 * вкладку и мобильное приложение не закрывала вовсе. Инвариант Библии
 * «заблокированный аккаунт не действует по старой сессии» не держался.
 *
 * Та же дыра открывалась обезличиванием: `AnonymizeUsersCommand` ставит
 * `status = blocked`, и обезличенная учётка продолжала бы действовать
 * прежним токеном.
 *
 * Почему middleware на всю группу `api`, а не отзыв токенов в админке.
 * Отзыв закрывает один путь из нескольких: статус меняют ещё команда
 * обезличивания и правка в базе руками, а сессионный вход через cookie
 * токенов не имеет вообще. Проверка на каждом запросе закрывает все
 * пути сразу и не зависит от того, кто и чем сменил статус.
 *
 * `pending_verification` пропускается намеренно: это обычный
 * зарегистрированный, у которого не подтверждена почта. Ему закрыты
 * отдельные действия своими воротами, а не весь API.
 *
 * Отказ — 401, а не 403: для клиента это «сессия больше не действует»,
 * и он должен отправить человека на вход, а не показать «нет прав».
 * Текст не говорит, заблокирован аккаунт или удалён, — состояние чужой
 * учётки не дело того, кто держит токен.
 */
class RejectBlockedAccounts
{
    /** Статусы, при которых уже выданный доступ перестаёт действовать. */
    private const ЗАКРЫТЫЕ = [UserStatus::Blocked, UserStatus::Deleted];

    public function handle(Request $request, Closure $next): Response
    {
        /*
         * Через guard, а не через `$request->user()`: это middleware группы,
         * оно выполняется до `auth:sanctum`, и у запроса в этот момент
         * пользователь ещё не разрешён. Guard разрешает токен сам и
         * возвращает null для гостя — гостевые маршруты проходят мимо.
         */
        $user = Auth::guard('sanctum')->user();

        if ($user instanceof User && in_array($user->status, self::ЗАКРЫТЫЕ, true)) {
            return response()->json(
                ['message' => 'Доступ к аккаунту закрыт. Обратитесь в поддержку.'],
                401,
            );
        }

        return $next($request);
    }
}
