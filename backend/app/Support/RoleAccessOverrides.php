<?php

namespace App\Support;

use App\Enums\UserRole;
use App\Models\SystemSetting;

/**
 * Что открывает роль — настройкой, а не только зашитой картой.
 *
 * До 28.09 состав разделов у роли задавался константами `AdminAccess::SECTIONS`
 * и `SERVICE`: ключ → минимальная роль. Поменять состав можно было только
 * правкой кода и выкаткой. Раздел «Что открывает роль» в админке эту карту
 * показывал галочками и ничего не позволял.
 *
 * Теперь поверх зашитой карты лежит **разреженный** список исключений:
 * `{ "moderator": { "events": true, "delivery": false } }`. Ключ, которого в
 * списке нет, решается по-прежнему — ступенью роли. Так сделано нарочно:
 *
 * — зашитая карта остаётся значением по умолчанию, и её правка в коде
 *   продолжает работать для всех ключей, которых никто не трогал руками;
 * — в настройке лежит ровно то, что человек изменил, и в журнале изменений
 *   видно, что именно, а не «вот вам вся карта из сорока строк»;
 * — сброс к умолчанию — это удаление ключа из списка, а не угадывание,
 *   какой была ступень.
 *
 * ПОЧЕМУ НЕ РАНГОМ. Зашитая карта ранговая: раздел открыт всем, чья ступень
 * не ниже объявленной. Если бы правка меняла ступень, одно нажатие меняло бы
 * и соседние столбцы: открыв раздел администратору направления, он открылся
 * бы и модератору. Матрица в админке показывает три независимых столбца, и
 * человек вправе ожидать, что нажатие меняет ту клетку, по которой он нажал.
 * Поэтому исключения адресные: роль плюс ключ.
 *
 * Следствие, о котором надо знать: матрица перестаёт быть обязательно
 * вложенной. Модератору можно закрыть то, что открыто администратору
 * направления. Это не запрещено — это решение того, кто правит.
 *
 * ЧТО НЕЛЬЗЯ ЗАБРАТЬ. Ровно одна клетка: `roles` у Владельца. Забрав её,
 * человек закрывает единственную дверь, из которой правится сама карта, — и
 * вернуть её будет нечем, кроме правки базы руками. Остальное обратимо: даже
 * потеряв настройки и деньги, Владелец через `roles` вернёт себе всё.
 */
final class RoleAccessOverrides
{
    public const SETTING_KEY = 'admin.role_access';

    /** Клетки, которые нельзя выключить: роль → ключи. */
    public const LOCKED = [
        'owner' => ['roles'],
    ];

    /**
     * Ключи, которые нельзя выдать настройкой никому, кроме Владельца.
     *
     * `LOCKED` закрывает только одну половину: у Владельца `roles` не
     * отобрать. Выдать его модератору или администратору направления ничто не
     * мешало — а `allows()` спрашивает настройку раньше ранга, значит клетка
     * сработала бы. Получивший `roles` правит ту же карту и открывает себе
     * `monetization`, `users.manage`, `settings`: деньги и права.
     *
     * Запрет держится в двух местах нарочно — здесь и проверкой на Владельца в
     * `AdminRoleAccessController`. Обойти надо было бы оба.
     */
    public const OWNER_ONLY = ['roles'];

    /**
     * Ответ живёт один запрос.
     *
     * `allows()` зовётся на каждом охраняемом маршруте, а внутри одного
     * запроса их бывает несколько (middleware плюс проверки полей). Без
     * памятки это был бы запрос в базу на каждую проверку.
     *
     * Статика переживает запрос только под Octane; php-fpm поднимает процесс
     * заново. Это уже записано про `CdekReadiness` и здесь ровно так же.
     *
     * @var array<string, array<string, bool>>|null
     */
    private static ?array $память = null;

    /** Забыть запомненное — для проверок и после записи настройки. */
    public static function forget(): void
    {
        self::$память = null;
    }

    /** @return array<string, array<string, bool>> роль → ключ → открыт ли */
    public static function all(): array
    {
        if (self::$память !== null) {
            return self::$память;
        }

        $строка = SystemSetting::query()->where('key', self::SETTING_KEY)->value('value');

        return self::$память = self::очистить(is_array($строка) ? $строка : []);
    }

    /**
     * Решение по клетке: `true` — открыто, `false` — закрыто, `null` — в
     * настройке ничего нет, решает зашитая карта.
     */
    public static function decide(UserRole|string $role, string $key): ?bool
    {
        $имя = $role instanceof UserRole ? $role->value : $role;

        if (in_array($key, self::LOCKED[$имя] ?? [], true)) {
            return true;
        }

        $решение = self::all()[$имя][$key] ?? null;

        return is_bool($решение) ? $решение : null;
    }

    /**
     * Записать исключения. Принимает полную карту роли → ключ → bool и
     * оставляет только то, что отличается от зашитой карты.
     *
     * Свёртка к отличиям — не экономия места, а то, ради чего настройка
     * разреженная: иначе первая же запись заморозила бы всю карту в базе, и
     * следующая правка `AdminAccess::SECTIONS` в коде ничего бы не изменила,
     * потому что настройка перебивала бы её по всем ключам.
     *
     * @param  array<string, array<string, bool>>  $карта
     * @return array<string, array<string, bool>> что легло в настройку
     */
    public static function store(array $карта): array
    {
        $исключения = [];

        foreach (self::очистить($карта) as $роль => $ключи) {
            foreach ($ключи as $ключ => $открыт) {
                if (in_array($ключ, self::LOCKED[$роль] ?? [], true)) {
                    // Запертую клетку не пишем ни в каком виде: она всегда да.
                    continue;
                }
                if ($открыт && $роль !== 'owner' && in_array($ключ, self::OWNER_ONLY, true)) {
                    // Выдать такой ключ настройкой нельзя; снять — можно,
                    // зашитая карта его этим ролям и так не даёт.
                    continue;
                }
                if ($открыт === self::поЗашитой($роль, $ключ)) {
                    continue;
                }
                $исключения[$роль][$ключ] = $открыт;
            }
        }

        SystemSetting::query()->updateOrCreate(
            ['key' => self::SETTING_KEY],
            ['value' => $исключения, 'group' => 'roles'],
        );

        self::forget();

        return $исключения;
    }

    /** Что говорит зашитая карта: ступень роли не ниже объявленной. */
    public static function поЗашитой(UserRole|string $role, string $key): bool
    {
        $нужно = AdminAccess::sectionLevels()[$key] ?? AdminAccess::serviceLevels()[$key] ?? null;

        return $нужно !== null && AdminAccess::rankOf($role) >= AdminAccess::rankOf($нужно);
    }

    /**
     * Полная карта для показа и для правки: роль → ключ → открыт ли.
     *
     * Собирается из зашитой карты и исключений, то есть отвечает на вопрос
     * «как сейчас», а не «что переопределено». Именно её показывает админка,
     * и именно её она присылает обратно.
     *
     * @return array<string, array<string, bool>>
     */
    public static function effective(): array
    {
        $карта = [];

        foreach ([UserRole::Owner, UserRole::Moderator, UserRole::CategoryAdmin] as $роль) {
            foreach (AdminAccess::keys() as $ключ) {
                $карта[$роль->value][$ключ] = self::decide($роль, $ключ)
                    ?? self::поЗашитой($роль, $ключ);
            }
        }

        return $карта;
    }

    /**
     * Выбросить то, чего не бывает: чужие роли и неизвестные ключи.
     *
     * Настройка живёт в `system_settings`, а туда пишет не только этот код.
     * Неизвестный ключ, оставшийся от переименования раздела, не должен ни
     * открывать доступ, ни ронять проверку.
     *
     * @param  array<mixed>  $сырое
     * @return array<string, array<string, bool>>
     */
    private static function очистить(array $сырое): array
    {
        $роли = ['owner', 'moderator', 'category_admin'];
        $ключи = AdminAccess::keys();
        $чисто = [];

        foreach ($сырое as $роль => $ключиРоли) {
            if (! in_array($роль, $роли, true) || ! is_array($ключиРоли)) {
                continue;
            }
            foreach ($ключиРоли as $ключ => $значение) {
                if (! in_array($ключ, $ключи, true) || ! is_bool($значение)) {
                    continue;
                }
                $чисто[$роль][$ключ] = $значение;
            }
        }

        return $чисто;
    }
}
