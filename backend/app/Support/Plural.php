<?php

namespace App\Support;

/**
 * Русское склонение по числу — одно на весь бэкенд.
 *
 * Было заведено приватным методом в `ReferralService`, и при второй
 * надобности (сообщение «не хватает N баллов») я чуть не написал такое же
 * рядом. Правило 11–14 переписывают по памяти и ошибаются на нём чаще
 * всего: «11 балл» выглядит опечаткой, а это несклонённое число.
 *
 * Падеж помощник не выбирает — его выбирает место вызова тремя словами.
 * «Начислено 2 балла», но «не хватает 2 баллов»: одно и то же число, разные
 * формы, и сводить их к одному набору значило бы испортить одно из двух.
 */
final class Plural
{
    public static function склонение(int $n, string $одна, string $две, string $пять): string
    {
        $сто = abs($n) % 100;
        $десять = $сто % 10;

        if ($сто >= 11 && $сто <= 14) {
            return $пять;
        }
        if ($десять === 1) {
            return $одна;
        }
        if ($десять >= 2 && $десять <= 4) {
            return $две;
        }

        return $пять;
    }

    /** «1 балл», «2 балла», «5 баллов» — именительный, для «начислено N …». */
    public static function баллы(int $n): string
    {
        return self::склонение($n, 'балл', 'балла', 'баллов');
    }

    /** «одного балла», «двух баллов» — родительный, для «не хватает N …». */
    public static function балловРодительный(int $n): string
    {
        return self::склонение($n, 'балла', 'баллов', 'баллов');
    }
}
