<?php

namespace App\Support;

/**
 * Клетка выгрузки не исполняется как формула.
 *
 * Выгрузки сделок и платежей кладут в CSV пользовательский текст:
 * название объявления, имя покупателя и продавца, описание платежа.
 * Эксель и его родня считают формулой всё, что начинается с `=`, `+`,
 * `-`, `@`, а также с табуляции и возврата каретки, — и считают её при
 * открытии файла, без всякого подтверждения.
 *
 * То есть объявление с названием `=HYPERLINK("http://…";"Счёт")`
 * превращалось в ссылку в таблице администратора, а
 * `=1+1` — в число 2 вместо названия. Это и есть внедрение формулы
 * (CSV injection): текст одного человека исполняется на машине другого,
 * причём того, у кого права.
 *
 * Выгрузку открывает только администрация, но текст в неё приносят
 * пользователи, и это ровно тот случай, когда «доступно только своим»
 * защитой не является.
 *
 * Как чинится. Перед опасным первым символом ставится апостроф —
 * единственный приём, который понимают и Excel, и LibreOffice, и
 * Google Sheets: содержимое остаётся прежним, формулой не становится.
 * Апостроф в самой таблице не показывается.
 *
 * Чего здесь нарочно нет: экранирования кавычек и разделителей. Это
 * работа `fputcsv`, и дублировать её значило бы ломать поля с точкой
 * с запятой внутри.
 */
final class CsvCell
{
    /**
     * Символы, с которых начинается формула.
     *
     * Табуляция и возврат каретки в списке не для красоты: Excel
     * пропускает их и смотрит на следующий символ, то есть
     * `"\t=1+1"` исполняется так же, как `"=1+1"`.
     */
    private const ОПАСНЫЕ = ['=', '+', '-', '@', "\t", "\r"];

    /**
     * Обычное число формулой не считается.
     *
     * Без этого исключения апостроф доставался бы каждой отрицательной
     * сумме: `-150` начинается с минуса. В бухгалтерской выгрузке это
     * прямой вред — столбец перестаёт складываться в таблице, а
     * пришли за ним именно затем, чтобы складывать.
     *
     * Запятая в образце не для красоты: суммы здесь форматируются
     * `number_format(..., 2, ',', '')`, то есть `-1234,56`.
     */
    private const ЧИСЛО = '/^[+-]?\d+(?:[.,]\d+)?$/';

    public static function safe(mixed $value): string
    {
        $текст = (string) ($value ?? '');

        if ($текст === '') {
            return '';
        }

        if (! in_array($текст[0], self::ОПАСНЫЕ, true)) {
            return $текст;
        }

        return preg_match(self::ЧИСЛО, $текст) === 1 ? $текст : "'".$текст;
    }

    /**
     * Строка целиком.
     *
     * Удобство не единственная причина: проходя по всей строке, легко
     * не забыть новый столбец. Числа и даты через `safe()` проходят
     * без изменений — опасен только первый символ, а у них он цифра.
     *
     * Отрицательные суммы проходят без апострофа — см. `ЧИСЛО` выше.
     *
     * @param  array<int, mixed>  $cells
     * @return array<int, string>
     */
    public static function row(array $cells): array
    {
        return array_map(static fn (mixed $c): string => self::safe($c), $cells);
    }
}
