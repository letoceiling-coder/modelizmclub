    /** Сколько людей в каждом состоянии — для отчёта сухого прогона. */
    public static function byState(): array
    {
        $phone = $sub = $expired = $plain = 0;
        foreach (self::roster() as $p) {
            $hasPhone = in_array(self::PHONE, $p['flags'], true);
            $hasPhone ? $phone++ : $plain++;
            in_array(self::SUB_ACTIVE, $p['flags'], true) && $sub++;
            in_array(self::SUB_EXPIRED, $p['flags'], true) && $expired++;
        }

        return ['всего' => count(self::roster()), 'с телефоном' => $phone, 'без телефона' => $plain, 'с подпиской' => $sub, 'подписка истекла' => $expired];
    }
