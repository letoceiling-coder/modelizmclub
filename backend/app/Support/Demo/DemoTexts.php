<?php

namespace App\Support\Demo;

/**
 * Тексты демо-набора.
 *
 * ТРИ ДЛИНЫ НЕ ДЛЯ КРАСОТЫ. Карточка ленты сворачивает длинный текст кнопкой
 * «Показать ещё», и порог срабатывания проверяется только текстом, который
 * его переходит. Короткий — одна строка, средний — абзац, длинный — заведомо
 * выше порога.
 *
 * ПЕРВАЯ СТРОКА — пометка. Записи публичные и видны живым людям; они должны
 * понимать, что читают витрину, а не участника клуба.
 */
final class DemoTexts
{
    /** @return list<string> */
    public static function titles(string $direction): array
    {
        $common = [
            'Сборка идёт: показываю этап',
            'Разбор набора перед началом',
            'Что получилось после покраски',
            'Мелкие детали крупным планом',
            'Ошибки, которые я повторяю',
            'Инструмент, который выручает',
            'Сравнил два подхода к шву',
            'Финал: собрал и поставил на полку',
        ];

        return array_map(fn (string $t): string => $t.' · '.$direction, $common);
    }

    /** Короткий текст — одна мысль. */
    public static function short(string $seed): string
    {
        $variants = [
            'Сегодня только грунт. Дальше посмотрим, как ляжет база.',
            'Нашёл в запасах набор, про который забыл. Беру в работу.',
            'Расшивку восстановил, теперь можно красить.',
            'Пару часов на маскировку — и наконец видно результат.',
            'Собрал на скорую руку, для примерки. Потом переделаю.',
        ];

        return $variants[abs(crc32($seed)) % count($variants)];
    }

    /** Средний — абзац, который помещается в карточку целиком. */
    public static function medium(string $seed): string
    {
        $variants = [
            "Основную сборку закончил, остались мелочи. Стыки крыла пришлось шпатлевать дважды: первый раз поленился и зашкурил слишком рано, усадка вылезла уже под грунтом.\n\nДальше по плану база, смывка и декали. Декали в этом наборе тонкие, рву их регулярно, поэтому режу по одной.",
            "Красил в три слоя с промежуточной сушкой. Первый слой лёг пятнами — виноват грунт, положил его слишком толсто.\n\nСмывку делаю маслом, разведённым уайт-спиритом: она даёт мягкий переход и не съедает базу, если не торопиться.",
            "Купил набор травления и понял, что половину деталей поставить некуда — они от другой модификации. Такое бывает, читайте инструкцию до покупки.\n\nЧто встало, то встало хорошо: решётки и ремни сразу дают другой вид.",
        ];

        return $variants[abs(crc32($seed)) % count($variants)];
    }

    /** Длинный — заведомо выше порога сворачивания. */
    public static function long(string $seed): string
    {
        $parts = [
            'Расскажу подробно, потому что меня несколько раз спрашивали в комментариях, как я делаю переходы на камуфляже.',
            'Сначала база: кладу самый светлый тон и даю ему высохнуть хотя бы сутки. Спешка здесь стоит дорого — свежая краска тянется под маской и оставляет рваный край.',
            'Маски режу из виниловой плёнки, а не из скотча: плёнка тянется и лучше садится на двойную кривизну. На плоских панелях разницы нет, а на капоте и на обтекателе — есть.',
            'Второй тон кладу в два прохода с разбавлением примерно один к одному. Давление ставлю ниже обычного: так пятно мягче, и на границе не появляется валик.',
            'Дальше — сутки на просушку и только потом лак. Лак под декали обязателен, иначе плёнка ляжет на матовую поверхность и даст серебрение, которое уже ничем не убрать.',
            'Смывку веду по одной панели, лишнее снимаю ватной палочкой сразу, не дожидаясь высыхания. Если передержать, остаются круги, и приходится перекрывать лаком заново.',
            'В финале — матовый лак и лёгкая сухая кисть по кромкам. Всё вместе занимает неделю вечеров, и это нормальный темп, если не гнаться за скоростью.',
        ];

        $offset = abs(crc32($seed)) % 3;

        return implode("\n\n", array_slice($parts, $offset, 6));
    }

