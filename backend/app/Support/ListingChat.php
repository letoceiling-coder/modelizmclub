<?php

namespace App\Support;

use App\Enums\ConversationType;
use App\Enums\ListingStatus;
use App\Models\Conversation;
use App\Models\Listing;
use App\Models\User;

/**
 * Переписка по объявлению — решение Ж3 от 09.10.
 *
 * «Написать продавцу» из объявления доступно любому вошедшему: ни дружбы, ни
 * подписки не требуется. До 09.10 этот путь шёл по общему правилу личной
 * переписки (дружба либо подписка), и покупатель, который хотел спросить про
 * товар, получал шторку «Добавьте пользователя в друзья, чтобы написать ему».
 * Чтобы задать вопрос о цене, надо было подружиться с незнакомым человеком.
 *
 * Правило живёт здесь, а не в политике, потому что спрашивают его трое:
 * политика (можно ли начать и можно ли писать), контроллер создания
 * переписки (нужен ли подтверждённый телефон) и контроллер отправки
 * сообщения. Три копии одного условия разошлись бы — так уже было с правилом
 * дружбы, которое до 05.10 жило в интерфейсе и на сервере по-разному.
 *
 * **Что считается объявлением, по которому можно написать.** Опубликованное
 * и принадлежащее получателю. Черновик, снятое, проданное, отклонённое,
 * ожидающее модерации — нельзя: иначе через `listing_uuid` можно было бы
 * заговорить с кем угодно, подставив любой идентификатор (пункт 4 решения).
 *
 * **Переписка остаётся открытой после снятия объявления** (пункт 3 решения):
 * `isListingConversation` смотрит на `listing_id` беседы, а не на состояние
 * объявления. Продавец снял товар — разговор не обрывается на полуслове.
 */
final class ListingChat
{
    /**
     * Объявление, по которому можно начать переписку с этим продавцом.
     *
     * Проверяется и статус, и владелец: без второго условия достаточно было
     * бы знать uuid любого опубликованного объявления, чтобы написать любому
     * человеку в обход правила дружбы.
     */
    public static function isOpenFor(?Listing $listing, ?User $seller): bool
    {
        if ($listing === null || $seller === null) {
            return false;
        }

        return $listing->status === ListingStatus::Published
            && (int) $listing->user_id === (int) $seller->id;
    }

    /** Эта переписка привязана к объявлению. */
    public static function isListingConversation(Conversation $conversation): bool
    {
        return $conversation->type === ConversationType::Direct
            && $conversation->listing_id !== null;
    }
}
