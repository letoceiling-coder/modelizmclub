<?php

namespace App\Console\Concerns;

use Illuminate\Console\ConfirmableTrait;

/**
 * Предохранитель для команд, которые пишут в данные руками.
 *
 * ЗАЧЕМ. Аудит 03.10 нашёл три команды, меняющие данные без единой защиты:
 * `app:stress-test` (150 учёток и настоящие файлы в объектное хранилище,
 * `--fresh` всё это стирает), `app:simulate-activity` (в своём докблоке
 * названа пригодной «for production smoke testing») и
 * `communities:sync-owners` (массовый UPDATE без сухого прогона). Ни у одной
 * из 36 команд проекта не было проверки окружения вовсе.
 *
 * Это та же защита, что появилась после запуска phpunit по боевой базе
 * 13.09 — `TestCase::assertEnvironmentIsSafeForTests()`. Там проверка стоит
 * до первой миграции и бросает исключение, а не мягко завершает: остановиться
 * надо целиком, пока ничего не сделано. Здесь так же.
 *
 * ТРИ МЕРЫ, и каждая закрывает свой случай:
 *
 *   refuseOnProduction()  — команду нельзя запускать на проде никогда.
 *                           Флага обхода нет намеренно: флаг, который есть,
 *                           рано или поздно наберут.
 *   writesOnlyWithApply() — команду на проде запускать можно, но сначала
 *                           показать. Без `--apply` только отчёт.
 *   confirmWrite()        — перед записью спросить. В неинтерактивном
 *                           режиме пропускает только по `--force`.
 *
 * ГРАНИЦА. Трейт — для команд, которые запускает человек. Командам из
 * расписания сухой прогон по умолчанию ставить нельзя: `posts:publish-scheduled`
 * и двенадцать её соседей тогда молча перестанут работать, и узнать об этом
 * будет не по чему. Расписание — в `routes/console.php`; что должно носить
 * трейт, перечислено в `tests/Feature/CommandWriteGuardsTest.php`, иначе
 * правило через месяц станет записью о намерении.
 */
trait GuardsDataWrites
{
    use ConfirmableTrait;

    /**
     * Отказ на боевом окружении. Возвращает false, если бежать нельзя.
     *
     * Проверяется окружение приложения, а не имя базы: команда трогает не
     * только базу — `app:stress-test` заливает файлы в объектное хранилище,
     * `app:simulate-activity` ходит через настоящие сервисы, а те шлют
     * письма и SMS.
     */
    protected function refuseOnProduction(): bool
    {
        if (! app()->environment('production')) {
            return true;
        }

        $this->components->error(
            'Команда '.$this->getName().' не запускается на боевом окружении (APP_ENV=production).'
        );
        $this->line('  Она создаёт учётные записи, содержимое и файлы в хранилище через настоящие сервисы.');
        $this->line('  Нужен прогон по живому — делайте его на отдельной базе и отдельном бакете.');

        return false;
    }

    /**
     * Сухой прогон по умолчанию: писать только по `--apply`.
     *
     * Почему `--apply`, а не `--dry-run` со значением по умолчанию: в проекте
     * `--dry-run` стоит у тринадцати команд и означает «сегодня не пиши» при
     * записи по умолчанию. Сделать его включённым по умолчанию — значит
     * завести два флага на одной оси и гадать, какой сильнее. `--apply`
     * уже есть у четырёх команд ровно в этом смысле, в том числе у
     * `moderation:reconcile-queue`.
     */
    protected function writesOnlyWithApply(): bool
    {
        return (bool) $this->option('apply');
    }

    /**
     * Подтверждение перед записью.
     *
     * Через `ConfirmableTrait`, а не свой `confirm()`: он сам пропускает
     * вызов при `--force` и при `--no-interaction`, то есть команда остаётся
     * пригодной для скрипта, но молча записать по невнимательности не выйдет.
     *
     * Второй довод — `fn () => true` — обязателен. По умолчанию
     * `confirmToProceed()` спрашивает **только на боевом окружении**, а
     * команда, которая на проде не запускается вовсе (см. выше), тогда не
     * спросит никогда и проверку подтверждения нельзя будет даже написать.
     * Спрашиваем всегда; в скрипте — `--force`.
     *
     * Зовётся только когда запись действительно будет: спрашивать на сухом
     * прогоне — учить отвечать «да» не читая.
     */
    protected function confirmWrite(string $что): bool
    {
        return $this->confirmToProceed($что, fn (): bool => true);
    }
}
