<?php

namespace App\Console\Commands;

use App\Models\PromoPool;
use Illuminate\Console\Command;

/**
 * Закрывает акции, у которых вышел срок или кончились места.
 *
 * ПОЧЕМУ КОМАНДА, ЕСЛИ СОСТОЯНИЕ И ТАК СЧИТАЕТСЯ. `PromoPool::state()`
 * отвечает по датам на лету, и выдача мест уже не зависит от этой команды:
 * `scopeGranting` сам не берёт акции, которые не начались или кончились.
 * То есть автоматический старт и завершение работают и без планировщика —
 * это важно, потому что планировщик однажды простоял сутки на замке
 * `withoutOverlapping`, и завязывать на него доступ к деньгам нельзя.
 *
 * Команда делает другое: проставляет `completed_at`. Без неё закончившаяся
 * акция вечно оставалась бы «с пустым `completed_at`», и вопрос «когда она
 * закрылась» пришлось бы отвечать датой окончания, которая могла и не
 * наступить — места кончились раньше срока.
 *
 * СТАРТ НЕ ТРЕБУЕТ ОТМЕТКИ. Акция начинается тем, что `starts_at` оказался
 * в прошлом; писать сюда ещё и «started_at» значило бы завести вторую
 * правду о том же моменте.
 */
class SyncPromoPoolsCommand extends Command
{
    protected $signature = 'promo:sync-pools';

    protected $description = 'Отмечает завершённые акции: вышел срок или кончились места';

    public function handle(): int
    {
        $закрыто = 0;

        PromoPool::query()
            ->whereNull('completed_at')
            ->orderBy('id')
            ->chunkById(200, function ($акции) use (&$закрыто): void {
                foreach ($акции as $акция) {
                    $срокВышел = $акция->expires_at !== null && $акция->expires_at->lte(now());
                    $местКончились = $акция->seatsLeft() <= 0;

                    if (! $срокВышел && ! $местКончились) {
                        continue;
                    }

                    /*
                     * Время закрытия — не `now()`, а момент, когда акция на
                     * самом деле кончилась: если срок вышел позавчера, а
                     * команда добралась сегодня, писать сегодняшнее число
                     * значило бы соврать про два дня.
                     */
                    $акция->forceFill([
                        'completed_at' => $срокВышел ? $акция->expires_at : now(),
                    ])->save();

                    $закрыто++;
                    $this->line("  закрыта: {$акция->name}".($срокВышел ? ' (вышел срок)' : ' (кончились места)'));
                }
            });

        $this->info("promo:sync-pools: закрыто акций — {$закрыто}");

        return self::SUCCESS;
    }
}
