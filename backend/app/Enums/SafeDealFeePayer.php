<?php

namespace App\Enums;

/**
 * Кто платит комиссию безопасной сделки.
 *
 * До 27.09 комиссия вычиталась из выплаты продавцу: товар 1 000 ₽ — покупатель
 * платил 1 000, продавец получал 950. Заказчик решил иначе: безопасную сделку
 * выбирает покупатель, значит и платит он, а продавец получает ровно ту цену,
 * которую указал в объявлении.
 *
 * СТАРЫЕ СДЕЛКИ НЕ ПЕРЕСЧИТЫВАЮТСЯ — прямое требование заказчика. Значит в
 * базе одновременно живут две схемы, и различать их надо по самой строке.
 *
 * Почему отдельной колонкой, а не иначе:
 *
 * — **по дате** ненадёжно: сделка, созданная до выкатки и завершённая после,
 *   попадает в обе половины, а восстановление базы или перенос строк
 *   разрушает соответствие «дата → правило» окончательно;
 * — **по пустоте новых колонок** нельзя: `item_kopecks` заполняется и для
 *   старых сделок — цена товара лежала в `metadata.item_kopecks` с самого
 *   начала, и не перенести её значило бы потерять величину, которая есть;
 * — **по арифметике** (сходится ли `amount = item + fee + delivery`) — вывод,
 *   а не факт: при нулевой комиссии обе схемы дают одно и то же, и строка
 *   перестала бы отвечать, по какому правилу её считали.
 *
 * Колонка называет ровно то, что изменилось, и остаётся читаемой в выгрузке
 * для бухгалтерии: без неё столбец «комиссия» в CSV означал бы то одно, то
 * другое, а правило различения жило бы в выгрузке.
 */
enum SafeDealFeePayer: string
{
    /** Комиссия вычтена из выплаты продавцу — схема до 27.09.2026. */
    case Seller = 'seller';

    /** Комиссия прибавлена к сумме покупателя — схема с 27.09.2026. */
    case Buyer = 'buyer';

    public function label(): string
    {
        return match ($this) {
            self::Seller => 'из выплаты продавцу',
            self::Buyer => 'покупатель при оформлении',
        };
    }
}
