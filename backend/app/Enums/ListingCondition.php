<?php

namespace App\Enums;

/**
 * Состояние товара в объявлении: новое или бывшее в употреблении.
 *
 * Хранится латиницей, а показывается по-русски. Причина не в стиле: карточка
 * каталога переводится на три языка, и русская подпись в базе сделала бы
 * английскую версию наполовину русской. Подпись живёт в словаре фронта,
 * `label()` остаётся для выгрузок и админки.
 */
enum ListingCondition: string
{
    case New = 'new';
    case Used = 'used';

    public function label(): string
    {
        return match ($this) {
            self::New => 'Новое',
            self::Used => 'Б/у',
        };
    }
}
