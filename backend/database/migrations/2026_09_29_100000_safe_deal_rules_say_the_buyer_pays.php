    }

    /** @param array<string, string> $замены */
    private function применить(array $замены): void
    {
        $page = LegalPage::query()->where('slug', self::SLUG)->first();

        if (! $page) {
            echo "  правила сделки: страницы «".self::SLUG."» нет — пропускаем\n";

            return;
        }

        $html = (string) $page->content_html;
        $сделано = 0;
        $пропущено = [];

        foreach ($замены as $было => $стало) {
            if (! str_contains($html, $было)) {
                // Уже исправлено или переписано руками — не трогаем.
                if (! str_contains($html, $стало)) {
                    $пропущено[] = mb_substr($было, 0, 70).'…';
                }

                continue;
            }

            $html = str_replace($было, $стало, $html);
            $сделано++;
        }

        foreach ($пропущено as $фраза) {
            echo "  правила сделки: НЕ НАЙДЕНО — {$фраза}\n";
        }

        if ($сделано === 0) {
            echo "  правила сделки: менять нечего\n";

            return;
        }

        // Прежняя редакция — в версии, чтобы правку можно было откатить
        // из админки, а не только миграцией.
        app(LegalPageContentService::class)->snapshot($page, null);

        $page->forceFill([
            'content_html' => $html,
            'version' => (int) $page->version + 1,
            'published_at' => now(),
        ])->save();

        echo "  правила сделки: заменено мест — {$сделано}, версия {$page->version}\n";
    }
