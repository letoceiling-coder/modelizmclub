    /** @param array<string, string> $замены */
    private function применить(array $замены): void
    {
        /*
         * Замена считается несделанной, только если в правилах нет **ни**
         * прежней формулировки, ни новой.
         *
         * На чистой установке текст сразу новый — его кладёт сидер, — и
         * сообщать не о чем. Первая редакция этого кода печатала три строки
         * на каждом прогоне тестов с `RefreshDatabase`, то есть приучала не
         * читать вывод миграций. Проверено: на пустой таблице и на свежем
         * сидере теперь тихо.
         */
        $несделанные = $замены;

        foreach (RulePageSection::query()->lazyById() as $section) {
            $было = (string) $section->content;
            $стало = $было;

            foreach ($замены as $откуда => $куда) {
                if (str_contains($стало, $откуда)) {
                    $стало = str_replace($откуда, $куда, $стало);
                }
                if (str_contains($стало, $куда)) {
                    unset($несделанные[$откуда]);
                }
            }

            if ($стало !== $было) {
                $section->forceFill(['content' => $стало])->save();
            }
        }

        app(RulePageService::class)->forgetCache();

        foreach (array_keys($несделанные) as $откуда) {
            /*
             * Формулировку могли поправить из админки. Подменять чужую
             * редакцию юридического текста нельзя, но и молчать нельзя:
             * выкатка должна показать, что пункт остался прежним.
             */
            echo "  правила: формулировка не найдена, замена пропущена — \"{$откуда}\"\n";
        }
    }
};
