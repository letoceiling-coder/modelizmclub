 * Пункт 2.2 не трогаем — он и раньше говорил, что покупатель оплачивает
 * стоимость товара **и** комиссию, то есть уже описывал новую схему.
 *
 * ПОЧЕМУ ЗАМЕНА ПО ТОЧНОМУ СОВПАДЕНИЮ. Текст правил правят и из админки. Если
 * формулировка уже другая — миграция не трогает ничего: подменить чужую
 * редакцию юридического текста хуже, чем не выполнить замену. Несделанные
 * замены печатаются, чтобы это не прошло молча.
 *
 * Сравнение и замена — в PHP, а не `like` по базе: кириллица в SQL-строке
 * сворачивается экранированием, и условие молча не совпадает ни с чем.
