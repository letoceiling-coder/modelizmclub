use Modules\Catalog\Services\CategoryTaxonomyService;

/**
 * Узел третьего уровня «ил 6» получает имя «Ил-6».
 *
 * ЧТО НАШЛА ПРИЁМКА 27.09. Цепочка Авиация → Планеры → «ил 6»
 * (1 → 141 → 140) — единственная тройка, чей последний узел назван
 * строчными буквами и с пробелом вместо дефиса. Соседи по уровню названы
 * иначе: «Автопилоты», «Эхолоты», «Багги и трагги», «Краулеры»,
 * «Шоссейные». Видно, что узел заведён руками при проверке и остался.
 *
 * ПОЧЕМУ ПЕРЕИМЕНОВАНИЕ, А НЕ УДАЛЕНИЕ. В задании стояло «убрать узел», и
 * сперва так и задумывалось. Но на узле висит содержимое, и внешние ключи
 * посчитаны по схеме, а не на глаз:
 *
 *   `posts.category_id`                     → cascade on delete
 *   `community_topic_categories`            → cascade on delete
 *   `category_admins.post_category_id`      → cascade on delete
 *   `conversations.post_category_id`        → null on delete
 *
 * То есть удаление строки унесло бы с собой **обе записи узла** (приёмка
 * насчитала две, и обе показываются в выдаче «Авиации»), а комната чата
 * этого уровня осталась бы без категории — висящей беседой, которую никто
 * не найдёт. Двухминутной правкой это быть перестаёт, а необратимой
 * становится. Имя же — ровно то, что в узле неправильно.
 *
 * Если узел всё-таки надо убрать, это отдельная миграция: записи сперва
 * переносятся на родителя («Планеры»), комната закрывается, и только потом
 * удаляется строка.
 *
 * ПРО ИМЯ. В чек-листе узел назван «ИЛ-6» заглавными. Обозначение машины
 * пишется «Ил-6», и соседи по уровню — тоже с заглавной только первой
 * буквой, поэтому здесь «Ил-6».
 *
 * ЕСЛИ УЗЛА НЕТ. Миграция молчит, а не падает: имя правится и из админки,
 * и к моменту выкатки его могли поправить руками. Искать по имени, а не по
 * идентификатору 140, — по той же причине.
 */
return new class extends Migration
{
    private const БЫЛО = 'ил 6';

    private const СТАЛО = 'Ил-6';

    public function up(): void
    {
        $this->переименовать(self::БЫЛО, self::СТАЛО);
    }

    public function down(): void
    {
        $this->переименовать(self::СТАЛО, self::БЫЛО);
    }

    private function переименовать(string $было, string $стало): void
    {
        $узел = PostCategory::query()->where('name', $было)->first();

        if ($узел === null) {
            return;
        }

        $узел->forceFill(['name' => $стало])->save();

        /*
         * Имя лежит ещё в двух деревьях — зеркалах в `listing_categories` и
         * `community_categories`. Сведение делает `syncFromPostCategory`, оно
         * же сбрасывает кеш справочников: без сброса переименование
         * приложению не видно, дерево отдаётся из кеша.
         */
        app(CategoryTaxonomyService::class)->syncFromPostCategory($узел);
    }
};
