    public function run(): void
    {
        foreach ($this->documents() as $i => $doc) {
            $page = RulePage::query()->firstOrCreate(
                ['slug' => $doc['slug']],
                [
                    'title' => $doc['title'],
                    'seo_title' => $doc['seo_title'],
                    'seo_description' => $doc['seo_description'],
                    'summary' => $doc['summary'],
                    'status' => LegalPageStatus::Published,
                    'version' => 1,
                    'sort' => ($i + 1) * 10,
                    'published_at' => now(),
                ],
            );

            if ($page->sections()->exists()) {
                continue;
            }

            foreach ($doc['sections'] as $position => $section) {
                $page->sections()->create([
                    'type' => $section['type'],
                    'title' => $section['title'] ?? null,
                    'content' => $section['content'],
                    'position' => $position,
                    'is_visible' => true,
                ]);
            }
        }

        app(RulePageService::class)->forgetCache();

        FooterLink::query()->firstOrCreate(
            ['group' => 'legal', 'target_value' => '/rules'],
            [
                'label' => 'Правила',
                'target_type' => 'internal',
                'sort' => 5,
                'is_visible' => true,
            ],
        );

        if (DB::table('footer_links')->where('target_value', '/rules/safe-deal')->exists()) {
            DB::table('footer_links')->where('target_value', '/safe-deal')->delete();
        } else {
            DB::table('footer_links')->where('target_value', '/safe-deal')->update([
                'target_value' => '/rules/safe-deal',
                'label' => 'Безопасная сделка',
            ]);
        }
    }

