    private function p(string $text): string
    {
        return '<p>'.e($text).'</p>';
    }

    /** @param list<string> $paragraphs */
    private function ps(array $paragraphs): string
    {
        return implode('', array_map(fn (string $p) => $this->p($p), $paragraphs));
    }

    /** @param list<string> $items */
    private function ul(array $items): string
    {
        return '<ul>'.implode('', array_map(fn (string $i) => '<li>'.e($i).'</li>', $items)).'</ul>';
    }

    /** @param list<string> $chunks */
