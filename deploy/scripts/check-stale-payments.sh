#!/usr/bin/env bash
#
# Платежи, которые сверка больше никогда не тронет.
#
# `payments:reconcile-pending` в расписании получает `--newer-than=1440`, то
# есть смотрит только платежи моложе суток. Верхняя граница там не лишняя:
# опрашивать банк про заказы годичной давности незачем, а песочница ВТБ 08.09
# отсекла залп из сорока семи запросов. Но у границы есть следствие, которого
# никто не заметил: платёж, доживший до суток в `pending`, выпадает из
# внимания навсегда.
#
# Замерено на проде 03.10: четыре таких платежа висят с 11–12 августа,
# пятьдесят два дня. Два по 499 ₽ («Полгода» тогдашней цены), два по 99 ₽. Все
# четыре — заказы в песочнице (`vtb.rbsuat.com`), то есть денег за ними нет.
# Но узнать это можно было только запросом руками: ни один отчёт о них не
# говорил, и за полтора месяца о них не сказал никто.
#
# Проверка не чинит и не закрывает. Закрытие — изменение данных, и решать его
# должен человек: платёж мог быть оплачен, и тогда у человека полтора месяца
# нет подписки, за которую он заплатил. Проверка делает одно — не даёт этому
# быть невидимым.
#
# Ответов три: 0 — таких платежей нет, 1 — есть (имена и возраст в выводе),
# 2 — выяснить не удалось. Третье не «всё хорошо».
#
# Имена переменных латиницей: кириллица в именах ломает bash, и ломает молча.
set -uo pipefail

ROOT="${1:-/var/www/modelizmclub}"
BACKEND="${ROOT}/backend"

if [[ ! -f "${BACKEND}/artisan" ]]; then
  echo "stale-payments: ${BACKEND} не похож на приложение — выяснить не удалось" >&2
  exit 2
fi

OUT="$(cd "${BACKEND}" && php artisan tinker --execute='
$окно = (int) config("billing.auto_poll.newer_than_minutes", 1440);
$граница = now()->subMinutes($окно);
$строки = \App\Models\Payment::query()
    ->where("status", "pending")
    ->where("created_at", "<", $граница)
    ->orderBy("created_at")
    ->get();
echo "ОКНО\t".$окно."\n";
echo "ВСЕГО\t".$строки->count()."\n";
foreach ($строки as $p) {
    echo "ПЛАТЁЖ\t".$p->id."\t".$p->provider."\t".$p->amount_cents."\t"
        .(int) $p->created_at->diffInDays(now())."\t"
        .(($p->metadata["payable_type"] ?? "—"))."\t"
        .$p->created_at->toDateString()."\n";
}
' < /dev/null 2>/dev/null)"

if [[ -z "${OUT}" ]]; then
  echo "stale-payments: artisan ничего не ответил — выяснить не удалось" >&2
  exit 2
fi

WINDOW="$(printf '%s\n' "${OUT}" | awk -F'\t' '$1=="ОКНО"{print $2; exit}')"
TOTAL="$(printf '%s\n' "${OUT}" | awk -F'\t' '$1=="ВСЕГО"{print $2; exit}')"

# Нет строки «ВСЕГО» — значит замер не выполнился. Пустой вывод и ноль
# платежей выглядят одинаково, и путать их нельзя.
if [[ -z "${TOTAL}" ]]; then
  echo "stale-payments: в ответе нет итога — выяснить не удалось" >&2
  printf '%s\n' "${OUT}" | head -4 | sed 's/^/  /' >&2
  exit 2
fi

if [[ "${TOTAL}" == "0" ]]; then
  echo "stale-payments: ok — незакрытых платежей старше ${WINDOW} мин нет"
  exit 0
fi

echo "stale-payments: ${TOTAL} платеж(ей) в pending старше окна сверки (${WINDOW} мин)"
echo "                сверка в расписании их больше не тронет — --newer-than отсекает"
printf '%s\n' "${OUT}" | awk -F'\t' '$1=="ПЛАТЁЖ" {
  printf "  id %-6s %-9s %9.2f ₽  %4s дн  %s  от %s\n", $2, $3, $4/100, $5, $6, $7
}'
echo "                разобрать: php artisan payments:reconcile-pending --newer-than=0 --provider=vtb"
echo "                закрыть — отдельное решение: платёж мог быть оплачен"
exit 1
