#!/usr/bin/env bash
#
# Пустой обработчик отказа во фронтенде.
#
# `.catch(() => {})` — это отказ, стёртый без следа: запрос падает, состояние
# остаётся прежним, человек смотрит на пустой список или на «сохранено»,
# которого не случилось. Так «загрузка обзоров не удалась» выглядела как
# «обзоров нет», а объявление оставалось «в архиве» на экране, оставаясь
# опубликованным на деле.
#
# 11.09 таких мест было 76; сейчас должно быть ноль. Вместо них — три
# помощника из frontend/src/lib/errors/handle.ts: сказать пользователю,
# показать состояние с «Повторить», промолчать с указанной причиной.
#
# Почему не eslint. Правило там есть, но предупреждением: уровень у
# `no-restricted-syntax` один на все селекторы, и поднять его до ошибки
# значило бы сделать ошибками полторы тысячи предупреждений про точные px.
# Ворота — здесь, и падают на первом же вхождении.
set -uo pipefail

ROOT="${1:-$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)}"
SRC="${ROOT}/frontend/src"

if [[ ! -d "${SRC}" ]]; then
  echo "check-empty-catch: нет каталога ${SRC}" >&2
  exit 1
fi

# -a обязателен: в исходниках попадаются нулевые байты, и без него grep
# считает файл двоичным и молча не печатает ничего — пустой вывод выглядел
# бы как «ноль вхождений». См. CLAUDE.md, раздел про grep.
#
# Файл самого помощника исключён: там этот текст стоит в пояснении.
hits="$(grep -arnE '\.catch\(\s*\(\s*[A-Za-z_]*\s*\)\s*=>\s*\{\s*\}\s*\)' \
          --include='*.ts' --include='*.tsx' "${SRC}" \
        | grep -av 'src/lib/errors/handle.ts' || true)"

if [[ -n "${hits}" ]]; then
  count="$(printf '%s\n' "${hits}" | wc -l | tr -d ' ')"
  echo "check-empty-catch: пустых обработчиков отказа — ${count}"
  printf '%s\n' "${hits}" | sed "s|${ROOT}/||" | sed 's/^/  /'
  echo
  echo "  Возьмите reportActionFailure, reportReadFailure или ignoreFailure"
  echo "  из @/lib/errors/handle — три ответа на три случая."
  exit 1
fi

echo "check-empty-catch: пустых обработчиков отказа нет"
