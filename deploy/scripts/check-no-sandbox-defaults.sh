#!/usr/bin/env bash
#
# Денежный адрес не подставляется молча.
#
# В `config/billing.php` умолчанием адреса эквайринга была песочница ВТБ
# (`https://vtb.rbsuat.com/payment/rest`), а у выплат — `epa-ift-sbp.vtb.ru`
# и `test3.api.vtb.ru:8443`. Выглядело безобидно — «не настроил, значит не
# боевое», — а работало наоборот: контур с ключами и `enabled=true` считал
# себя настроенным и слал заказы в испытательный узел. На проде так прошло
# больше месяца; снаружи не видно ничем, платёж создаётся и возвращает
# ссылку на форму банка.
#
# Теперь у этих адресов умолчания нет вовсе, и `isConfigured()` без адреса
# отвечает false. Проверка сторожит, чтобы умолчание не вернулось: вписать
# «удобный» адрес обратно — правка в одну строку, и заметить её без
# проверки некому.
#
# Проверяется текст конфигурации, а не окружение: окружение смотрит
# `check-live-money.sh` на сервере, где есть `.env` и кеш конфигурации.
set -uo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
CONFIG="${ROOT}/backend/config/billing.php"

if [[ ! -f "${CONFIG}" ]]; then
  echo "no-sandbox-defaults: ${CONFIG} не найден" >&2
  exit 2
fi

# Запрещено не умолчание само по себе, а умолчание на испытательный узел.
#
# У ЮKassa умолчание `https://api.yookassa.ru/v3` — боевой адрес, у него
# одно значение, и подставлять его безвредно. Запрет «никаких умолчаний у
# денежных адресов» срабатывал бы и там, а запрет, который мешает по
# пустякам, за неделю превращается в привычку писать --no-verify.
#
# Ключи перечислены явно: общее правило «любой env со вторым аргументом»
# задело бы FRONTEND_URL и прочее безобидное.
MONEY_KEYS=(
  VTB_ACQUIRING_API_URL
  VTB_PAYOUT_OAUTH_URL
  VTB_PAYOUT_API_URL
  YOOKASSA_API_URL
)

# Признаки испытательного узла. Те же, что у check-live-money.sh, и это
# намеренное повторение: там читается окружение сервера, здесь — текст
# конфигурации, и общий файл для двух строк создал бы связь между
# проверками, которую пришлось бы сопровождать.
TEST_MARKERS='rbsuat|sandbox|-ift-|\.ift\.|ift-|test|uat\.|demo\.|stage\.|localhost|127\.0\.0\.1'

STATUS=0
for key in "${MONEY_KEYS[@]}"; do
  hits="$(grep -nE "env\(['\"]${key}['\"][[:space:]]*," "${CONFIG}" || true)"
  [[ -z "${hits}" ]] && continue
  while IFS= read -r line; do
    num="${line%%:*}"
    # Умолчание проверяется целиком: испытательный узел ищется в строке с
    # умолчанием, а не в адресе — разобрать PHP-выражение из bash нельзя,
    # и попытка была бы хуже честной грубости.
    if printf '%s' "${line}" | tr 'A-Z' 'a-z' | grep -Eq "${TEST_MARKERS}"; then
      echo "no-sandbox-defaults: ${key} по умолчанию уходит на испытательный узел — ${CONFIG}:${num}" >&2
      STATUS=1
    fi
  done <<< "${hits}"
done

# И отдельно: испытательный узел не должен стоять в значении нигде.
# Сопровождающему полезно видеть адрес песочницы в пояснении — но не в том,
# что подставится.
NARROW_HOSTS='rbsuat|epa-ift-sbp|test3\.api\.vtb'
while IFS= read -r line; do
  [[ -z "${line}" ]] && continue
  num="${line%%:*}"
  text="${line#*:}"
  # Комментарии в этом файле блочные: вертикальная черта, звёздочка, слеши.
  trimmed="$(printf '%s' "${text}" | sed -E 's/^[[:space:]]+//')"
  case "${trimmed}" in
    '|'*|'*'*|'//'*|'#'*|'/*'*) continue ;;
  esac
  echo "no-sandbox-defaults: испытательный узел в значении — ${CONFIG}:${num}: ${trimmed}" >&2
  STATUS=1
done <<< "$(grep -nE "${NARROW_HOSTS}" "${CONFIG}" || true)"

if [[ "${STATUS}" == "0" ]]; then
  echo "no-sandbox-defaults: ok — денежные адреса без умолчаний, испытательных узлов в значениях нет"
fi
exit "${STATUS}"
